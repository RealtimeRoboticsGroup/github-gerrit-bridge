// GrantRunAs gives the bridge group the global capabilities the bridge
// needs, and no more (design §7.1): Run As, which /submit, votes and
// mirrored edits use, and Stream Events. It is idempotent, and brings an
// older site in line: the bridge leaves Service Users, and the
// administrators' abandon and WIP grants move from All-Projects to
// project.
func (s *Server) GrantRunAs(ctx context.Context, project string) error {
	bridge, err := s.groupID(ctx, BridgeGroup)
	if err != nil {
		return err
	}
	admins, err := s.groupID(ctx, "Administrators")
	if err != nil {
		return err
	}
	allow := map[string]any{"rules": map[string]any{bridge: map[string]any{"action": "ALLOW"}}}
	if err := s.Admin.Do(ctx, http.MethodPost, "projects/All-Projects/access", map[string]any{
		"add": map[string]any{"GLOBAL_CAPABILITIES": map[string]any{"permissions": map[string]any{
			"runAs": allow, "streamEvents": allow,
		}}},
		"remove": map[string]any{"refs/*": map[string]any{"permissions": map[string]any{
			"abandon":        map[string]any{"rules": map[string]any{admins: map[string]any{}}},
			"toggleWipState": map[string]any{"rules": map[string]any{admins: map[string]any{}}},
		}}},
	}, nil); err != nil {
		return err
	}
	// The bridge never matches administrators to GitHub logins
	// (identity.never_groups), so it must see who they are: Gerrit hides
	// Administrators from non-members otherwise.
	if err := s.Admin.Do(ctx, http.MethodPut, "groups/Administrators/options", map[string]any{"visible_to_all": true}, nil); err != nil {
		return fmt.Errorf("making Administrators visible: %w", err)
	}
	err = s.Admin.Do(ctx, http.MethodDelete, "groups/"+url.PathEscape("Service Users")+"/members/github-bridge", nil, nil)
	if ge := (*gerrit.Error)(nil); err != nil && !(errors.As(err, &ge) && ge.Status == http.StatusNotFound) {
		return fmt.Errorf("leaving Service Users: %w", err)
	}
	// Administrators may abandon anyone's change through Administrate
	// Server, which Gerrit does not apply to a user the bridge acts as
	// (Run-As): closing a PR on GitHub, which abandons its change as the
	// closer, needs the explicit grant. AOS needs it too. The same for
	// toggling work in progress (a PR's draft state). Only on the bridged
	// project's branches: whoever the bridge acts as has them.
	return s.Admin.Do(ctx, http.MethodPost, "projects/"+url.PathEscape(project)+"/access", map[string]any{
		"add": map[string]any{"refs/heads/*": map[string]any{"permissions": map[string]any{
			"abandon":        map[string]any{"rules": map[string]any{admins: map[string]any{"action": "ALLOW"}}},
			"toggleWipState": map[string]any{"rules": map[string]any{admins: map[string]any{"action": "ALLOW"}}},
		}}},
	}, nil)
}

// ProjectExists reports whether project exists.
func (s *Server) ProjectExists(ctx context.Context, project string) (bool, error) {
	err := s.Admin.Do(ctx, http.MethodGet, "projects/"+url.PathEscape(project), nil, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status == http.StatusNotFound {
		return false, nil
	}
	return err == nil, err
}

// MirrorProject creates project, configured for the bridge, with the
// branch of a GitHub repository as its main: the starting point of a site
// that owns that repository's main from then on.
func (s *Server) MirrorProject(ctx context.Context, project, repoURL, token, branch string) error {
	if err := s.Admin.Do(ctx, http.MethodPut, "projects/"+url.PathEscape(project), map[string]any{"create_empty_commit": false}, nil); err != nil {
		return fmt.Errorf("project %s: %w", project, err)
	}
	if err := s.ConfigureProject(ctx, project); err != nil {
		return err
	}
	tmp, err := os.MkdirTemp(filepath.Dir(s.Site), "seed-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	git := func(env []string, args ...string) error {
		cmd := exec.CommandContext(ctx, "git", args...)
		cmd.Dir = tmp
		cmd.Env = append(append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_TERMINAL_PROMPT=0"), env...)
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("git %s: %w: %s", args[0], err, out)
		}
		return nil
	}
	cfgGH, envGH := gitmirror.HTTPCredentials("https://github.com", "x-access-token", token)
	cfgG, envG := gitmirror.HTTPCredentials(s.URL, "admin", s.Admin.Password)
	if err := git(nil, "init", "-q", "--bare"); err != nil {
		return err
	}
	if err := git(envGH, "-c", cfgGH[0], "fetch", "-q", repoURL, "+refs/heads/"+branch+":refs/heads/"+branch); err != nil {
		return err
	}
	return git(envG, "-c", cfgG[0], "push", "-q", s.URL+"/a/"+project, "refs/heads/"+branch+":refs/heads/"+branch)
}

// EditProjectConfig changes project.config on refs/meta/config the way an
// administrator would: each edit is the arguments to
// `git config -f project.config`. Unchanged configs are not pushed.
func (s *Server) EditProjectConfig(ctx context.Context, project, message string, edits [][]string) error {
	tmp, err := os.MkdirTemp(filepath.Dir(s.Site), "meta-config-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	helper, env := gitmirror.HTTPCredentials(s.URL, "admin", s.Admin.Password)
	git := func(args ...string) error {
		cmd := exec.CommandContext(ctx, "git", append([]string{"-c", helper[0]}, args...)...)
		cmd.Dir = tmp
		cmd.Env = append(append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_TERMINAL_PROMPT=0",
			"GIT_AUTHOR_NAME=Administrator", "GIT_AUTHOR_EMAIL=admin@example.com",
			"GIT_COMMITTER_NAME=Administrator", "GIT_COMMITTER_EMAIL=admin@example.com"), env...)
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("git %s: %w: %s", args[0], err, out)
		}
		return nil
	}
	remote := s.URL + "/a/" + project
	if err := git("init", "-q"); err != nil {
		return err
	}
	if err := git("fetch", "-q", remote, "refs/meta/config"); err != nil {
		return err
	}
	if err := git("checkout", "-q", "FETCH_HEAD"); err != nil {
		return err
	}
	for _, e := range edits {
		err := git(append([]string{"config", "-f", "project.config"}, e...)...)
		if err != nil && !(len(e) > 0 && e[0] == "--unset-all") { // unsetting nothing is fine
			return err
		}
	}
	if err := git("diff", "--quiet"); err == nil {
		return nil
	}
	if err := git("commit", "-q", "-am", message); err != nil {
		return err
	}
	return git("push", "-q", remote, "HEAD:refs/meta/config")
}

// AddEmail gives username another (confirmed) email address, so commits
// with it may be pushed as that user. Existing addresses are fine.
func (s *Server) AddEmail(ctx context.Context, username, email string) error {
	// Gerrit decodes "+" in a path as a space, so escape it too.
	escaped := strings.ReplaceAll(url.PathEscape(email), "+", "%2B")
	err := s.Admin.Do(ctx, http.MethodPut, "accounts/"+url.PathEscape(username)+"/emails/"+escaped,
		map[string]any{"no_confirmation": true}, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status == http.StatusConflict {
		return nil
	}
	return err
}

// ReindexOpenChanges recomputes the stored submit requirement results of
// project's open changes, after its config changed.
func (s *Server) ReindexOpenChanges(ctx context.Context, project string) error {
	cs, err := s.Admin.QueryChanges(ctx, "project:"+gerrit.QueryString(project)+" status:open")
	if err != nil {
		return err
	}
	for _, c := range cs {
		if err := s.Admin.Do(ctx, http.MethodPost, fmt.Sprintf("changes/%d/index", c.Number), nil, nil); err != nil {
			return err
		}
	}
	return nil
}

func tokenCommand(user string) string {
	if user == "" {
		return "gh, auth, token"
	}
	return "gh, auth, token, --user, " + user
}

// GitHubUser is a Gerrit account the way Gerrit's github plugin creates
// them: username = GitHub login, email = the person's address.
type GitHubUser struct {
	Login, Email string
	Trusted      bool // in Verified Users, so CI builds their uploads
}

// EnsureGitHubUser creates u's account if it does not exist, makes Email
// its preferred address (taking it from any other account first, since an
// address can belong to only one), and returns the new credentials, or nil
// if the account already existed.
func (s *Server) EnsureGitHubUser(ctx context.Context, u GitHubUser) (*User, error) {
	var created *User
	err := s.Admin.Do(ctx, http.MethodGet, "accounts/"+url.PathEscape(u.Login), nil, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status == http.StatusNotFound {
		groups := []string{}
		if u.Trusted {
			groups = append(groups, TrustedGroup, SubmitGroup)
		}
		if created, err = s.CreateUser(ctx, u.Login, u.Login, groups...); err != nil {
			return nil, err
		}
	} else if err != nil {
		return nil, err
	}
	if u.Email == "" {
		return created, nil
	}
	escaped := strings.ReplaceAll(url.PathEscape(u.Email), "+", "%2B")
	owners, err := s.Admin.QueryAccounts(ctx, "email:"+gerrit.QueryString(u.Email))
	if err != nil {
		return nil, err
	}
	for _, o := range owners {
		if !strings.EqualFold(o.Username, u.Login) {
			if err := s.Admin.Do(ctx, http.MethodDelete, fmt.Sprintf("accounts/%d/emails/%s", o.AccountID, escaped), nil, nil); err != nil {
				return nil, fmt.Errorf("taking %s from %s: %w", u.Email, o.Username, err)
			}
		}
	}
	if err := s.AddEmail(ctx, u.Login, u.Email); err != nil {
		return nil, err
	}
	err = s.Admin.Do(ctx, http.MethodPut, "accounts/"+url.PathEscape(u.Login)+"/emails/"+escaped+"/preferred", nil, nil)
	return created, err
}

// SetPreferredEmail adds email to username (confirmed) and makes it the
// preferred address.
func (s *Server) SetPreferredEmail(ctx context.Context, username, email string) error {
	if err := s.AddEmail(ctx, username, email); err != nil {
		return err
	}
	escaped := strings.ReplaceAll(url.PathEscape(email), "+", "%2B")
	return s.Admin.Do(ctx, http.MethodPut, "accounts/"+url.PathEscape(username)+"/emails/"+escaped+"/preferred", nil, nil)
}

// SetUpLoginUser finishes an account the github plugin created: adds it to
// groups and, if passwordFile does not exist, generates an HTTP password
// and writes it there. It reports false if the account does not exist yet.
func (s *Server) SetUpLoginUser(ctx context.Context, username string, groups []string, passwordFile string) (bool, error) {
	accts, err := s.Admin.QueryAccounts(ctx, "username:"+gerrit.QueryString(username))
	if err != nil || len(accts) == 0 {
		return false, err
	}
	id := fmt.Sprint(accts[0].AccountID)
	for _, g := range groups {
		if err := s.Admin.Do(ctx, http.MethodPut, "groups/"+url.PathEscape(g)+"/members/"+id, nil, nil); err != nil {
			return false, fmt.Errorf("adding to %s: %w", g, err)
		}
	}
	if _, err := os.Stat(passwordFile); err == nil {
		return true, nil
	}
	var pw string
	if err := s.Admin.Do(ctx, http.MethodPut, "accounts/"+id+"/password.http", map[string]any{"generate": true}, &pw); err != nil {
		return false, fmt.Errorf("HTTP password: %w", err)
	}
	return true, os.WriteFile(passwordFile, []byte(pw+"\n"), 0o600)
}
