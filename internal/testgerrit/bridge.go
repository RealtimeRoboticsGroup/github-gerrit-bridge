// BridgeGroup is the group the bridge account is in; refs/bridge/* is
// visible to it alone.
const BridgeGroup = "GitHub Bridge"

// TrustedGroup is the CI group from design §6.5. The bridge is not in it.
const TrustedGroup = "Verified Users"

// Env is a project set up the way the bridge expects a real one to be.
type Env struct {
	Project string
	Bridge  *User
	// Alice is a trusted (CI-verified) developer; Bob is not.
	Alice, Bob *User
}

// SetupBridge creates project with the bridge's accounts, groups, ACLs and
// labels. It is not idempotent: call it once, on a fresh site.
func (s *Server) SetupBridge(ctx context.Context, project string) (*Env, error) {
	for _, g := range []string{BridgeGroup, TrustedGroup} {
		if err := s.CreateGroup(ctx, g); err != nil {
			return nil, fmt.Errorf("group %s: %w", g, err)
		}
	}
	var err error
	e := &Env{Project: project}
	// "Service Users" carries the Stream Events capability.
	if e.Bridge, err = s.CreateUser(ctx, "github-bridge", "GitHub Bridge", BridgeGroup, "Service Users"); err != nil {
		return nil, err
	}
	if e.Alice, err = s.CreateUser(ctx, "alice", "Alice Trusted", TrustedGroup); err != nil {
		return nil, err
	}
	if e.Bob, err = s.CreateUser(ctx, "bob", "Bob Newcomer"); err != nil {
		return nil, err
	}
	if err := s.CreateProject(ctx, project); err != nil {
		return nil, fmt.Errorf("project %s: %w", project, err)
	}
	if err := s.ConfigureProject(ctx, project); err != nil {
		return nil, err
	}
	if err := s.GrantRunAs(ctx); err != nil {
		return nil, err
	}
	return e, nil
}

// WriteBridgeConfig writes a bridge config, and the secrets it names, into
// dir, for running cmd/bridge against this server and GitHub repo
// owner/repo.
func (s *Server) WriteBridgeConfig(dir string, e *Env, owner, repo string, listen string) (string, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	kh, err := s.KnownHostsLine()
	if err != nil {
		return "", err
	}
	secret := make([]byte, 16)
	rand.Read(secret)
	// A separate peer key, so imports from GitHub are owned by the mapped
	// user (suexec, design §5.2).
	peer, err := s.CreatePeerKey()
	if err != nil {
		return "", err
	}
	files := map[string]string{
		"gerrit-http-password": e.Bridge.HTTPPassword + "\n",
		"id_ed25519":           string(e.Bridge.PrivateKeyPEM),
		"known_hosts":          kh + "\n",
		"webhook-secret":       fmt.Sprintf("%x\n", secret),
		"peer_key":             string(peer),
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			return "", err
		}
	}
	return s.WriteProjectConfig(dir, ProjectConfig{
		File: "config.yaml", Project: e.Project, Owner: owner, Repo: repo, Listen: listen,
		Identity: map[string]string{owner: "alice"}, ResyncInterval: time.Minute,
	})
}

// ProjectConfig describes a bridge config written by WriteProjectConfig.
type ProjectConfig struct {
	File, Project, Owner, Repo, Listen string
	// Identity maps GitHub logins to Gerrit usernames.
	Identity           map[string]string
	ImportCreatedAfter time.Time
	ResyncInterval     time.Duration
	// TokenUser is the gh account whose token the bridge uses (the bot);
	// empty means gh's active account.
	TokenUser string
	// CIAccount is CI's Gerrit username.
	CIAccount string
	// Buildkite is the (fake) Buildkite API URL CI uses, organization
	// "test", pipeline "ci"; empty means none. The bridge then serves
	// Gerrit's Checks tab at http://Listen.
	Buildkite string
}

// WriteProjectConfig writes a bridge config for one project into dir,
// using the credentials WriteBridgeConfig put there. Each project gets its
// own mirror directory.
func (s *Server) WriteProjectConfig(dir string, c ProjectConfig) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by testgerrit for a local test Gerrit. Do not use in production.
listen: %q
resync_interval: %s
gerrit:
  url: %s
  project: %s
  http_user: github-bridge
  http_password_file: %s
  mirror_dir: %s
  ssh:
    address: %s
    user: github-bridge
    key_file: %s
    peer_key_file: %s
    known_hosts_file: %s
github:
  owner: %s
  repo: %s
  webhook_secret_file: %s
  token_command: [%s]
`, c.Listen, c.ResyncInterval, s.URL, c.Project, filepath.Join(dir, "gerrit-http-password"),
		filepath.Join(dir, c.Project+"-mirror.git"), s.SSHAddr, filepath.Join(dir, "id_ed25519"),
		filepath.Join(dir, "peer_key"), filepath.Join(dir, "known_hosts"), c.Owner, c.Repo, filepath.Join(dir, "webhook-secret"), tokenCommand(c.TokenUser))
	if !c.ImportCreatedAfter.IsZero() {
		fmt.Fprintf(&b, "  import_created_after: %s\n", c.ImportCreatedAfter.UTC().Format(time.RFC3339))
	}
	b.WriteString("identity:\n  github_to_gerrit:\n")
	for gh, user := range c.Identity {
		fmt.Fprintf(&b, "    %s: %s\n", gh, user)
	}
	fmt.Fprintf(&b, "ci:\n  trusted_group: %s\n", TrustedGroup)
	if c.CIAccount != "" {
		fmt.Fprintf(&b, "  account: %s\n", c.CIAccount)
	}
	if c.Buildkite != "" {
		tok := filepath.Join(dir, "buildkite-token")
		if err := os.WriteFile(tok, []byte("fake\n"), 0o600); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "  buildkite:\n    api_url: %s\n    organization: test\n    pipeline: ci\n    token_file: %s\n  checks_url: http://%s\n",
			c.Buildkite, tok, c.Listen)
	}
	path := filepath.Join(dir, c.File)
	return path, os.WriteFile(path, []byte(b.String()), 0o600)
}

// AddPeerKey lets key log in as Gerrit's peer daemon user (SSH user
// "Gerrit Code Review"), which may run `suexec --as <user> -- <command>`.
// Gerrit rereads the file when it changes.
//
// The file format is not authorized_keys: each line is the base64 key blob
// and an optional one-word comment, with no key type. A line with more
// fields makes Gerrit silently ignore the whole file.
func (s *Server) AddPeerKey(key ssh.PublicKey, comment string) error {
	f, err := os.OpenFile(filepath.Join(s.Site, "etc", "peer_keys"), os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	_, err = fmt.Fprintf(f, "%s %s\n", base64.StdEncoding.EncodeToString(key.Marshal()), strings.Join(strings.Fields(comment), "_"))
	return err
}

// CreatePeerKey generates a key, registers it in etc/peer_keys and returns
// the private key in OpenSSH PEM form.
func (s *Server) CreatePeerKey() ([]byte, error) {
	_, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return nil, err
	}
	signer, err := ssh.NewSignerFromKey(priv)
	if err != nil {
		return nil, err
	}
	if err := s.AddPeerKey(signer.PublicKey(), "bridge-peer"); err != nil {
		return nil, err
	}
	block, err := ssh.MarshalPrivateKey(priv, "bridge-peer")
	if err != nil {
		return nil, err
	}
	return pem.EncodeToMemory(block), nil
}

func (s *Server) groupID(ctx context.Context, name string) (string, error) {
	var g struct {
		ID string `json:"id"`
	}
	err := s.Admin.Do(ctx, http.MethodGet, "groups/"+url.PathEscape(name), nil, &g)
	return g.ID, err
}

// ConfigureProject sets up project the way the bridge expects (and the way
// the real site should be): refs/bridge/* readable and writable only by the
// bridge, Forge Author for imports, a Verified label with a submit
// requirement, Submit for registered users, and Push for administrators
// (to seed branches).
func (s *Server) ConfigureProject(ctx context.Context, project string) error {
	bridge, err := s.groupID(ctx, BridgeGroup)
	if err != nil {
		return err
	}
	admins, err := s.groupID(ctx, "Administrators")
	if err != nil {
		return err
	}
	allow := func(id string) map[string]any {
		return map[string]any{"rules": map[string]any{id: map[string]any{"action": "ALLOW"}}}
	}
	access := map[string]any{"add": map[string]any{
		// Only the bridge can see or write its state (design §4.4).
		"refs/bridge/*": map[string]any{"permissions": map[string]any{
			"read":   map[string]any{"exclusive": true, "rules": map[string]any{bridge: map[string]any{"action": "ALLOW"}}},
			"push":   allow(bridge),
			"create": allow(bridge),
		}},
		// Imports from GitHub keep the real author (design §5.2).
		"refs/*": map[string]any{"permissions": map[string]any{"forgeAuthor": allow(bridge)}},
		// Administrators edit project.config by pushing it.
		"refs/meta/config": map[string]any{"permissions": map[string]any{"push": allow(admins)}},
		"refs/heads/*": map[string]any{"permissions": map[string]any{
			"submit": allow("global:Registered-Users"),
			"push":   map[string]any{"rules": map[string]any{admins: map[string]any{"action": "ALLOW", "force": true}}},
			"create": allow(admins),
		}},
	}}
	if err := s.Admin.Do(ctx, http.MethodPost, "projects/"+url.PathEscape(project)+"/access", access, nil); err != nil {
		return fmt.Errorf("access: %w", err)
	}
	// The Verified label and submit requirements are AOS's
	// (RealtimeRoboticsGroup/aos project.config, 2026-10-10), except the
	// label function: AOS still has MaxWithBlock from before an upgrade,
	// but 3.14 refuses to store it now. It changes nothing, because the
	// explicit "Verified" submit requirement replaces the label function's
	// check.
	err = s.EditProjectConfig(ctx, project, "Configure like AOS", [][]string{
		{"label.Verified.defaultValue", "0"},
		{"--unset-all", "label.Verified.value"},
		{"--add", "label.Verified.value", "-1 Fails"},
		{"--add", "label.Verified.value", "0 No score"},
		{"--add", "label.Verified.value", "+1 Verified"},
		{"label.Verified.copyCondition", "changekind:NO_CHANGE"},
		{"label.Verified.function", "NoBlock"},
		{"receive.enableSignedPush", "true"},
		{"submit-requirement.Verified.description", "At least one maximum vote for label 'Verified' is required"},
		{"submit-requirement.Verified.submittableIf", "label:Verified=MAX,user=non_uploader AND -label:Verified=MIN"},
		{"submit-requirement.Verified.canOverrideInChildProjects", "true"},
		{"submit-requirement.Signed-off-by.description", "Commit message must include a Signed-off-by footer"},
		{"submit-requirement.Signed-off-by.submittableIf", `message:"Signed-off-by"`},
		{"submit-requirement.Signed-off-by.canOverrideInChildProjects", "false"},
	})
	if err != nil {
		return fmt.Errorf("project.config: %w", err)
	}
	// AOS lets Service Users (its CI accounts) vote Verified.
	svc, err := s.groupID(ctx, "Service Users")
	if err != nil {
		return err
	}
	vote := map[string]any{"add": map[string]any{"refs/heads/*": map[string]any{"permissions": map[string]any{
		"label-Verified": map[string]any{"label": "Verified", "rules": map[string]any{
			svc: map[string]any{"action": "ALLOW", "min": -1, "max": 1}}},
	}}}}
	if err := s.Admin.Do(ctx, http.MethodPost, "projects/"+url.PathEscape(project)+"/access", vote, nil); err != nil {
		return fmt.Errorf("Verified access: %w", err)
	}
	return nil
}

// GrantRunAs gives the bridge group the global Run As capability, which
// /submit and draft mirroring use (design §6.7).
func (s *Server) GrantRunAs(ctx context.Context) error {
	bridge, err := s.groupID(ctx, BridgeGroup)
	if err != nil {
		return err
	}
	access := map[string]any{"add": map[string]any{"GLOBAL_CAPABILITIES": map[string]any{"permissions": map[string]any{
		"runAs": map[string]any{"rules": map[string]any{bridge: map[string]any{"action": "ALLOW"}}},
	}}}}
	return s.Admin.Do(ctx, http.MethodPost, "projects/All-Projects/access", access, nil)
}

// ProjectExists reports whether project exists.
func (s *Server) ProjectExists(ctx context.Context, project string) (bool, error) {
	err := s.Admin.Do(ctx, http.MethodGet, "projects/"+url.PathEscape(project), nil, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status == http.StatusNotFound {
		return false, nil
	}
	return err == nil, err
}

// MirrorProject creates project, configured for the bridge, with the
// branch of a GitHub repository as its main: the starting point of a site
// that owns that repository's main from then on.
func (s *Server) MirrorProject(ctx context.Context, project, repoURL, token, branch string) error {
	if err := s.Admin.Do(ctx, http.MethodPut, "projects/"+url.PathEscape(project), map[string]any{"create_empty_commit": false}, nil); err != nil {
		return fmt.Errorf("project %s: %w", project, err)
	}
	if err := s.ConfigureProject(ctx, project); err != nil {
		return err
	}
	tmp, err := os.MkdirTemp(filepath.Dir(s.Site), "seed-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	git := func(env []string, args ...string) error {
		cmd := exec.CommandContext(ctx, "git", args...)
		cmd.Dir = tmp
		cmd.Env = append(append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_TERMINAL_PROMPT=0"), env...)
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("git %s: %w: %s", args[0], err, out)
		}
		return nil
	}
	cfgGH, envGH := gitmirror.HTTPCredentials("https://github.com", "x-access-token", token)
	cfgG, envG := gitmirror.HTTPCredentials(s.URL, "admin", s.Admin.Password)
	if err := git(nil, "init", "-q", "--bare"); err != nil {
		return err
	}
	if err := git(envGH, "-c", cfgGH[0], "fetch", "-q", repoURL, "+refs/heads/"+branch+":refs/heads/"+branch); err != nil {
		return err
	}
	return git(envG, "-c", cfgG[0], "push", "-q", s.URL+"/a/"+project, "refs/heads/"+branch+":refs/heads/"+branch)
}

// EditProjectConfig changes project.config on refs/meta/config the way an
// administrator would: each edit is the arguments to
// `git config -f project.config`. Unchanged configs are not pushed.
func (s *Server) EditProjectConfig(ctx context.Context, project, message string, edits [][]string) error {
	tmp, err := os.MkdirTemp(filepath.Dir(s.Site), "meta-config-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	helper, env := gitmirror.HTTPCredentials(s.URL, "admin", s.Admin.Password)
	git := func(args ...string) error {
		cmd := exec.CommandContext(ctx, "git", append([]string{"-c", helper[0]}, args...)...)
		cmd.Dir = tmp
		cmd.Env = append(append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_TERMINAL_PROMPT=0",
			"GIT_AUTHOR_NAME=Administrator", "GIT_AUTHOR_EMAIL=admin@example.com",
			"GIT_COMMITTER_NAME=Administrator", "GIT_COMMITTER_EMAIL=admin@example.com"), env...)
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("git %s: %w: %s", args[0], err, out)
		}
		return nil
	}
	remote := s.URL + "/a/" + project
	if err := git("init", "-q"); err != nil {
		return err
	}
	if err := git("fetch", "-q", remote, "refs/meta/config"); err != nil {
		return err
	}
	if err := git("checkout", "-q", "FETCH_HEAD"); err != nil {
		return err
	}
	for _, e := range edits {
		err := git(append([]string{"config", "-f", "project.config"}, e...)...)
		if err != nil && !(len(e) > 0 && e[0] == "--unset-all") { // unsetting nothing is fine
			return err
		}
	}
	if err := git("diff", "--quiet"); err == nil {
		return nil
	}
	if err := git("commit", "-q", "-am", message); err != nil {
		return err
	}
	return git("push", "-q", remote, "HEAD:refs/meta/config")
}

// AddEmail gives username another (confirmed) email address, so commits
// with it may be pushed as that user. Existing addresses are fine.
func (s *Server) AddEmail(ctx context.Context, username, email string) error {
	// Gerrit decodes "+" in a path as a space, so escape it too.
	escaped := strings.ReplaceAll(url.PathEscape(email), "+", "%2B")
	err := s.Admin.Do(ctx, http.MethodPut, "accounts/"+url.PathEscape(username)+"/emails/"+escaped,
		map[string]any{"no_confirmation": true}, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status == http.StatusConflict {
		return nil
	}
	return err
}

// ReindexOpenChanges recomputes the stored submit requirement results of
// project's open changes, after its config changed.
func (s *Server) ReindexOpenChanges(ctx context.Context, project string) error {
	cs, err := s.Admin.QueryChanges(ctx, "project:"+gerrit.QueryString(project)+" status:open")
	if err != nil {
		return err
	}
	for _, c := range cs {
		if err := s.Admin.Do(ctx, http.MethodPost, fmt.Sprintf("changes/%d/index", c.Number), nil, nil); err != nil {
			return err
		}
	}
	return nil
}

func tokenCommand(user string) string {
	if user == "" {
		return "gh, auth, token"
	}
	return "gh, auth, token, --user, " + user
}

// GitHubUser is a Gerrit account the way Gerrit's github plugin creates
// them: username = GitHub login, email = the person's address.
type GitHubUser struct {
	Login, Email string
	Trusted      bool // in Verified Users, so CI builds their uploads
}

// EnsureGitHubUser creates u's account if it does not exist, makes Email
// its preferred address (taking it from any other account first, since an
// address can belong to only one), and returns the new credentials, or nil
// if the account already existed.
func (s *Server) EnsureGitHubUser(ctx context.Context, u GitHubUser) (*User, error) {
	var created *User
	err := s.Admin.Do(ctx, http.MethodGet, "accounts/"+url.PathEscape(u.Login), nil, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status == http.StatusNotFound {
		groups := []string{}
		if u.Trusted {
			groups = append(groups, TrustedGroup)
		}
		if created, err = s.CreateUser(ctx, u.Login, u.Login, groups...); err != nil {
			return nil, err
		}
	} else if err != nil {
		return nil, err
	}
	if u.Email == "" {
		return created, nil
	}
	escaped := strings.ReplaceAll(url.PathEscape(u.Email), "+", "%2B")
	owners, err := s.Admin.QueryAccounts(ctx, "email:"+gerrit.QueryString(u.Email))
	if err != nil {
		return nil, err
	}
	for _, o := range owners {
		if !strings.EqualFold(o.Username, u.Login) {
			if err := s.Admin.Do(ctx, http.MethodDelete, fmt.Sprintf("accounts/%d/emails/%s", o.AccountID, escaped), nil, nil); err != nil {
				return nil, fmt.Errorf("taking %s from %s: %w", u.Email, o.Username, err)
			}
		}
	}
	if err := s.AddEmail(ctx, u.Login, u.Email); err != nil {
		return nil, err
	}
	err = s.Admin.Do(ctx, http.MethodPut, "accounts/"+url.PathEscape(u.Login)+"/emails/"+escaped+"/preferred", nil, nil)
	return created, err
}

// SetPreferredEmail adds email to username (confirmed) and makes it the
// preferred address.
func (s *Server) SetPreferredEmail(ctx context.Context, username, email string) error {
	if err := s.AddEmail(ctx, username, email); err != nil {
		return err
	}
	escaped := strings.ReplaceAll(url.PathEscape(email), "+", "%2B")
	return s.Admin.Do(ctx, http.MethodPut, "accounts/"+url.PathEscape(username)+"/emails/"+escaped+"/preferred", nil, nil)
}

// SetUpLoginUser finishes an account the github plugin created: adds it to
// groups and, if passwordFile does not exist, generates an HTTP password
// and writes it there. It reports false if the account does not exist yet.
func (s *Server) SetUpLoginUser(ctx context.Context, username string, groups []string, passwordFile string) (bool, error) {
	accts, err := s.Admin.QueryAccounts(ctx, "username:"+gerrit.QueryString(username))
	if err != nil || len(accts) == 0 {
		return false, err
	}
	id := fmt.Sprint(accts[0].AccountID)
	for _, g := range groups {
		if err := s.Admin.Do(ctx, http.MethodPut, "groups/"+url.PathEscape(g)+"/members/"+id, nil, nil); err != nil {
			return false, fmt.Errorf("adding to %s: %w", g, err)
		}
	}
	if _, err := os.Stat(passwordFile); err == nil {
		return true, nil
	}
	var pw string
	if err := s.Admin.Do(ctx, http.MethodPut, "accounts/"+id+"/password.http", map[string]any{"generate": true}, &pw); err != nil {
		return false, fmt.Errorf("HTTP password: %w", err)
	}
	return true, os.WriteFile(passwordFile, []byte(pw+"\n"), 0o600)
}
