// BridgeGroup is the group the bridge account is in; refs/bridge/* is
// visible to it alone.
const BridgeGroup = "GitHub Bridge"

// TrustedGroup is the CI group from design §6.5. The bridge is not in it.
const TrustedGroup = "Verified Users"

// Env is a project set up the way the bridge expects a real one to be.
type Env struct {
	Project string
	Bridge  *User
	// Alice is a trusted (CI-verified) developer; Bob is not.
	Alice, Bob *User
}

// SetupBridge creates project with the bridge's accounts, groups, ACLs and
// labels. It is not idempotent: call it once, on a fresh site.
func (s *Server) SetupBridge(ctx context.Context, project string) (*Env, error) {
	for _, g := range []string{BridgeGroup, TrustedGroup} {
		if err := s.CreateGroup(ctx, g); err != nil {
			return nil, fmt.Errorf("group %s: %w", g, err)
		}
	}
	var err error
	e := &Env{Project: project}
	// "Service Users" carries the Stream Events capability.
	if e.Bridge, err = s.CreateUser(ctx, "github-bridge", "GitHub Bridge", BridgeGroup, "Service Users"); err != nil {
		return nil, err
	}
	if e.Alice, err = s.CreateUser(ctx, "alice", "Alice Trusted", TrustedGroup); err != nil {
		return nil, err
	}
	if e.Bob, err = s.CreateUser(ctx, "bob", "Bob Newcomer"); err != nil {
		return nil, err
	}
	if err := s.CreateProject(ctx, project); err != nil {
		return nil, fmt.Errorf("project %s: %w", project, err)
	}
	if err := s.ConfigureProject(ctx, project); err != nil {
		return nil, err
	}
	if err := s.GrantRunAs(ctx); err != nil {
		return nil, err
	}
	return e, nil
}

// WriteBridgeConfig writes a bridge config, and the secrets it names, into
// dir, for running cmd/bridge against this server and GitHub repo
// owner/repo.
func (s *Server) WriteBridgeConfig(dir string, e *Env, owner, repo string, listen string) (string, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	kh, err := s.KnownHostsLine()
	if err != nil {
		return "", err
	}
	secret := make([]byte, 16)
	rand.Read(secret)
	// A separate peer key, so imports from GitHub are owned by the mapped
	// user (suexec, design §5.2).
	peer, err := s.CreatePeerKey()
	if err != nil {
		return "", err
	}
	files := map[string]string{
		"gerrit-http-password": e.Bridge.HTTPPassword + "\n",
		"id_ed25519":           string(e.Bridge.PrivateKeyPEM),
		"known_hosts":          kh + "\n",
		"webhook-secret":       fmt.Sprintf("%x\n", secret),
		"peer_key":             string(peer),
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			return "", err
		}
	}
	return s.WriteProjectConfig(dir, ProjectConfig{
		File: "config.yaml", Project: e.Project, Owner: owner, Repo: repo, Listen: listen,
		Identity: map[string]string{owner: "alice"}, ResyncInterval: time.Minute,
	})
}

// ProjectConfig describes a bridge config written by WriteProjectConfig.
type ProjectConfig struct {
	File, Project, Owner, Repo, Listen string
	// Identity maps GitHub logins to Gerrit usernames.
	Identity           map[string]string
	ImportCreatedAfter time.Time
	ResyncInterval     time.Duration
}

// WriteProjectConfig writes a bridge config for one project into dir,
// using the credentials WriteBridgeConfig put there. Each project gets its
// own mirror directory.
func (s *Server) WriteProjectConfig(dir string, c ProjectConfig) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by testgerrit for a local test Gerrit. Do not use in production.
listen: %q
resync_interval: %s
gerrit:
  url: %s
  project: %s
  http_user: github-bridge
  http_password_file: %s
  mirror_dir: %s
  ssh:
    address: %s
    user: github-bridge
    key_file: %s
    peer_key_file: %s
    known_hosts_file: %s
github:
  owner: %s
  repo: %s
  webhook_secret_file: %s
  token_command: [gh, auth, token]
`, c.Listen, c.ResyncInterval, s.URL, c.Project, filepath.Join(dir, "gerrit-http-password"),
		filepath.Join(dir, c.Project+"-mirror.git"), s.SSHAddr, filepath.Join(dir, "id_ed25519"),
		filepath.Join(dir, "peer_key"), filepath.Join(dir, "known_hosts"), c.Owner, c.Repo, filepath.Join(dir, "webhook-secret"))
	if !c.ImportCreatedAfter.IsZero() {
		fmt.Fprintf(&b, "  import_created_after: %s\n", c.ImportCreatedAfter.UTC().Format(time.RFC3339))
	}
	b.WriteString("identity:\n  github_to_gerrit:\n")
	for gh, user := range c.Identity {
		fmt.Fprintf(&b, "    %s: %s\n", gh, user)
	}
	fmt.Fprintf(&b, "ci:\n  trusted_group: %s\n", TrustedGroup)
	path := filepath.Join(dir, c.File)
	return path, os.WriteFile(path, []byte(b.String()), 0o600)
}

// AddPeerKey lets key log in as Gerrit's peer daemon user (SSH user
// "Gerrit Code Review"), which may run `suexec --as <user> -- <command>`.
// Gerrit rereads the file when it changes.
//
// The file format is not authorized_keys: each line is the base64 key blob
// and an optional one-word comment, with no key type. A line with more
// fields makes Gerrit silently ignore the whole file.
func (s *Server) AddPeerKey(key ssh.PublicKey, comment string) error {
	f, err := os.OpenFile(filepath.Join(s.Site, "etc", "peer_keys"), os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	_, err = fmt.Fprintf(f, "%s %s\n", base64.StdEncoding.EncodeToString(key.Marshal()), strings.Join(strings.Fields(comment), "_"))
	return err
}

// CreatePeerKey generates a key, registers it in etc/peer_keys and returns
// the private key in OpenSSH PEM form.
func (s *Server) CreatePeerKey() ([]byte, error) {
	_, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return nil, err
	}
	signer, err := ssh.NewSignerFromKey(priv)
	if err != nil {
		return nil, err
	}
	if err := s.AddPeerKey(signer.PublicKey(), "bridge-peer"); err != nil {
		return nil, err
	}
	block, err := ssh.MarshalPrivateKey(priv, "bridge-peer")
	if err != nil {
		return nil, err
	}
	return pem.EncodeToMemory(block), nil
}

func (s *Server) groupID(ctx context.Context, name string) (string, error) {
	var g struct {
		ID string `json:"id"`
	}
	err := s.Admin.Do(ctx, http.MethodGet, "groups/"+url.PathEscape(name), nil, &g)
	return g.ID, err
}

// ConfigureProject sets up project the way the bridge expects (and the way
// the real site should be): refs/bridge/* readable and writable only by the
// bridge, Forge Author for imports, a Verified label with a submit
// requirement, Submit for registered users, and Push for administrators
// (to seed branches).
func (s *Server) ConfigureProject(ctx context.Context, project string) error {
	bridge, err := s.groupID(ctx, BridgeGroup)
	if err != nil {
		return err
	}
	admins, err := s.groupID(ctx, "Administrators")
	if err != nil {
		return err
	}
	allow := func(id string) map[string]any {
		return map[string]any{"rules": map[string]any{id: map[string]any{"action": "ALLOW"}}}
	}
	access := map[string]any{"add": map[string]any{
		// Only the bridge can see or write its state (design §4.4).
		"refs/bridge/*": map[string]any{"permissions": map[string]any{
			"read":   map[string]any{"exclusive": true, "rules": map[string]any{bridge: map[string]any{"action": "ALLOW"}}},
			"push":   allow(bridge),
			"create": allow(bridge),
		}},
		// Imports from GitHub keep the real author (design §5.2).
		"refs/*": map[string]any{"permissions": map[string]any{"forgeAuthor": allow(bridge)}},
		"refs/heads/*": map[string]any{"permissions": map[string]any{
			"submit": allow("global:Registered-Users"),
			"push":   map[string]any{"rules": map[string]any{admins: map[string]any{"action": "ALLOW", "force": true}}},
			"create": allow(admins),
		}},
	}}
	if err := s.Admin.Do(ctx, http.MethodPost, "projects/"+url.PathEscape(project)+"/access", access, nil); err != nil {
		return fmt.Errorf("access: %w", err)
	}
	// Label functions are gone in 3.14; submittability is a submit
	// requirement.
	verified := map[string]any{
		"function": "NoBlock",
		"values":   map[string]string{"-1": "Fails", " 0": "No score", "+1": "Verified"},
	}
	if err := s.Admin.Do(ctx, http.MethodPut, "projects/"+url.PathEscape(project)+"/labels/Verified", verified, nil); err != nil {
		return fmt.Errorf("Verified label: %w", err)
	}
	sr := map[string]any{
		"name":                             "Verified",
		"submittability_expression":        "label:Verified=MAX AND -label:Verified=MIN",
		"allow_override_in_child_projects": false,
	}
	if err := s.Admin.Do(ctx, http.MethodPut, "projects/"+url.PathEscape(project)+"/submit_requirements/Verified", sr, nil); err != nil {
		return fmt.Errorf("Verified submit requirement: %w", err)
	}
	return nil
}

// GrantRunAs gives the bridge group the global Run As capability, which
// /submit and draft mirroring use (design §6.7).
func (s *Server) GrantRunAs(ctx context.Context) error {
	bridge, err := s.groupID(ctx, BridgeGroup)
	if err != nil {
		return err
	}
	access := map[string]any{"add": map[string]any{"GLOBAL_CAPABILITIES": map[string]any{"permissions": map[string]any{
		"runAs": map[string]any{"rules": map[string]any{bridge: map[string]any{"action": "ALLOW"}}},
	}}}}
	return s.Admin.Do(ctx, http.MethodPost, "projects/All-Projects/access", access, nil)
}

// ProjectExists reports whether project exists.
func (s *Server) ProjectExists(ctx context.Context, project string) (bool, error) {
	err := s.Admin.Do(ctx, http.MethodGet, "projects/"+url.PathEscape(project), nil, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status == http.StatusNotFound {
		return false, nil
	}
	return err == nil, err
}

// MirrorProject creates project, configured for the bridge, with the
// branch of a GitHub repository as its main: the starting point of a site
// that owns that repository's main from then on.
func (s *Server) MirrorProject(ctx context.Context, project, repoURL, token, branch string) error {
	if err := s.Admin.Do(ctx, http.MethodPut, "projects/"+url.PathEscape(project), map[string]any{"create_empty_commit": false}, nil); err != nil {
		return fmt.Errorf("project %s: %w", project, err)
	}
	if err := s.ConfigureProject(ctx, project); err != nil {
		return err
	}
	tmp, err := os.MkdirTemp(filepath.Dir(s.Site), "seed-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	git := func(env []string, args ...string) error {
		cmd := exec.CommandContext(ctx, "git", args...)
		cmd.Dir = tmp
		cmd.Env = append(append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_TERMINAL_PROMPT=0"), env...)
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("git %s: %w: %s", args[0], err, out)
		}
		return nil
	}
	cfgGH, envGH := gitmirror.HTTPCredentials("https://github.com", "x-access-token", token)
	cfgG, envG := gitmirror.HTTPCredentials(s.URL, "admin", s.Admin.Password)
	if err := git(nil, "init", "-q", "--bare"); err != nil {
		return err
	}
	if err := git(envGH, "-c", cfgGH[0], "fetch", "-q", repoURL, "+refs/heads/"+branch+":refs/heads/"+branch); err != nil {
		return err
	}
	return git(envG, "-c", cfgG[0], "push", "-q", s.URL+"/a/"+project, "refs/heads/"+branch+":refs/heads/"+branch)
}
