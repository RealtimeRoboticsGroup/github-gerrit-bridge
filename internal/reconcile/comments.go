// GerritAPI is what comment sync needs from Gerrit.
type GerritAPI interface {
	ListComments(ctx context.Context, change int) ([]gerrit.CommentInfo, error)
	SetReview(ctx context.Context, change int, revision string, in gerrit.ReviewInput) error
	DeleteVote(ctx context.Context, change int, account, label string) error
	GetChange(ctx context.Context, change int, opts ...string) (*gerrit.ChangeInfo, error)
	FileContent(ctx context.Context, change int, revision, path string) ([]byte, error)
	CommentURL(project string, change int, id string) string
	ChangeURL(project string, number int) string
}

// GitHubAPI is what comment sync needs from GitHub.
type GitHubAPI interface {
	ListReviewComments(ctx context.Context, n int) ([]github.ReviewComment, error)
	ListReviews(ctx context.Context, n int) ([]github.Review, error)
	ListIssueComments(ctx context.Context, n int) ([]github.IssueComment, error)
	ReviewThreads(ctx context.Context, n int) ([]github.ReviewThread, error)
	Edits(ctx context.Context, n int) (map[int64]string, error)
	ReviewEdits(ctx context.Context, n int) (map[int64]string, error)
	CreateReview(ctx context.Context, n int, r github.NewReview) (*github.Review, error)
	ListReviewCommentsOf(ctx context.Context, n int, review int64) ([]github.ReviewComment, error)
	CreateReviewComment(ctx context.Context, n int, rc github.NewReviewComment) (*github.ReviewComment, error)
	ReplyToReviewComment(ctx context.Context, n int, id int64, body string) (*github.ReviewComment, error)
	CreateIssueComment(ctx context.Context, n int, body string) (*github.IssueComment, error)
	SetThreadResolved(ctx context.Context, threadID string, resolved bool) error
	UpdateReviewComment(ctx context.Context, id int64, body string) error
	UpdateIssueComment(ctx context.Context, id int64, body string) error
	DismissReview(ctx context.Context, n int, id int64, message string) error
	Dismissals(ctx context.Context, n int) (map[int64]github.Dismissal, error)
	FileAt(ctx context.Context, ref, path string) ([]byte, error)
	IsAncestor(ctx context.Context, a, b string) (bool, error)
	GetPull(ctx context.Context, n int) (*github.PullRequest, error)
}

// Comments mirrors review comments, replies and thread resolution between
// a Gerrit change and its PR (design §6.1-6.3).
//
// Identity: on GitHub the bridge posts as its own account, naming the
// real author at the top of each comment (design §7, v1). Every mirrored
// comment is recognisable without state: GitHub bodies carry a hidden
// <!-- bridge:gerrit/<change>/<id> --> marker, and Gerrit comments are
// authored by the bridge account and link the GitHub original. So the
// bridge never mirrors its own posts back, and can rebuild the mapping if
// refs/bridge is lost or a crash interrupts a sync.
type Comments struct {
	// Now is the clock (time.Now if nil).
	Now     func() time.Time
	Project string
	Gerrit  GerritAPI
	GitHub  GitHubAPI
	Store   *state.Store
	// BridgeAccount is the bridge's Gerrit account id.
	BridgeAccount int
	// BridgeLogin is the bridge's GitHub login: only its comments' markers
	// are trusted (anyone can write <!-- bridge:... --> in a comment).
	BridgeLogin string
	// Users maps GitHub logins to Gerrit accounts. With GerritAs, content
	// from mapped GitHub users is posted in Gerrit as them (Run-As), so
	// Gerrit and its CI see the real author; otherwise as the bridge.
	Users    Identity
	GerritAs func(user string) GerritAPI
	// PostBudget, if set, bounds the Gerrit comments and messages of each
	// author the bridge posts on GitHub; the rest wait for a later sync.
	PostBudget *Budget
	// CIMessage matches CI messages, which are mirrored as statuses
	// (Checks), not as comments.
	CIMessage *regexp.Regexp
	DryRun    bool
	Logger    *slog.Logger

	mu sync.Mutex
	// firstSeen is when each review body was first seen (bodyTooFresh).
	firstSeen map[string]time.Time
}

// Comment kinds in comments.json.
const (
	kindReviewComment = "review_comment"
	kindIssueComment  = "issue_comment"
	kindReviewBody    = "review_body"
	// kindRefused maps a Gerrit comment GitHub would not take: no GitHub
	// comment has it, and it is not retried.
	kindRefused = "refused"
)

// Tags on what the bridge posts in Gerrit. Bridge notices are
// autogenerated; content mirrored from a GitHub user (often posted as that
// user) is not, so Gerrit shows it like any reply. Either tag marks a post
// as the bridge's, which is how it is never mirrored back, whoever the
// author is.
const (
	commentTag = "autogenerated:github-bridge"
	mirrorTag  = "github-bridge:mirror"
	// withdrawTag tags cannotWithdraw's notice: nothing mirrored has it.
	withdrawTag = commentTag + ":withdraw"
)

// isBridgeTag reports whether a Gerrit tag marks a bridge post.
func isBridgeTag(tag string) bool {
	return strings.HasPrefix(tag, commentTag) || strings.HasPrefix(tag, mirrorTag)
}

var (
	// The bridge's mirrors end with it; one anywhere else is not the
	// bridge's.
	gerritMarker = regexp.MustCompile(`<!-- bridge:gerrit/(\d+)/([^ ]+) -->\s*\z`)
	// The GitHub link in the attribution of a comment the bridge posted
	// under its own account identifies the original. (Only the header's:
	// the text after it is the GitHub user's, and may link anything.)
	githubRef = regexp.MustCompile(`^\*\*@[^*]+\*\* \(\[GitHub\]\([^)\s]*#(discussion_r|issuecomment-|pullrequestreview-)(\d+)\)\):`)
)

func githubKind(frag string) string {
	switch frag {
	case "discussion_r":
		return kindReviewComment
	case "issuecomment-":
		return kindIssueComment
	}
	return kindReviewBody
}

// snapshot is one change's comments on both sides.
type commentSnapshot struct {
	messages []gerrit.ChangeMessage
	// psGitHub is the GitHub commit for each patch set, where it differs
	// from Gerrit's (GitHub-born and re-parented revisions).
	psGitHub map[int]string
	// revisions are the change's recorded revisions, oldest first.
	revisions []state.Revision
	gerrit    []gerrit.CommentInfo
	byID      map[string]*gerrit.CommentInfo
	rcs       []github.ReviewComment
	// edits maps edited GitHub comments to their last editor, and
	// reviewEdits edited review bodies.
	edits, reviewEdits map[int64]string
	rcByID             map[int64]*github.ReviewComment
	ics                []github.IssueComment
	reviews            []github.Review
	threads            []github.ReviewThread
	psToSHA            map[int]string
	shaToPS            map[string]int
	current            int
	revision           string
	// labels are the current patch set's votes.
	labels map[string]gerrit.LabelInfo
	// wait is how long what was left out for now waits (tooFresh).
	wait time.Duration
	// heads are the commits the PR's branch was seen at (state.Head), up
	// to at, when it was read last, after everything listed here.
	heads []state.Head
	at    time.Time
}

// seen is the patch set whose commit GitHub had from minSeen before t
// until now, so the one someone commenting then could have seen; 0 if
// none. A comment that names no commit (an issue comment, a review of a
// commit Gerrit never had) goes on it, not on whatever is current when
// the bridge gets to it: a trusted reviewer's "retest" must not start CI
// on a patch set uploaded after it, or pushed moments before it (fourth
// audit), which they could not have read; nor on the newest patch set if
// the branch went back to an older one's commit, or on to one the bridge
// does not import (seventh audit). Until now: a head is seen once it is
// there, so one first seen after t may have been there at t.
func (s *commentSnapshot) seen(t time.Time) int {
	sha := headThroughout(s.heads, t.Add(-minSeen), s.at)
	if _, ok := s.psToSHA[s.shaToPS[sha]]; sha == "" || !ok {
		return 0
	}
	return s.shaToPS[sha]
}

// shown reports whether commit had been the PR's head for minSeen at t,
// and still was: a review then, which names it, is of it.
func (s *commentSnapshot) shown(commit string, t time.Time) bool {
	return commit != "" && headThroughout(s.heads, t.Add(-minSeen), t) == commit
}

// minSeen is how long a patch set must have been on GitHub before a
// comment counts as being about it (seen); it also covers the clocks of
// the bridge, which records when, and GitHub, which dates comments.
const minSeen = time.Minute

// ghSHA is the GitHub commit standing for patch set ps.
func (s *commentSnapshot) ghSHA(ps int) string {
	if sha, ok := s.psGitHub[ps]; ok {
		return sha
	}
	return s.psToSHA[ps]
}

type commentMap struct {
	byGerrit map[string]*state.Comment
	byGitHub map[string]*state.Comment // kind/id
}

func ghKey(kind string, id int64) string { return kind + "/" + strconv.FormatInt(id, 10) }

func newCommentMap(cs []state.Comment) *commentMap {
	m := &commentMap{byGerrit: map[string]*state.Comment{}, byGitHub: map[string]*state.Comment{}}
	for i := range cs {
		m.add(cs[i])
	}
	return m
}

func (m *commentMap) add(c state.Comment) {
	if m.byGerrit[c.GerritID] != nil {
		return
	}
	p := &c
	m.byGerrit[c.GerritID] = p
	m.byGitHub[ghKey(c.Kind, c.GitHubID)] = p
}

func (m *commentMap) list() []state.Comment {
	out := make([]state.Comment, 0, len(m.byGerrit))
	for _, c := range m.byGerrit {
		out = append(out, *c)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].GerritID < out[j].GerritID })
	return out
}

// Sync mirrors change n's comments. It does nothing for unlinked changes.
//
// It repeats until a pass posts nothing: a reply can only be mirrored once
// its thread's root has been, and ids of posted comments are learned by
// reading them back.
func (c *Comments) Sync(ctx context.Context, n int) error {
	st, err := c.Store.Load(ctx, n)
	if err != nil {
		return err
	}
	pr := st.State.PR
	if pr == 0 {
		return nil
	}
	m := newCommentMap(st.Comments)
	threads := map[string]*state.Thread{}
	for i := range st.Threads {
		t := st.Threads[i]
		threads[t.GerritRoot] = &t
	}
	var first *commentSnapshot
	var wait time.Duration
	for pass := 0; ; pass++ {
		if pass == 4 {
			return fmt.Errorf("comments on change %d did not settle", n)
		}
		snap, err := c.observe(ctx, n, pr, st)
		if err != nil {
			return err
		}
		if first == nil {
			first = snap
		} else {
			c.settle(snap, first)
		}
		c.recover(n, snap, m)
		c.recoverThreads(snap, m, threads)
		p1, err := c.gerritToGitHub(ctx, n, pr, snap, m, threads)
		if err != nil {
			return err
		}
		p2, err := c.githubToGerrit(ctx, n, pr, snap, m, threads)
		if err != nil {
			return err
		}
		wait = max(wait, snap.wait)
		p3, err := c.mirrorEdits(ctx, n, pr, snap, m)
		if err != nil {
			return err
		}
		p2 = p2 || p3
		if c.DryRun {
			return nil
		}
		if p1 || p2 {
			continue
		}
		if err := c.syncResolution(ctx, n, pr, snap, threads); err != nil {
			return err
		}
		if err := c.dismissStale(ctx, n, pr, snap, m); err != nil {
			return err
		}
		break
	}
	var ts []state.Thread
	for _, t := range threads {
		ts = append(ts, *t)
	}
	sort.Slice(ts, func(i, j int) bool { return ts[i].GerritRoot < ts[j].GerritRoot })
	if err := updateStateFn(ctx, c.Store, n, "Sync comments", func(s *state.Change) {
		s.Comments = m.list()
		s.Threads = ts
	}); err != nil {
		return err
	}
	return waitFor(wait)
}

// settle leaves out of a later pass's snapshot s what someone other than
// the bridge posted or edited since the first pass, first: the passes
// after it only finish what that one started (replies whose roots are
// mirrored now, ids learned by reading back). Anything newer waits for
// the next sync (fourth audit: a comment posted during each pass kept the
// sync, and the /submit and checks after it, from ever finishing).
func (c *Comments) settle(s, first *commentSnapshot) {
	ics := map[int64]string{}
	for _, ic := range first.ics {
		ics[ic.ID] = ic.Body
	}
	s.ics = slices.DeleteFunc(s.ics, func(ic github.IssueComment) bool {
		body, ok := ics[ic.ID]
		return !c.byBridge(ic.User.Login) && (!ok || body != ic.Body)
	})
	rcs := map[int64]string{}
	for _, rc := range first.rcs {
		rcs[rc.ID] = rc.Body
	}
	s.rcs = slices.DeleteFunc(s.rcs, func(rc github.ReviewComment) bool {
		body, ok := rcs[rc.ID]
		return !c.byBridge(rc.User.Login) && (!ok || body != rc.Body)
	})
	s.rcByID = map[int64]*github.ReviewComment{}
	for i := range s.rcs {
		s.rcByID[s.rcs[i].ID] = &s.rcs[i]
	}
	reviews := map[int64]github.Review{}
	for _, r := range first.reviews {
		reviews[r.ID] = r
	}
	s.reviews = slices.DeleteFunc(s.reviews, func(r github.Review) bool {
		was, ok := reviews[r.ID]
		return !c.byBridge(r.User.Login) && (!ok || was.Body != r.Body || was.State != r.State)
	})
	ours := func(a gerrit.AccountInfo, tag string) bool {
		return isBridgeTag(tag) || (a.AccountID != 0 && a.AccountID == c.BridgeAccount)
	}
	gerritIDs := map[string]bool{}
	for _, gc := range first.gerrit {
		gerritIDs[gc.ID] = true
	}
	s.gerrit = slices.DeleteFunc(s.gerrit, func(gc gerrit.CommentInfo) bool { return !ours(gc.Author, gc.Tag) && !gerritIDs[gc.ID] })
	s.byID = map[string]*gerrit.CommentInfo{}
	for i := range s.gerrit {
		s.byID[s.gerrit[i].ID] = &s.gerrit[i]
	}
	messageIDs := map[string]bool{}
	for _, m := range first.messages {
		messageIDs[m.ID] = true
	}
	s.messages = slices.DeleteFunc(s.messages, func(m gerrit.ChangeMessage) bool { return !ours(m.Author, m.Tag) && !messageIDs[m.ID] })
}

func (c *Comments) observe(ctx context.Context, n, pr int, st *state.Change) (*commentSnapshot, error) {
	s := &commentSnapshot{byID: map[string]*gerrit.CommentInfo{}, rcByID: map[int64]*github.ReviewComment{},
		psToSHA: map[int]string{}, shaToPS: map[string]int{}}
	var err error
	if s.gerrit, err = c.Gerrit.ListComments(ctx, n); err != nil {
		return nil, err
	}
	sort.SliceStable(s.gerrit, func(i, j int) bool {
		if s.gerrit[i].Updated != s.gerrit[j].Updated {
			return s.gerrit[i].Updated < s.gerrit[j].Updated
		}
		return s.gerrit[i].ID < s.gerrit[j].ID
	})
	for i := range s.gerrit {
		s.byID[s.gerrit[i].ID] = &s.gerrit[i]
	}
	ch, err := c.Gerrit.GetChange(ctx, n, "ALL_REVISIONS", "MESSAGES", "DETAILED_ACCOUNTS", "DETAILED_LABELS")
	if err != nil {
		return nil, err
	}
	for sha, r := range ch.Revisions {
		s.psToSHA[r.Number] = sha
		s.shaToPS[sha] = r.Number
	}
	s.revision = ch.CurrentRevision
	s.messages = ch.Messages
	s.labels = ch.Labels
	s.current = s.shaToPS[ch.CurrentRevision]
	// GitHub-born revisions have their own SHAs (design §5.2).
	s.psGitHub = map[int]string{}
	s.revisions = st.Revisions
	for _, r := range st.Revisions {
		if r.GitHubSHA != "" && r.GitHubSHA != r.GerritSHA {
			s.shaToPS[r.GitHubSHA] = r.PatchSet
			s.psGitHub[r.PatchSet] = r.GitHubSHA
		}
	}
	if s.rcs, err = c.GitHub.ListReviewComments(ctx, pr); err != nil {
		return nil, err
	}
	for i := range s.rcs {
		s.rcByID[s.rcs[i].ID] = &s.rcs[i]
	}
	if s.ics, err = c.GitHub.ListIssueComments(ctx, pr); err != nil {
		return nil, err
	}
	if s.reviews, err = c.GitHub.ListReviews(ctx, pr); err != nil {
		return nil, err
	}
	if s.threads, err = c.GitHub.ReviewThreads(ctx, pr); err != nil {
		return nil, err
	}
	if s.edits, err = c.GitHub.Edits(ctx, pr); err != nil {
		return nil, err
	}
	if s.reviewEdits, err = c.GitHub.ReviewEdits(ctx, pr); err != nil {
		return nil, err
	}
	// What GitHub has now, read after everything above was listed.
	p, err := c.GitHub.GetPull(ctx, pr)
	if err != nil {
		return nil, err
	}
	s.at = c.now()
	s.heads = withHead(st.Heads, p.Head.SHA, s.at)
	if !slices.Equal(s.heads, st.Heads) && !c.DryRun {
		if err := noteHead(ctx, c.Store, n, p.Head.SHA, s.at); err != nil {
			return nil, err
		}
	}
	return s, nil
}

// recover adds mappings that the markers prove but state lacks.
func (c *Comments) recover(n int, s *commentSnapshot, m *commentMap) {
	mark := func(body string, kind string, id int64) {
		for _, sm := range gerritMarker.FindAllStringSubmatch(body, -1) {
			if sm[1] == strconv.Itoa(n) {
				mc := state.Comment{GerritID: sm[2], GitHubID: id, Kind: kind, Origin: "gerrit"}
				if gc := s.byID[sm[2]]; gc != nil {
					mc.BodyHash = hashString(gc.Message)
				}
				m.add(mc)
			}
		}
	}
	// A marker counts only in the bridge's own comment, as it wrote it:
	// anyone with write access can edit the bridge's comments too.
	untouched := func(id int64) bool {
		editor, ok := s.edits[id]
		return !ok || c.byBridge(editor)
	}
	for _, rc := range s.rcs {
		if c.byBridge(rc.User.Login) && untouched(rc.ID) {
			mark(rc.Body, kindReviewComment, rc.ID)
		}
	}
	for _, ic := range s.ics {
		if c.byBridge(ic.User.Login) && untouched(ic.ID) {
			mark(ic.Body, kindIssueComment, ic.ID)
		}
	}
	for _, gc := range s.gerrit {
		// Only the bridge's own posts carry an attribution header; one
		// posted as a user starts with their own words, which may imitate
		// it (claim maps those).
		if gc.Author.AccountID != c.BridgeAccount || !c.bridgePost(&gc) {
			continue
		}
		if sm := githubRef.FindStringSubmatch(gc.Message); sm != nil {
			id, _ := strconv.ParseInt(sm[2], 10, 64)
			mc := state.Comment{GerritID: gc.ID, GitHubID: id, Kind: githubKind(sm[1]), Origin: "github"}
			if body, _, _, ok := s.githubBody(mc.Kind, id); ok {
				mc.BodyHash = hashString(body)
			}
			m.add(mc)
		}
	}
}

// recoverThreads links every mapped Gerrit thread root to its GitHub
// review thread.
func (c *Comments) recoverThreads(s *commentSnapshot, m *commentMap, threads map[string]*state.Thread) {
	byRoot := map[int64]github.ReviewThread{}
	for _, t := range s.threads {
		byRoot[t.RootID] = t
	}
	for gid, mc := range m.byGerrit {
		gc := s.byID[gid]
		if gc == nil || gc.InReplyTo != "" || mc.Kind != kindReviewComment {
			continue
		}
		t := threads[gid]
		if t == nil {
			// A new thread starts unresolved on GitHub.
			t = &state.Thread{GerritRoot: gid, GitHubRootID: mc.GitHubID}
			threads[gid] = t
		}
		if th, ok := byRoot[mc.GitHubID]; ok {
			t.GitHubThread = th.ID
		}
	}
}

// --- Gerrit -> GitHub ---

func (c *Comments) gerritHeader(n int, gc *gerrit.CommentInfo, current int) string {
	ps := ""
	if gc.PatchSet != 0 && gc.PatchSet != current {
		ps = fmt.Sprintf(" on patch set %d", gc.PatchSet)
	}
	return fmt.Sprintf("**%s** ([Gerrit](%s))%s:", whoMD(gc.Author), c.Gerrit.CommentURL(c.Project, n, gc.ID), ps)
}

func gerritFooter(n int, id string) string { return fmt.Sprintf("<!-- bridge:gerrit/%d/%s -->", n, id) }

// ghBody is the GitHub body for a Gerrit comment, with an optional note
// (quoted code, the true anchor) above the message and an optional
// suggestion block below it.
func (c *Comments) ghBody(n int, gc *gerrit.CommentInfo, current int, note, suggestion string) string {
	head, foot := c.gerritHeader(n, gc, current)+"\n\n", "\n\n"+gerritFooter(n, gc.ID)
	if note != "" {
		note = fitForGitHub(forGitHub(note), maxGitHubNote) + "\n\n"
	}
	if len(suggestion) > maxGitHubComment/2 {
		suggestion = "" // too big to suggest; the comment is still there
	}
	// Bounded as a whole: GitHub refuses a comment over 65,536 characters
	// (defusing makes text longer), and one it refuses must not stop the
	// change's sync.
	room := maxGitHubComment - len(head) - len(note) - len(suggestion) - len(foot) - 2
	var b strings.Builder
	b.WriteString(head + note)
	b.WriteString(fitForGitHub(forGitHub(strings.TrimSpace(gc.Message)), room))
	if suggestion != "" {
		// Exact: it may be committed. Its fence keeps it code, where
		// nothing in it mentions anyone.
		b.WriteString("\n\n" + suggestion)
	}
	b.WriteString(foot)
	return b.String()
}

// maxGitHubComment bounds what the bridge posts as one GitHub comment, in
// bytes, under GitHub's 65,536 characters; maxGitHubNote bounds the note
// (quoted lines, say) above a mirrored comment.
const (
	maxGitHubComment = 60000
	maxGitHubNote    = 4000
)

// fitForGitHub cuts s to at most room bytes, at a character boundary,
// saying the rest is in Gerrit. Cutting only removes text, so nothing
// defused becomes live again.
func fitForGitHub(s string, room int) string {
	if len(s) <= room {
		return s
	}
	cut := max(room-len(tooLongForGitHub)-maxFence, 0)
	for cut > 0 && !utf8.RuneStart(s[cut]) {
		cut--
	}
	return closeFence(s[:cut]) + tooLongForGitHub
}

// maxFence is the room fitForGitHub keeps for closing a code fence.
const maxFence = 64

// closeFence closes a code fence s leaves open, so a cut inside quoted
// code does not make code of the rest.
func closeFence(s string) string {
	open := ""
	for _, line := range strings.Split(s, "\n") {
		t := strings.TrimLeft(line, " ")
		run := len(t) - len(strings.TrimLeft(t, "`~"))
		if run < 3 || len(line)-len(t) > 3 {
			continue
		}
		fence := t[:run]
		if strings.Trim(fence, fence[:1]) != "" {
			continue // mixed: not a fence
		}
		switch {
		case open == "":
			open = fence
		case fence[0] == open[0] && len(fence) >= len(open) && strings.TrimSpace(t[run:]) == "":
			open = ""
		}
	}
	if open == "" || len(open) > maxFence-1 {
		return s
	}
	return s + "\n" + open
}

// refusedOnGitHub records Gerrit comment id as refused if err is GitHub
// refusing it for good (422), and reports whether it did: one comment
// GitHub will not take must not stop the change's sync.
func (c *Comments) refusedOnGitHub(n int, m *commentMap, id string, err error) bool {
	if !isUnprocessable(err) {
		return false
	}
	c.Logger.Warn("GitHub refused a Gerrit comment; not mirroring it", "change", n, "id", id, "err", err)
	m.add(state.Comment{GerritID: id, Kind: kindRefused, Origin: "gerrit"})
	return true
}

// githubParent finds the GitHub comment a Gerrit reply belongs under, by
// walking up its in_reply_to chain to the nearest mapped comment.
func githubParent(s *commentSnapshot, m *commentMap, gc *gerrit.CommentInfo) *state.Comment {
	seen := map[string]bool{}
	for id := gc.InReplyTo; id != "" && !seen[id]; {
		seen[id] = true
		if mc := m.byGerrit[id]; mc != nil {
			return mc
		}
		p := s.byID[id]
		if p == nil {
			return nil
		}
		id = p.InReplyTo
	}
	return nil
}

func (c *Comments) gerritToGitHub(ctx context.Context, n, pr int, s *commentSnapshot, m *commentMap, threads map[string]*state.Thread) (bool, error) {
	type group struct {
		ps    int
		items []*gerrit.CommentInfo
	}
	var groups []*group // review batches: one per (Gerrit reply, patch set)
	gkey := map[string]*group{}
	posted := false
	deferred := 0
	for i := range s.gerrit {
		gc := &s.gerrit[i]
		if c.bridgePost(gc) || m.byGerrit[gc.ID] != nil {
			continue
		}
		if c.DryRun {
			c.Logger.Info("dry run: would mirror Gerrit comment to GitHub", "change", n, "pr", pr, "id", gc.ID, "path", gc.Path, "line", gc.Line)
			continue
		}
		if !c.PostBudget.Take(ctx, gc.Author.AccountID) {
			deferred++
			continue
		}
		parent := githubParent(s, m, gc)
		switch {
		case parent != nil && parent.Kind == kindReviewComment:
			root := parent.GitHubID
			if rc := s.rcByID[root]; rc != nil && rc.InReplyTo != 0 {
				root = rc.InReplyTo
			}
			out, err := c.GitHub.ReplyToReviewComment(ctx, pr, root, c.ghBody(n, gc, s.current, "", ""))
			if c.refusedOnGitHub(n, m, gc.ID, err) {
				continue
			}
			if err != nil {
				return posted, err
			}
			m.add(state.Comment{GerritID: gc.ID, GitHubID: out.ID, Kind: kindReviewComment, Origin: "gerrit", BodyHash: hashString(gc.Message)})
			posted = true
		case gc.Path == gerrit.PatchSetLevel || parent != nil || gc.Path == gerrit.CommitMsg:
			ctxLine := ""
			if gc.Path == gerrit.CommitMsg {
				ctxLine = c.quote(ctx, n, gc, "commit message")
			}
			out, err := c.GitHub.CreateIssueComment(ctx, pr, c.ghBody(n, gc, s.current, ctxLine, ""))
			if c.refusedOnGitHub(n, m, gc.ID, err) {
				continue
			}
			if err != nil {
				return posted, err
			}
			m.add(state.Comment{GerritID: gc.ID, GitHubID: out.ID, Kind: kindIssueComment, Origin: "gerrit", BodyHash: hashString(gc.Message)})
			posted = true
		default:
			k := gc.Author.Username + "|" + gc.Updated + "|" + strconv.Itoa(gc.PatchSet)
			g := gkey[k]
			if g == nil {
				g = &group{ps: gc.PatchSet}
				gkey[k] = g
				groups = append(groups, g)
			}
			g.items = append(g.items, gc)
		}
	}
	for _, msg := range s.messages {
		if m.byGerrit[msg.ID] != nil {
			continue
		}
		text := c.messageText(msg)
		if text == "" {
			continue
		}
		if c.DryRun {
			c.Logger.Info("dry run: would mirror Gerrit message to GitHub", "change", n, "pr", pr, "id", msg.ID)
			continue
		}
		if !c.PostBudget.Take(ctx, msg.Author.AccountID) {
			deferred++
			continue
		}
		votes := ""
		if v := messageVotes(msg.Message); v != "" {
			votes = ", **" + v + "**"
		}
		head := fmt.Sprintf("**%s** ([Gerrit](%s)) on patch set %d%s:\n\n", whoMD(msg.Author), c.messageURL(n, msg), msg.RevisionNumber, votes)
		foot := "\n\n" + gerritFooter(n, msg.ID)
		body := head + fitForGitHub(forGitHub(text), maxGitHubComment-len(head)-len(foot)) + foot
		out, err := c.GitHub.CreateIssueComment(ctx, pr, body)
		if c.refusedOnGitHub(n, m, msg.ID, err) {
			continue
		}
		if err != nil {
			return posted, err
		}
		m.add(state.Comment{GerritID: msg.ID, GitHubID: out.ID, Kind: kindIssueComment, Origin: "gerrit"})
		posted = true
	}
	for _, g := range groups {
		if err := c.postReview(ctx, n, pr, s, m, g.ps, g.items); err != nil {
			return true, err
		}
		posted = true
	}
	if deferred > 0 {
		c.Logger.Info("Gerrit comments deferred: their authors posted too many lately", "change", n, "pr", pr, "comments", deferred)
	}
	return posted, nil
}

func ghSide(gerritSide string) string {
	if gerritSide == "PARENT" {
		return "LEFT"
	}
	return "RIGHT"
}

// ghAnchor is where a Gerrit comment goes on GitHub.
type ghAnchor struct {
	sha         string // GitHub commit
	first, last int    // lines; 0 means file level
	side        string // LEFT, RIGHT
	note        string // shown above the message
	suggestion  string // a ```suggestion block valid on first..last
}

// anchorFor translates a Gerrit comment's anchor (design §6.1).
func (c *Comments) anchorFor(ctx context.Context, n int, s *commentSnapshot, gc *gerrit.CommentInfo) ghAnchor {
	a := ghAnchor{sha: s.ghSHA(gc.PatchSet), side: ghSide(gc.Side), first: gc.Line, last: gc.Line}
	if r := gc.Range; r != nil {
		a.first, a.last = r.StartLine, r.EndLine
		if r.EndCharacter == 0 && r.EndLine > r.StartLine {
			a.last-- // the range ends at the start of EndLine
		}
		a.note = rangeNote(gc)
	}
	if sug, first, last, ok := c.toSuggestion(ctx, n, gc); ok {
		a.first, a.last, a.suggestion, a.note = first, last, sug, ""
	}
	return a
}

func (a ghAnchor) draft(path, body string) github.DraftReviewComment {
	d := github.DraftReviewComment{Path: path, Body: body, Line: a.last, Side: a.side}
	if a.first != a.last {
		d.StartLine, d.StartSide = a.first, a.side
	}
	return d
}

func (a ghAnchor) comment(path, body string) github.NewReviewComment {
	nc := github.NewReviewComment{CommitID: a.sha, Path: path, Body: body, Line: a.last, Side: a.side}
	if a.first != a.last {
		nc.StartLine, nc.StartSide = a.first, a.side
	}
	return nc
}

// postReview posts one Gerrit reply's line and file comments as a single
// GitHub review. If GitHub refuses (a line outside the diff), each comment
// is posted on its own, which ports or falls back as needed.
func (c *Comments) postReview(ctx context.Context, n, pr int, s *commentSnapshot, m *commentMap, ps int, items []*gerrit.CommentInfo) error {
	sha := s.ghSHA(ps)
	var lineItems []*gerrit.CommentInfo
	var drafts []github.DraftReviewComment
	sent := map[string]string{} // body -> Gerrit comment id
	for _, gc := range items {
		a := c.anchorFor(ctx, n, s, gc)
		if a.first == 0 {
			if err := c.postSingle(ctx, n, pr, s, m, gc); err != nil {
				return err
			}
			continue
		}
		lineItems = append(lineItems, gc)
		body := c.ghBody(n, gc, s.current, a.note, a.suggestion)
		sent[strings.TrimSpace(body)] = gc.ID
		drafts = append(drafts, a.draft(gc.Path, body))
	}
	if len(drafts) == 0 {
		return nil
	}
	rev, err := c.GitHub.CreateReview(ctx, pr, github.NewReview{CommitID: sha, Event: "COMMENT", Comments: drafts})
	if err == nil {
		c.Logger.Info("mirrored Gerrit comments to GitHub review", "change", n, "pr", pr, "review", rev.ID, "comments", len(drafts))
		// Map them now, by the exact text sent: their markers can be
		// edited by anyone with write access before the next pass reads
		// them. (If this read fails, the markers are the fallback.)
		posted, err := c.GitHub.ListReviewCommentsOf(ctx, pr, rev.ID)
		if err != nil {
			c.Logger.Warn("reading back the posted review", "change", n, "pr", pr, "err", err)
			return nil
		}
		for _, rc := range posted {
			if id, ok := sent[strings.TrimSpace(rc.Body)]; ok {
				gc := s.byID[id]
				m.add(state.Comment{GerritID: id, GitHubID: rc.ID, Kind: kindReviewComment, Origin: "gerrit", BodyHash: hashString(gc.Message)})
				delete(sent, strings.TrimSpace(rc.Body))
			}
		}
		return nil
	}
	if !isUnprocessable(err) {
		return err
	}
	c.Logger.Info("GitHub refused the batch; posting comments one by one", "change", n, "pr", pr, "err", err)
	for _, gc := range lineItems {
		if err := c.postSingle(ctx, n, pr, s, m, gc); err != nil {
			return err
		}
	}
	return nil
}

func rangeNote(gc *gerrit.CommentInfo) string {
	r := gc.Range
	if r == nil || (r.StartCharacter == 0 && r.EndCharacter == 0) {
		return ""
	}
	return fmt.Sprintf("<sub>Gerrit range: L%d:%d–L%d:%d</sub>", r.StartLine, r.StartCharacter, r.EndLine, r.EndCharacter)
}

// postSingle posts one comment, trying in turn: its own lines on its own
// patch set; the same lines ported to the current patch set (design §6.1
// step 6); file level with the lines quoted; and a PR comment.
func (c *Comments) postSingle(ctx context.Context, n, pr int, s *commentSnapshot, m *commentMap, gc *gerrit.CommentInfo) error {
	a := c.anchorFor(ctx, n, s, gc)
	try := func(nc github.NewReviewComment) (bool, error) {
		out, err := c.GitHub.CreateReviewComment(ctx, pr, nc)
		if err == nil {
			m.add(state.Comment{GerritID: gc.ID, GitHubID: out.ID, Kind: kindReviewComment, Origin: "gerrit", BodyHash: hashString(gc.Message)})
			return true, nil
		}
		if isUnprocessable(err) {
			return false, nil
		}
		return false, err
	}
	if a.first != 0 {
		if ok, err := try(a.comment(gc.Path, c.ghBody(n, gc, s.current, a.note, a.suggestion))); ok || err != nil {
			return err
		}
		if p, ok := c.portToCurrent(ctx, n, s, gc, a); ok {
			if ok, err := try(p.comment(gc.Path, c.ghBody(n, gc, s.current, p.note, p.suggestion))); ok || err != nil {
				return err
			}
		}
	}
	quote := ""
	if a.first != 0 {
		quote = c.quote(ctx, n, gc, gc.Path)
	}
	for _, sha := range []string{a.sha, s.ghSHA(s.current)} {
		nc := github.NewReviewComment{CommitID: sha, Path: gc.Path, Body: c.ghBody(n, gc, s.current, quote, ""), SubjectType: "file"}
		if ok, err := try(nc); ok || err != nil {
			return err
		}
	}
	if quote == "" {
		quote = codeSpan(gc.Path)
	}
	ic, err := c.GitHub.CreateIssueComment(ctx, pr, c.ghBody(n, gc, s.current, quote, ""))
	if c.refusedOnGitHub(n, m, gc.ID, err) {
		return nil
	}
	if err != nil {
		return err
	}
	m.add(state.Comment{GerritID: gc.ID, GitHubID: ic.ID, Kind: kindIssueComment, Origin: "gerrit", BodyHash: hashString(gc.Message)})
	return nil
}

// portToCurrent moves a comment's lines from its patch set to the current
// one, if they are unchanged in between.
func (c *Comments) portToCurrent(ctx context.Context, n int, s *commentSnapshot, gc *gerrit.CommentInfo, a ghAnchor) (ghAnchor, bool) {
	if gc.PatchSet == s.current || gc.Side == "PARENT" {
		return a, false
	}
	oldC, err1 := c.Gerrit.FileContent(ctx, n, strconv.Itoa(gc.PatchSet), gc.Path)
	newC, err2 := c.Gerrit.FileContent(ctx, n, strconv.Itoa(s.current), gc.Path)
	if err1 != nil || err2 != nil {
		return a, false
	}
	first, last, ok := anchor.NewMap(anchor.Lines(string(oldC)), anchor.Lines(string(newC))).Range(a.first, a.last)
	if !ok {
		return a, false
	}
	p := a
	p.sha, p.first, p.last = s.ghSHA(s.current), first, last
	where := fmt.Sprintf("line %d", a.first)
	if a.last != a.first {
		where = fmt.Sprintf("lines %d-%d", a.first, a.last)
	}
	p.note = strings.TrimSpace(fmt.Sprintf("<sub>Ported from patch set %d, %s.</sub> %s", gc.PatchSet, where, a.note))
	return p, true
}

// quote renders the commented lines as "`path` L3-L5" plus the lines, as
// code: they are someone's file, not Markdown or HTML to render.
func (c *Comments) quote(ctx context.Context, n int, gc *gerrit.CommentInfo, label string) string {
	first, last := gc.Line, gc.Line
	if r := gc.Range; r != nil {
		first, last = r.StartLine, r.EndLine
	}
	where := fmt.Sprintf("%s L%d", codeSpan(label), first)
	if last != first {
		where += fmt.Sprintf("-L%d", last)
	}
	if first == 0 || gc.Side == "PARENT" {
		return where
	}
	content, err := c.Gerrit.FileContent(ctx, n, strconv.Itoa(gc.PatchSet), gc.Path)
	if err != nil {
		return where
	}
	lines := strings.Split(string(content), "\n")
	var code strings.Builder
	for i := first; i <= last && i <= len(lines) && i-first < 10; i++ {
		code.WriteString(shorten(lines[i-1], 300) + "\n")
	}
	f := suggestionFence(code.String())
	return where + ":\n" + f + "\n" + code.String() + f
}

func isUnprocessable(err error) bool {
	var ae *github.APIError
	return errors.As(err, &ae) && ae.Status == http.StatusUnprocessableEntity
}

// --- GitHub -> Gerrit ---

// gerritBody is a GitHub comment's text for Gerrit. Posted as its author
// (Run-As) it needs no attribution; posted by the bridge it says who
// wrote it, and where.
func gerritBody(login, url, body string, asAuthor bool) string {
	body = limitComment(strings.TrimSpace(body), url)
	if asAuthor {
		return body
	}
	// The bridge posts it: its mentions would be the bridge's.
	return fmt.Sprintf("**@%s** ([GitHub](%s)):\n\n%s", login, url, forGerrit(strings.TrimSpace(body)))
}

// isMirror reports whether a GitHub body was written by the bridge: a
// mirrored Gerrit comment or a bridge notice.
// byBridge reports whether a GitHub comment by login may carry bridge
// markers.
func (c *Comments) byBridge(login string) bool {
	return c.BridgeLogin == "" || strings.EqualFold(login, c.BridgeLogin)
}

func isMirror(body string) bool { return strings.Contains(body, "<!-- bridge:") }

// ownMirror reports whether a GitHub comment is the bridge's copy of
// something (under a login it no longer uses, say) rather than someone's
// comment: it carries a marker that its author put there. A marker edited
// into someone else's comment does not keep it out of Gerrit.
func ownMirror(edits map[int64]string, id int64, author, body string) bool {
	return isMirror(body) && !editedByOther(edits, id, author)
}

// mine reports whether the bridge's GitHub account wrote a comment: never
// mirrored to Gerrit as someone's GitHub comment, whatever its text says
// now.
func (c *Comments) now() time.Time {
	if c.Now != nil {
		return c.Now()
	}
	return time.Now()
}

// mentionsRetest reports whether text may carry gerrit-buildkite's
// command to build a patch set, a line `(?m)^retest$`, once Gerrit has
// it: "retest" anywhere, in any case. What the bridge and Gerrit do to a
// comment on the way trims its ends (Go and Java each their own set of
// characters) and cuts it to size, which can leave such a line where a
// stricter match saw none (seventh audit: "retest "; eighth: a no-break
// space, a control character, a cut at 12 KiB). Prose that says it waits
// too, which costs only the wait.
func mentionsRetest(text string) bool { return strings.Contains(strings.ToLower(text), "retest") }

// tooFresh reports whether a comment changed at changed, saying body,
// waits before it is posted as its author: a "retest" starts CI as them
// (editSettle). s keeps the longest wait.
func (c *Comments) tooFresh(s *commentSnapshot, changed time.Time, body string) bool {
	w := editSettle - c.now().Sub(changed)
	if w <= 0 || !mentionsRetest(body) {
		return false
	}
	s.wait = max(s.wait, w)
	return true
}

// bodyTooFresh is tooFresh for a body GitHub gives no edit time for, a
// review's (key): changed when the bridge first saw it as it is, or when
// it was submitted, if later. Anyone with write access can edit a review,
// and GraphQL, which says who did, may lag REST (seventh audit).
func (c *Comments) bodyTooFresh(s *commentSnapshot, key string, submitted time.Time, body string) bool {
	if !mentionsRetest(body) {
		return false
	}
	now := c.now()
	k := key + " " + hashString(body)
	c.mu.Lock()
	first, ok := c.firstSeen[k]
	if !ok {
		if c.firstSeen == nil {
			c.firstSeen = map[string]time.Time{}
		}
		for k, at := range c.firstSeen {
			if now.Sub(at) > time.Hour {
				delete(c.firstSeen, k)
			}
		}
		first, c.firstSeen[k] = now, now
	}
	c.mu.Unlock()
	return c.tooFresh(s, latest(first, submitted), body)
}

func (c *Comments) mine(login string) bool {
	return c.BridgeLogin != "" && strings.EqualFold(login, c.BridgeLogin)
}

// noticeMarker marks bridge notices (not mirrors of anything).
const noticeMarker = "<!-- bridge:notice -->"

func (c *Comments) githubToGerrit(ctx context.Context, n, pr int, s *commentSnapshot, m *commentMap, threads map[string]*state.Thread) (bool, error) {
	resolved := map[int64]bool{}
	for _, t := range s.threads {
		resolved[t.RootID] = t.IsResolved
	}
	// One SetReview per (GitHub review, patch set).
	type batch struct {
		ps       int
		login    string         // GitHub author, posted as (Run-As)
		author   string         // their Gerrit account, as its text was written for ("": the bridge)
		labels   map[string]int // votes from a GitHub review
		comments map[string][]gerrit.CommentInput
		// plain is comments without fix suggestions (the suggestion
		// stays in the text), for Gerrit sites that do not allow them.
		plain map[string][]gerrit.CommentInput
		srcs  []ghComment // what it mirrors
	}
	var order []string
	batches := map[string]*batch{}
	// asAuthor reports whether login's comments are posted as their
	// Gerrit account.
	authors := map[string]string{}
	// GitHub's numeric ids for the logins: a login names one account at
	// a time, the same in every answer.
	ids := map[string]int64{}
	for _, rc := range s.rcs {
		ids[rc.User.Login] = rc.User.ID
	}
	for _, ic := range s.ics {
		ids[ic.User.Login] = ic.User.ID
	}
	for _, rv := range s.reviews {
		ids[rv.User.Login] = rv.User.ID
	}
	asAuthor := func(login string) bool {
		if login == "" {
			return false
		}
		if u, ok := authors[login]; ok {
			return u != ""
		}
		_, u := c.asUser(ctx, github.User{Login: login, ID: ids[login]})
		authors[login] = u
		return u != ""
	}
	claimed := map[string]bool{}
	// add queues ci, the Gerrit form of GitHub comment src, unless it was
	// posted already (see claim); plain is its message for sites without
	// fix suggestions ("" if ci has none).
	add := func(key, login string, src ghComment, ps int, path string, ci gerrit.CommentInput, plain ...string) {
		if c.claim(s, m, claimed, authors[login], src, ps, path, ci, plain...) {
			return
		}
		// Who posts is part of the key: one review's inline comments and
		// its body, one of them edited by someone else, are two posts.
		k := batchKey(key, ps, login)
		b := batches[k]
		if b == nil {
			b = &batch{ps: ps, login: login, author: authors[login], comments: map[string][]gerrit.CommentInput{}, plain: map[string][]gerrit.CommentInput{}}
			batches[k] = b
			order = append(order, k)
		}
		b.comments[path] = append(b.comments[path], ci)
		b.srcs = append(b.srcs, src)
		if ci.FixSuggestions != nil && len(plain) > 0 {
			ci.FixSuggestions, ci.Message = nil, plain[0]
		}
		b.plain[path] = append(b.plain[path], ci)
	}
	for i := range s.rcs {
		rc := &s.rcs[i]
		if c.mine(rc.User.Login) || ownMirror(s.edits, rc.ID, rc.User.Login, rc.Body) || m.byGitHub[ghKey(kindReviewComment, rc.ID)] != nil {
			continue
		}
		rootID := rc.ID
		if rc.InReplyTo != 0 {
			rootID = rc.InReplyTo
		}
		unresolved := !resolved[rootID]
		key := "review/" + strconv.FormatInt(rc.ReviewID, 10)
		login := rc.User.Login
		if editedByOther(s.edits, rc.ID, rc.User.Login) {
			// Anyone with write access can edit anyone's comment: not as
			// the author.
			login, key = "", key+"/edited"
		}
		if login != "" && c.tooFresh(s, latest(rc.CreatedAt, rc.UpdatedAt), rc.Body) {
			continue
		}
		body := gerritBody(rc.User.Login, rc.HTMLURL, rc.Body, asAuthor(login))
		ci := gerrit.CommentInput{Message: body, Unresolved: &unresolved}
		src := ghComment{kindReviewComment, rc.ID, rc.Body}
		if rc.InReplyTo != 0 {
			parent := m.byGitHub[ghKey(kindReviewComment, rc.InReplyTo)]
			if parent == nil {
				continue // the root has not been mirrored yet; next pass
			}
			pc := s.byID[parent.GerritID]
			if pc == nil {
				continue
			}
			ci.InReplyTo = pc.ID
			ci.Line, ci.Range, ci.Side = pc.Line, pc.Range, pc.Side
			add(key, login, src, pc.PatchSet, pc.Path, ci)
			continue
		}
		commit := rc.OriginalCommitID
		if commit == "" {
			commit = rc.CommitID
		}
		line := rc.OriginalLine
		if line == 0 {
			line = rc.Line
		}
		first := rc.OriginalStart
		if first == 0 || first > line {
			first = line
		}
		ps, ok := s.shaToPS[commit]
		if !ok && rc.SubjectType != "file" && rc.Side != "LEFT" {
			// A commit Gerrit never saw, e.g. an intermediate commit of
			// a multi-commit layer: port to the patch set built from the
			// first later head that contains it (design §6.1).
			if p, f, l, ok2 := c.portFromGitHub(ctx, s, commit, rc.Path, first, line); ok2 {
				ps, first, line, ok = p, f, l, true
				ci.Message = fmt.Sprintf("%s\n\n<sub>(Ported from GitHub commit %s.)</sub>", ci.Message, short(commit))
			}
		}
		if !ok {
			// Nowhere to anchor it: keep the comment, at file level on
			// the patch set its author could have seen, saying where it
			// was.
			if ps = s.seen(rc.CreatedAt); ps == 0 {
				ps, login, key = s.current, "", key+"/unseen"
				body = gerritBody(rc.User.Login, rc.HTMLURL, rc.Body, asAuthor(login))
			}
			ci.Message = fmt.Sprintf("%s\n\n<sub>(on GitHub commit %s, line %d)</sub>", body, short(commit), rc.OriginalLine)
			add(key, login, src, ps, rc.Path, ci)
			continue
		}
		if rc.SubjectType != "file" {
			if rc.Side == "LEFT" {
				ci.Side = "PARENT"
			}
			lastLen := c.lineLen(ctx, n, ps, rc.Path, line, ci.Side)
			if first != line {
				ci.Range = &gerrit.Range{StartLine: first, EndLine: line, EndCharacter: lastLen}
			} else {
				ci.Line = line
			}
			if ci.Side == "" {
				plain := ci.Message
				ci.Message, ci.FixSuggestions = fromSuggestion(ci.Message, rc.Path, first, line, lastLen)
				if ci.FixSuggestions != nil {
					// The fix is the author's exact code: from the raw
					// body, not the defused text (a decorator's @ would
					// get a joiner).
					if _, raw := fromSuggestion(rc.Body, rc.Path, first, line, lastLen); raw != nil {
						ci.FixSuggestions = raw
					}
				}
				add(key, login, src, ps, rc.Path, ci, plain)
				continue
			}
		}
		add(key, login, src, ps, rc.Path, ci)
	}
	for _, rv := range s.reviews {
		// Approvals and change requests count even without a body: they
		// become votes (and a note saying where they came from).
		vote := rv.State == "APPROVED" || rv.State == "CHANGES_REQUESTED"
		if (strings.TrimSpace(rv.Body) == "" && !vote) || c.mine(rv.User.Login) || ownMirror(s.reviewEdits, rv.ID, rv.User.Login, rv.Body) || m.byGitHub[ghKey(kindReviewBody, rv.ID)] != nil {
			continue
		}
		if rv.State != "COMMENTED" && !vote {
			continue
		}
		reviewed, known := s.shaToPS[rv.CommitID]
		// A review names the PR's head when it was submitted unless its
		// client says otherwise (GitHub's API, gh pr review): one pushed
		// moments before is not what was read (sixth audit). As for
		// comments and /submit, it counts only once on GitHub minSeen.
		early := known && !s.shown(rv.CommitID, rv.SubmittedAt)
		ps := reviewed
		if !known || early {
			ps = s.seen(rv.SubmittedAt)
		}
		body := rv.Body
		switch rv.State {
		case "APPROVED":
			body = "Approved on GitHub.\n\n" + body
		case "CHANGES_REQUESTED":
			body = "Requested changes on GitHub.\n\n" + body
		}
		if vote && !known {
			// GitHub showed code Gerrit does not have (say a push not
			// imported yet): a vote would land on code nobody reviewed.
			body = notCounted + " it was made on a commit that is not a patch set in Gerrit.\n\n" + body
		} else if vote && early {
			body = notCounted + " it was made on a commit that reached GitHub less than a minute before it. Review it again to count it.\n\n" + body
		}
		login := rv.User.Login
		if ps == 0 {
			ps, login = s.current, "" // nothing it could have seen: not as its author
		}
		if editedByOther(s.reviewEdits, rv.ID, login) {
			// Edited by someone else: not as the author, and no vote.
			login = ""
			if vote {
				body = notCounted + " someone other than its author edited it.\n\n" + body
			}
		}
		// Mirrored late (the bridge was busy, or down), it is older than
		// the reviewer's own vote in Gerrit since, which stands: an old
		// approval must not undo their veto (seventh audit).
		since := vote && known && !early && login != "" && asAuthor(login) &&
			s.votedSince(gerrit.AccountInfo{Username: authors[login]}, rv.SubmittedAt, anyCodeReview)
		if since {
			body = notCounted + " its author has voted in Gerrit since.\n\n" + body
		}
		if login != "" && c.bodyTooFresh(s, "review/"+strconv.FormatInt(rv.ID, 10), rv.SubmittedAt, rv.Body) {
			continue
		}
		f := false
		key := "review/" + strconv.FormatInt(rv.ID, 10)
		add(key, login, ghComment{kindReviewBody, rv.ID, rv.Body}, ps, gerrit.PatchSetLevel,
			gerrit.CommentInput{Message: gerritBody(rv.User.Login, rv.HTMLURL, body, asAuthor(login)), Unresolved: &f})
		if vote && known && !early && !since && reviewed == s.current && login != "" {
			// Design §6.4: approve = Code-Review +2 (or the most the user
			// may give), request changes = -1. Only as the user (Run-As);
			// the bridge never votes on someone's behalf as itself.
			v := -1
			if rv.State == "APPROVED" {
				v = 2
			}
			if b := batches[batchKey(key, ps, login)]; b != nil { // nil: posted already
				b.labels = map[string]int{"Code-Review": v}
			}
		}
	}
	for _, ic := range s.ics {
		if c.mine(ic.User.Login) || ownMirror(s.edits, ic.ID, ic.User.Login, ic.Body) || m.byGitHub[ghKey(kindIssueComment, ic.ID)] != nil {
			continue
		}
		f := false
		login := ic.User.Login
		if editedByOther(s.edits, ic.ID, ic.User.Login) {
			login = "" // edited by someone else: not as the author
		}
		if login != "" && c.tooFresh(s, lastChanged(ic), ic.Body) {
			continue
		}
		ps := s.seen(ic.CreatedAt)
		if ps == 0 {
			ps, login = s.current, "" // nothing it could have seen: not as its author
		}
		add("issue/"+strconv.FormatInt(ic.ID, 10), login, ghComment{kindIssueComment, ic.ID, ic.Body}, ps, gerrit.PatchSetLevel,
			gerrit.CommentInput{Message: gerritBody(ic.User.Login, ic.HTMLURL, ic.Body, asAuthor(login)), Unresolved: &f})
	}
	for _, k := range order {
		b := batches[k]
		if c.DryRun {
			c.Logger.Info("dry run: would mirror GitHub comments to Gerrit", "change", n, "pr", pr, "batch", k, "files", len(b.comments))
			continue
		}
		err := c.postBatch(ctx, n, b.login, b.author, b.ps, b.comments, b.plain, b.labels)
		var ge *gerrit.Error
		if errors.As(err, &ge) && (ge.Status == http.StatusBadRequest || ge.Status == http.StatusConflict || ge.Status == http.StatusRequestEntityTooLarge) {
			// Gerrit will never take it (a change's comment limits, say):
			// recorded as refused so it is not retried, and the rest of
			// the change still syncs. Otherwise anyone could stop a
			// change's sync, /submit and votes with one bad comment.
			c.Logger.Warn("Gerrit refused GitHub comments; not mirroring them", "change", n, "pr", pr, "batch", k, "err", err)
			for _, src := range b.srcs {
				m.add(state.Comment{GerritID: refusedID(src), GitHubID: src.id, Kind: src.kind, Origin: "github", BodyHash: hashString(src.body)})
			}
			continue
		}
		if err != nil {
			return true, fmt.Errorf("posting %s to change %d: %w", k, n, err)
		}
		c.Logger.Info("mirrored GitHub comments to Gerrit", "change", n, "pr", pr, "batch", k, "patch_set", b.ps)
	}
	return len(order) > 0 && !c.DryRun, nil
}

// batchKey names the batch of GitHub comments that key's source (a review,
// an issue comment) posts on patch set ps as login ("" for the bridge).
func batchKey(key string, ps int, login string) string {
	return key + "|" + strconv.Itoa(ps) + "|" + login
}

// refusedID stands in for the Gerrit comment of a GitHub comment Gerrit
// refused: no Gerrit comment has it, so nothing replies to or edits it.
func refusedID(src ghComment) string { return "refused:" + ghKey(src.kind, src.id) }

// maxGerritComment bounds what the bridge posts as one Gerrit comment,
// under Gerrit's change.commentSizeLimit (16 KiB by default).
const maxGerritComment = 12 << 10

// limitComment shortens body to maxGerritComment bytes (on a UTF-8
// boundary), saying where the rest is.
func limitComment(body, url string) string {
	if len(body) <= maxGerritComment {
		return body
	}
	cut := maxGerritComment
	for cut > 0 && !utf8.RuneStart(body[cut]) {
		cut--
	}
	return body[:cut] + fmt.Sprintf("\n\n[… too long for Gerrit; the rest is on [GitHub](%s)]", url)
}

// ghComment identifies a GitHub comment being mirrored.
type ghComment struct {
	kind string
	id   int64
	body string
}

// claim maps src to a Gerrit comment the bridge already posted for it and
// reports whether it found one. Comments posted as their author carry no
// link back to GitHub, so the Gerrit copy is recognised by what was
// posted: a bridge post (by the bridge, or tagged as a mirror by user),
// not mapped yet, at the same place, with the same text. Identical
// comments pair up oldest first. This is how a posted comment gets mapped
// on the next pass, and why a crash between posting and saving the map
// does not post it twice.
func (c *Comments) claim(s *commentSnapshot, m *commentMap, claimed map[string]bool, user string, src ghComment,
	ps int, path string, ci gerrit.CommentInput, plain ...string) bool {
	texts := []string{strings.TrimSpace(ci.Message), strings.TrimSpace(byBridgeFor(ci.Message))}
	for _, p := range plain {
		texts = append(texts, strings.TrimSpace(p), strings.TrimSpace(byBridgeFor(p)))
	}
	for i := range s.gerrit { // oldest first
		gc := &s.gerrit[i]
		if claimed[gc.ID] || m.byGerrit[gc.ID] != nil || !c.bridgePost(gc) || gc.PatchSet != ps || gc.Path != path ||
			gc.InReplyTo != ci.InReplyTo || gc.Line != ci.Line || !sameRange(gc.Range, ci.Range) || gc.Side != ci.Side ||
			!slices.Contains(texts, strings.TrimSpace(gc.Message)) {
			continue
		}
		if gc.Author.AccountID != c.BridgeAccount && (user == "" || !strings.EqualFold(gc.Author.Username, user)) {
			continue
		}
		claimed[gc.ID] = true
		m.add(state.Comment{GerritID: gc.ID, GitHubID: src.id, Kind: src.kind, Origin: "github", BodyHash: hashString(src.body)})
		return true
	}
	return false
}

func sameRange(a, b *gerrit.Range) bool {
	if a == nil || b == nil {
		return a == b
	}
	return *a == *b
}

// lineLen is the length of a line, for a Gerrit range ending at its end.
func (c *Comments) lineLen(ctx context.Context, n, ps int, path string, line int, side string) int {
	rev := strconv.Itoa(ps)
	if side == "PARENT" {
		return 0 // whole lines; Gerrit accepts end_character 0 on the next line
	}
	content, err := c.Gerrit.FileContent(ctx, n, rev, path)
	if err != nil {
		return 0
	}
	lines := strings.Split(string(content), "\n")
	if line < 1 || line > len(lines) {
		return 0
	}
	return len(lines[line-1])
}

