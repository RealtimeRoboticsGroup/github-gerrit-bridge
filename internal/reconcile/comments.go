// dismissStale dismisses GitHub approvals and change requests that Gerrit
// no longer agrees with (design §6.4): the reviewer's Code-Review vote is
// now the other way or gone, because they changed it in Gerrit, a new
// patch set reset it, or it was never cast (made on an older patch set).
// Only reviews already mirrored count, so a vote still on its way is not
// mistaken for a missing one; GitHub then shows what Gerrit counts.
func (c *Comments) dismissStale(ctx context.Context, n, pr int, s *commentSnapshot, m *commentMap) error {
	if c.Users == nil || c.GerritAs == nil {
		return nil // no votes are cast from GitHub
	}
	// GitHub's review state per reviewer is their latest approval, change
	// request or dismissal; comments do not change it.
	latest := map[string]github.Review{}
	for _, rv := range s.reviews {
		switch rv.State {
		case "APPROVED", "CHANGES_REQUESTED", "DISMISSED":
			k := strings.ToLower(rv.User.Login)
			if cur, ok := latest[k]; !ok || !rv.SubmittedAt.Before(cur.SubmittedAt) {
				latest[k] = rv
			}
		}
	}
	var dismissals map[int64]github.Dismissal
	for _, login := range sortedStringKeys(latest) {
		rv := latest[login]
		mc := m.byGitHub[ghKey(kindReviewBody, rv.ID)]
		if c.mine(rv.User.Login) {
			continue
		}
		if rv.State == "DISMISSED" {
			// Mirrored or not: one dismissed while it was being mirrored
			// is never mapped, though its vote was cast (sixth audit).
			if err := c.dropDismissed(ctx, n, pr, rv, mc, s, &dismissals); err != nil {
				return err
			}
			continue
		}
		if mc == nil || strings.HasPrefix(mc.GerritID, "refused:") {
			continue // not mirrored, or Gerrit would not take it: nothing to disagree with
		}
		if gc := s.byID[mc.GerritID]; rv.State == "CHANGES_REQUESTED" && gc != nil && strings.Contains(gc.Message, notCounted) {
			// It cast no vote (made on a commit only just pushed, say):
			// dismissed for disagreeing with the reviewer's older +2,
			// their objection would be gone from both sides (seventh
			// audit). Gerrit has its text, saying it was not counted.
			continue
		}
		user, ok := c.Users.GerritUserFor(ctx, rv.User)
		if !ok {
			continue // never voted: the review is only text in Gerrit
		}
		v, voted := 0, false
		for _, a := range s.labels["Code-Review"].All {
			if strings.EqualFold(a.Username, user) && a.Value != 0 {
				v, voted = a.Value, true
			}
		}
		if (rv.State == "APPROVED" && v > 0) || (rv.State == "CHANGES_REQUESTED" && v < 0) {
			continue
		}
		now := "has no Code-Review vote"
		if voted {
			now = "is now Code-Review " + voteString(v)
		}
		msg := fmt.Sprintf("In [Gerrit](%s), @%s %s on patch set %d.",
			c.Gerrit.ChangeURL(c.Project, n), rv.User.Login, now, s.current)
		if c.DryRun {
			c.Logger.Info("dry run: would dismiss GitHub review", "change", n, "pr", pr, "review", rv.ID, "reason", now)
			continue
		}
		if err := c.GitHub.DismissReview(ctx, pr, rv.ID, msg); err != nil {
			return fmt.Errorf("dismissing review %d on #%d: %w", rv.ID, pr, err)
		}
		c.Logger.Info("dismissed GitHub review Gerrit disagrees with", "change", n, "pr", pr, "review", rv.ID, "user", rv.User.Login, "state", rv.State, "gerrit", now)
	}
	return nil
}

// dropDismissed withdraws the Code-Review vote a GitHub approval cast once
// someone (a person, not GitHub, a bot or the bridge) dismisses that
// approval on GitHub (the owner's call, 2026-10-19): the reviewer's
// positive vote on the current patch set is reset to 0, as them, unless
// they voted for it again in Gerrit since. Gerrit dates a vote it copies
// to a new patch set by that patch set, so whether they did is read from
// their own change messages, which are never copied (sixth audit). Where
// the bridge cannot withdraw it, it says so on the change and the PR.
// mc is the review's mirror, if mapped.
func (c *Comments) dropDismissed(ctx context.Context, n, pr int, rv github.Review, mc *state.Comment, s *commentSnapshot, dismissals *map[int64]github.Dismissal) error {
	g, user := c.asUser(ctx, rv.User)
	if gerrit.AmbiguousUsername(user) {
		user = ""
	}
	reviewer := gerrit.AccountInfo{Username: user}
	if user == "" {
		// The login no longer maps to the account its review was
		// mirrored as (renamed, deactivated): the vote is still theirs.
		gc := (*gerrit.CommentInfo)(nil)
		if mc != nil {
			gc = s.byID[mc.GerritID]
		}
		if gc == nil || gc.Author.AccountID == c.BridgeAccount {
			return nil // never voted
		}
		reviewer = gc.Author
	}
	var vote *gerrit.ApprovalInfo
	for _, a := range s.labels["Code-Review"].All {
		if sameAccount(a.AccountInfo, reviewer) && a.Value > 0 {
			vote = &a
		}
	}
	if vote == nil {
		return nil
	}
	if *dismissals == nil {
		ds, err := c.GitHub.Dismissals(ctx, pr)
		if err != nil {
			return err
		}
		*dismissals = ds
	}
	d, ok := (*dismissals)[rv.ID]
	if !ok || d.State != "approved" || d.Bot || d.Commit != "" || (d.By != "" && c.mine(d.By)) {
		// Not a person's call (§6.4: GitHub's own stale-approval
		// dismissals, on a push, leave the vote to Gerrit's copyCondition;
		// the bridge's dismiss only votes already gone). Nobody named is
		// a deleted account: still a person's.
		return nil
	}
	if s.votedSince(reviewer, d.At, positiveCodeReview) {
		return nil // voted again since
	}
	// Read again just before acting: the reviewer may have vetoed since
	// the snapshot, while every page of the PR's issue events, which
	// anyone can pad, was read (seventh audit). Gerrit has no
	// compare-and-set for votes; this keeps the window short.
	now, err := c.Gerrit.GetChange(ctx, n, "DETAILED_LABELS", "DETAILED_ACCOUNTS")
	if err != nil {
		return err
	}
	vote = nil
	for _, a := range now.Labels["Code-Review"].All {
		if sameAccount(a.AccountInfo, reviewer) && a.Value > 0 {
			vote = &a
		}
	}
	if vote == nil {
		return nil
	}
	by := "@" + d.By
	if d.By == "" {
		by = "A deleted GitHub account"
	}
	if c.DryRun {
		c.Logger.Info("dry run: would withdraw a dismissed approval's vote", "change", n, "pr", pr, "review", rv.ID, "user", user)
		return nil
	}
	if user == "" {
		return c.cannotWithdraw(ctx, n, pr, rv, s, vote, by, "the bridge no longer knows @"+rv.User.Login+"'s Gerrit account")
	}
	msg := fmt.Sprintf("Code-Review %s withdrawn: %s dismissed this approval on GitHub.", voteString(vote.Value), by)
	err = g.SetReview(ctx, n, strconv.Itoa(s.current), gerrit.ReviewInput{Message: forGerrit(msg), Tag: mirrorTag, Labels: map[string]int{"Code-Review": 0}})
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status < 500 {
		// Over the change's message limits, say, which anyone can fill
		// up (sixth audit): deleting the vote, which Gerrit still takes.
		c.Logger.Warn("Gerrit refused to reset a dismissed approval's vote; deleting it", "change", n, "user", user, "err", err)
		err = g.DeleteVote(ctx, n, "self", "Code-Review")
	}
	if errors.As(err, &ge) && ge.Status < 500 {
		c.Logger.Warn("Gerrit refused to withdraw a dismissed approval's vote", "change", n, "user", user, "err", err)
		return c.cannotWithdraw(ctx, n, pr, rv, s, vote, by, "Gerrit refused")
	}
	if err != nil {
		return fmt.Errorf("withdrawing %s's vote on change %d: %w", user, n, err)
	}
	c.Logger.Info("withdrew the vote of an approval dismissed on GitHub", "change", n, "pr", pr, "review", rv.ID, "user", user, "dismissed_by", d.By)
	return nil
}

// sameAccount reports whether a and b are one Gerrit account: by id, if
// both say, else by username.
func sameAccount(a, b gerrit.AccountInfo) bool {
	if a.AccountID != 0 && b.AccountID != 0 {
		return a.AccountID == b.AccountID
	}
	return a.Username != "" && strings.EqualFold(a.Username, b.Username)
}

// notCounted begins the Gerrit text of a review that cast no vote.
const notCounted = "Not counted as a vote:"

// positiveCodeReview matches the change message Gerrit writes when
// someone votes Code-Review up ("Patch Set 3: Code-Review+2", with any
// other labels); anyCodeReview when they vote it at all, reset it
// ("-Code-Review") or remove it.
var (
	positiveCodeReview = regexp.MustCompile(`\APatch Set \d+:(?: [^ \n]+)*? Code-Review\+[1-9]`)
	anyCodeReview      = regexp.MustCompile(`\A(?:Patch Set \d+:(?: [^ \n]+)*? (?:Code-Review[+-]\d|-Code-Review)|Removed Code-Review[+-]?\d)`)
)

// votedSince reports whether reviewer voted Code-Review in Gerrit after
// t themselves, not through the bridge, as re matches the message.
func (s *commentSnapshot) votedSince(reviewer gerrit.AccountInfo, t time.Time, re *regexp.Regexp) bool {
	for _, m := range s.messages {
		at, err := time.Parse("2006-01-02 15:04:05.999999999", m.Date)
		if err == nil && at.After(t) && sameAccount(m.Author, reviewer) && !isBridgeTag(m.Tag) && re.MatchString(m.Message) {
			return true
		}
	}
	return false
}

// cannotWithdraw says, once, on change n and its PR, that the vote of
// dismissed review rv still stands, and why: whoever submits must know.
// Gerrit refusing the message (the change's limits, again) stops nothing
// else.
func (c *Comments) cannotWithdraw(ctx context.Context, n, pr int, rv github.Review, s *commentSnapshot, vote *gerrit.ApprovalInfo, by, why string) error {
	// Said once on each side, as only the bridge can say it: anyone's
	// text the bridge mirrors is posted by its accounts too, so a marker
	// that text could carry would keep the notice from being posted
	// (seventh audit). On GitHub, a bridge marker, which mirrored text
	// cannot carry (forGitHub), in a comment nobody else edited; in
	// Gerrit, a tag nothing mirrored has.
	marker := fmt.Sprintf("(GitHub review %d)", rv.ID)
	ghMarker := fmt.Sprintf("<!-- bridge:withdraw/%d -->", rv.ID)
	msg := fmt.Sprintf("%s dismissed @%s's approval on GitHub, but the bridge could not withdraw its Code-Review %s in Gerrit: %s. Remove the vote in Gerrit if it should not count. %s",
		by, rv.User.Login, voteString(vote.Value), why, marker)
	if !slices.ContainsFunc(s.ics, func(ic github.IssueComment) bool {
		return c.mine(ic.User.Login) && !editedByOther(s.edits, ic.ID, ic.User.Login) && strings.Contains(ic.Body, ghMarker)
	}) {
		if _, err := c.GitHub.CreateIssueComment(ctx, pr, forGitHub(msg)+"\n\n"+noticeMarker+"\n"+ghMarker); err != nil {
			return err
		}
	}
	if slices.ContainsFunc(s.messages, func(m gerrit.ChangeMessage) bool {
		return m.Author.AccountID == c.BridgeAccount && m.Tag == withdrawTag && strings.Contains(m.Message, marker)
	}) {
		return nil
	}
	err := c.Gerrit.SetReview(ctx, n, strconv.Itoa(s.current), gerrit.ReviewInput{Message: forGerrit(msg), Tag: withdrawTag})
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status < 500 {
		c.Logger.Warn("Gerrit refused a notice", "change", n, "err", err)
		return nil
	}
	return err
}

// --- resolution ---

// edited reports whether a GitHub comment was changed after it was posted.
// editedByOther reports whether comment id was last edited by someone
// other than its author (edits from GitHub.Edits).
func editedByOther(edits map[int64]string, id int64, author string) bool {
	editor, ok := edits[id]
	return ok && !strings.EqualFold(editor, author)
}

// gerritResolved is whether a Gerrit thread is resolved: the unresolved
// flag of its latest comment.
func gerritResolved(s *commentSnapshot, root string) bool {
	children := map[string][]*gerrit.CommentInfo{}
	for i := range s.gerrit {
		gc := &s.gerrit[i]
		if gc.InReplyTo != "" {
			children[gc.InReplyTo] = append(children[gc.InReplyTo], gc)
		}
	}
	last := s.byID[root]
	queue := []string{root}
	for len(queue) > 0 {
		id := queue[0]
		queue = queue[1:]
		for _, ch := range children[id] {
			if ch.Updated > last.Updated || (ch.Updated == last.Updated && ch.ID > last.ID) {
				last = ch
			}
			queue = append(queue, ch.ID)
		}
	}
	return !last.Unresolved
}

func (c *Comments) syncResolution(ctx context.Context, n, pr int, s *commentSnapshot, threads map[string]*state.Thread) error {
	ghResolved := map[string]bool{}
	resolver := map[string]github.User{} // thread -> who resolved it
	for _, t := range s.threads {
		ghResolved[t.ID] = t.IsResolved
		resolver[t.ID] = t.ResolvedBy
	}
	roots := make([]string, 0, len(threads))
	for r := range threads {
		roots = append(roots, r)
	}
	slices.Sort(roots)
	for _, root := range roots {
		t := threads[root]
		if t.GitHubThread == "" || s.byID[root] == nil {
			continue
		}
		gr := gerritResolved(s, root)
		hr := ghResolved[t.GitHubThread]
		switch {
		case gr == hr:
			t.Resolved = gr
		case gr != t.Resolved:
			// Gerrit changed (or both did: Gerrit wins).
			if err := c.GitHub.SetThreadResolved(ctx, t.GitHubThread, gr); err != nil {
				return err
			}
			c.Logger.Info("mirrored Gerrit resolution to GitHub", "change", n, "pr", pr, "thread", root, "resolved", gr)
			t.Resolved = gr
		default:
			// GitHub changed.
			last := lastInThread(s, root)
			unresolved := !hr
			msg := "Resolved on GitHub."
			if !hr {
				msg = "Unresolved on GitHub."
			}
			_, user := c.asUser(ctx, resolver[t.GitHubThread])
			err := c.setReviewAs(ctx, resolver[t.GitHubThread].Login, user, n, strconv.Itoa(last.PatchSet), gerrit.ReviewInput{
				Comments: map[string][]gerrit.CommentInput{last.Path: {{
					InReplyTo: last.ID, Line: last.Line, Range: last.Range, Side: last.Side,
					Message: msg, Unresolved: &unresolved,
				}}},
			})
			if err != nil {
				return err
			}
			c.Logger.Info("mirrored GitHub resolution to Gerrit", "change", n, "pr", pr, "thread", root, "resolved", hr)
			t.Resolved = hr
		}
	}
	return nil
}

func lastInThread(s *commentSnapshot, root string) *gerrit.CommentInfo {
	last := s.byID[root]
	inThread := map[string]bool{root: true}
	for i := range s.gerrit { // sorted by time, so parents come first
		gc := &s.gerrit[i]
		if inThread[gc.InReplyTo] {
			inThread[gc.ID] = true
			last = gc
		}
	}
	return last
}

// updateStateFn loads, mutates and saves change n's state, retrying once
// on a concurrent write.
func updateStateFn(ctx context.Context, store *state.Store, n int, msg string, f func(*state.Change)) error {
	for try := 0; ; try++ {
		st, err := store.Load(ctx, n)
		if err != nil {
			return err
		}
		f(st)
		err = store.Save(ctx, n, st, msg)
		if errors.Is(err, state.ErrConflict) && try == 0 {
			continue
		}
		return err
	}
}

var (
	// "Patch Set 3: Code-Review+2 Verified-1" (or "Patch Set 3:") header.
	messageHeader = regexp.MustCompile(`^Patch Set \d+:[^\n]*\n*`)
	// "(2 comments)" summary, which Gerrit adds when inline comments
	// (mirrored separately) came with the reply.
	commentCount = regexp.MustCompile(`(?m)^\(\d+ (inline )?comments?\)\s*$`)
)

// messageText is the human-written part of a change message, or "" if the
// message should not be mirrored: Gerrit's own messages, the bridge's,
// CI's, and messages that only carried votes or inline comments.
func (c *Comments) messageText(msg gerrit.ChangeMessage) string {
	if msg.Author.AccountID == c.BridgeAccount || msg.Author.AccountID == 0 || strings.HasPrefix(msg.Tag, "autogenerated:") || isBridgeTag(msg.Tag) {
		return ""
	}
	if c.CIMessage != nil && c.CIMessage.MatchString(msg.Message) {
		return ""
	}
	text := messageHeader.ReplaceAllString(msg.Message, "")
	text = commentCount.ReplaceAllString(text, "")
	return strings.TrimSpace(text)
}

var inlineCount = regexp.MustCompile(`\(\d+ (inline )?comments?\)`)

// voteToken is one vote in a change message header: "Code-Review+2", or
// "-Code-Review" for a removed vote.
var voteToken = regexp.MustCompile(`^(-?)([A-Za-z][A-Za-z0-9-]*?)([+-]\d+)?$`)

// messageVotes renders the votes in a change message's "Patch Set N: ..."
// header ("Code-Review +2, Verified removed"), or "" if it has none.
func messageVotes(message string) string {
	header := messageHeader.FindString(message)
	if header == "" {
		return ""
	}
	_, rest, _ := strings.Cut(strings.TrimSpace(header), ":")
	rest = inlineCount.ReplaceAllString(rest, "")
	var votes []string
	for _, tok := range strings.Fields(rest) {
		m := voteToken.FindStringSubmatch(tok)
		switch {
		case m == nil:
			return "" // not a votes-only header
		case m[1] == "-" && m[3] == "":
			votes = append(votes, m[2]+" removed")
		case m[1] == "" && m[3] != "":
			if m[3] == "+0" || m[3] == "-0" {
				votes = append(votes, m[2]+" removed")
			} else {
				votes = append(votes, m[2]+" "+m[3])
			}
		default:
			return ""
		}
	}
	return strings.Join(votes, ", ")
}

func (c *Comments) messageURL(n int, msg gerrit.ChangeMessage) string {
	return fmt.Sprintf("%s#message-%s", c.Gerrit.ChangeURL(c.Project, n), msg.ID)
}

// --- suggestions (design §8) ---

var suggestionOpen = regexp.MustCompile("(?m)^(```+)suggestion[^\n]*\n")

// toSuggestion renders a Gerrit fix suggestion as a GitHub suggestion
// block, and the lines it must be anchored on. Only a single replacement in
// the commented file, on the revision side, converts.
func (c *Comments) toSuggestion(ctx context.Context, n int, gc *gerrit.CommentInfo) (string, int, int, bool) {
	if len(gc.FixSuggestions) == 0 || gc.Side == "PARENT" {
		return "", 0, 0, false
	}
	reps := gc.FixSuggestions[0].Replacements
	if len(reps) != 1 || reps[0].Path != gc.Path {
		return "", 0, 0, false
	}
	content, err := c.Gerrit.FileContent(ctx, n, strconv.Itoa(gc.PatchSet), gc.Path)
	if err != nil {
		return "", 0, 0, false
	}
	text, first, last, ok := applyReplacement(strings.Split(string(content), "\n"), reps[0])
	if !ok {
		return "", 0, 0, false
	}
	f := suggestionFence(text)
	return f + "suggestion\n" + text + f, first, last, true
}

// applyReplacement returns the new text of the whole lines a replacement
// touches (ending in a newline unless empty), and those lines.
func applyReplacement(lines []string, r gerrit.FixReplacement) (string, int, int, bool) {
	rg := r.Range
	first, last := rg.StartLine, rg.EndLine
	wholeLines := rg.EndCharacter == 0 && last > first
	if wholeLines {
		last-- // ends at the start of EndLine
	}
	if first < 1 || last < first || last > len(lines) || rg.StartCharacter > len(lines[first-1]) {
		return "", 0, 0, false
	}
	prefix := lines[first-1][:rg.StartCharacter]
	suffix := ""
	if !wholeLines {
		if rg.EndCharacter > len(lines[last-1]) {
			return "", 0, 0, false
		}
		suffix = lines[last-1][rg.EndCharacter:]
	}
	text := prefix + r.Replacement + suffix
	if wholeLines {
		text = strings.TrimSuffix(text, "\n")
	}
	if text != "" {
		text += "\n"
	}
	return text, first, last, true
}

// fromSuggestion turns a GitHub suggestion block into a Gerrit fix on
// lines first..last of path, returning the message without the block.
func fromSuggestion(body, path string, first, last, lastLen int) (string, []gerrit.FixSuggestion) {
	om := suggestionOpen.FindStringSubmatchIndex(body)
	if om == nil || first < 1 || last < first {
		return body, nil
	}
	fence := body[om[2]:om[3]]
	end := strings.Index(body[om[1]:], fence)
	if end < 0 {
		return body, nil
	}
	end += om[1]
	replacement := strings.TrimSuffix(body[om[1]:end], "\n")
	msg := strings.TrimSpace(body[:om[0]] + "_(Suggested change attached: use Apply fix.)_" + body[end+len(fence):])
	return msg, []gerrit.FixSuggestion{{
		Description: "Suggested on GitHub",
		Replacements: []gerrit.FixReplacement{{
			Path:        path,
			Range:       gerrit.Range{StartLine: first, EndLine: last, EndCharacter: lastLen},
			Replacement: replacement,
		}},
	}}
}

// portFromGitHub maps lines of path in GitHub commit commit to the first
// recorded revision whose GitHub head contains commit.
func (c *Comments) portFromGitHub(ctx context.Context, s *commentSnapshot, commit, path string, first, last int) (int, int, int, bool) {
	for _, r := range s.revisions {
		if r.GitHubSHA == "" {
			continue
		}
		if ok, err := c.GitHub.IsAncestor(ctx, commit, r.GitHubSHA); err != nil || !ok {
			continue
		}
		oldC, err1 := c.GitHub.FileAt(ctx, commit, path)
		newC, err2 := c.GitHub.FileAt(ctx, r.GitHubSHA, path)
		if err1 != nil || err2 != nil {
			return 0, 0, 0, false
		}
		f, l, ok := anchor.NewMap(anchor.Lines(string(oldC)), anchor.Lines(string(newC))).Range(first, last)
		if !ok {
			return 0, 0, 0, false
		}
		return r.PatchSet, f, l, true
	}
	return 0, 0, 0, false
}

// --- edits (design §8) ---

// githubBody returns a GitHub comment's current body, author and URL.
func (s *commentSnapshot) githubBody(kind string, id int64) (body, login, url string, ok bool) {
	switch kind {
	case kindReviewComment:
		if rc := s.rcByID[id]; rc != nil {
			return rc.Body, rc.User.Login, rc.HTMLURL, true
		}
	case kindIssueComment:
		for _, ic := range s.ics {
			if ic.ID == id {
				return ic.Body, ic.User.Login, ic.HTMLURL, true
			}
		}
	case kindReviewBody:
		for _, rv := range s.reviews {
			if rv.ID == id {
				return rv.Body, rv.User.Login, rv.HTMLURL, true
			}
		}
	}
	return "", "", "", false
}

// mirrorEdits mirrors comments edited since they were mirrored.
//
// GitHub -> Gerrit: published Gerrit comments are immutable, so an edit
// becomes a reply in the same thread with the new text. The reply links
// the PR, not the comment, so it is never taken for a mirror of a new
// GitHub comment. Deleted GitHub comments are left alone.
//
// Gerrit -> GitHub: Gerrit comments only change when an administrator
// deletes their content; the bridge's GitHub copy is updated to match.
//
// BodyHash in comments.json is the hash of the source side's text as last
// mirrored.
func (c *Comments) mirrorEdits(ctx context.Context, n, pr int, s *commentSnapshot, m *commentMap) (bool, error) {
	posted := false
	for _, k := range sortedStringKeys(m.byGitHub) {
		mc := m.byGitHub[k]
		gc := s.byID[mc.GerritID]
		body, login, url, ok := s.githubBody(mc.Kind, mc.GitHubID)
		if !ok || gc == nil {
			continue
		}
		switch mc.Origin {
		case "github":
			h := hashString(body)
			if mc.BodyHash == h {
				continue
			}
			if mc.BodyHash == "" {
				mc.BodyHash = h // first sight
				continue
			}
			if c.DryRun {
				c.Logger.Info("dry run: would mirror GitHub edit to Gerrit", "change", n, "github_id", mc.GitHubID)
				continue
			}
			prURL, _, _ := strings.Cut(url, "#")
			f := false
			ci := gerrit.CommentInput{
				InReplyTo: gc.ID, Line: gc.Line, Range: gc.Range, Side: gc.Side,
				Message:    fmt.Sprintf("**@%s**'s comment was edited on GitHub ([GitHub](%s)):\n\n%s", login, prURL, forGerrit(limitComment(strings.TrimSpace(body), url))),
				Unresolved: &f,
			}
			if mc.Kind == kindReviewComment {
				unresolved := !gerritResolved(s, threadRoot(s, gc.ID))
				ci.Unresolved = &unresolved
			}
			// As the bridge: anyone with write access can edit a comment,
			// and GitHub does not say who did.
			err := c.Gerrit.SetReview(ctx, n, strconv.Itoa(gc.PatchSet), gerrit.ReviewInput{
				Tag:      commentTag,
				Comments: map[string][]gerrit.CommentInput{gc.Path: {ci}},
			})
			var ge *gerrit.Error
			if errors.As(err, &ge) && (ge.Status == http.StatusBadRequest || ge.Status == http.StatusConflict || ge.Status == http.StatusRequestEntityTooLarge) {
				// As for new comments: one Gerrit will not take must not
				// stop the change's sync.
				c.Logger.Warn("Gerrit refused a GitHub edit; not mirroring it", "change", n, "github_id", mc.GitHubID, "err", err)
				mc.BodyHash = h
				continue
			}
			if err != nil {
				return posted, err
			}
			c.Logger.Info("mirrored GitHub edit to Gerrit", "change", n, "pr", pr, "github_id", mc.GitHubID)
			mc.BodyHash = h
			posted = true
		case "gerrit":
			if editor, ok := s.edits[mc.GitHubID]; ok && !c.byBridge(editor) {
				// The GitHub copy of a Gerrit comment was edited on
				// GitHub: Gerrit comments only change in Gerrit, so put
				// it back (text and marker).
				if c.DryRun {
					c.Logger.Info("dry run: would restore edited copy of a Gerrit comment", "change", n, "github_id", mc.GitHubID, "editor", editor)
					continue
				}
				a := c.anchorFor(ctx, n, s, gc)
				nb := c.ghBody(n, gc, s.current, strings.TrimSpace(a.note+
					"\n\n<sub>(Restored by the bridge: this mirrors a Gerrit comment, which can only change in Gerrit.)</sub>"), a.suggestion)
				if err := c.updateGitHub(ctx, mc, nb); err != nil {
					return posted, err
				}
				c.Logger.Warn("restored a Gerrit comment's GitHub copy edited on GitHub", "change", n, "pr", pr, "github_id", mc.GitHubID, "editor", editor)
				mc.BodyHash = hashString(gc.Message)
				continue
			}
			h := hashString(gc.Message)
			if mc.BodyHash == h {
				continue
			}
			if mc.BodyHash == "" || mc.BodyHash == hashString(body) {
				mc.BodyHash = h
				continue
			}
			if c.DryRun {
				continue
			}
			nb := c.ghBody(n, gc, s.current, "<sub>(Changed in Gerrit.)</sub>", "")
			if err := c.updateGitHub(ctx, mc, nb); err != nil {
				return posted, err
			}
			mc.BodyHash = h
		}
	}
	return posted, nil
}

// updateGitHub replaces the body of the bridge's GitHub copy mc.
func (c *Comments) updateGitHub(ctx context.Context, mc *state.Comment, body string) error {
	if mc.Kind == kindReviewComment {
		return c.GitHub.UpdateReviewComment(ctx, mc.GitHubID, body)
	}
	return c.GitHub.UpdateIssueComment(ctx, mc.GitHubID, body)
}

// threadRoot walks in_reply_to up to a thread's first comment.
func threadRoot(s *commentSnapshot, id string) string {
	seen := map[string]bool{}
	for !seen[id] {
		seen[id] = true
		gc := s.byID[id]
		if gc == nil || gc.InReplyTo == "" {
			return id
		}
		id = gc.InReplyTo
	}
	return id
}

func hasFixes(cs map[string][]gerrit.CommentInput) bool {
	for _, l := range cs {
		for _, ci := range l {
			if len(ci.FixSuggestions) > 0 {
				return true
			}
		}
	}
	return false
}

// bridgePost reports whether a Gerrit comment was posted by the bridge:
// by its account, or (Run-As) with a bridge tag.
func (c *Comments) bridgePost(gc *gerrit.CommentInfo) bool {
	return gc.Author.AccountID == c.BridgeAccount || isBridgeTag(gc.Tag)
}

// as returns the Gerrit client to post GitHub user login's content with:
// their own account if they have one and Run-As is set up, else the
// bridge's.
func (c *Comments) asUser(ctx context.Context, gh github.User) (GerritAPI, string) {
	if c.GerritAs == nil || c.Users == nil || gh.Login == "" {
		return c.Gerrit, ""
	}
	if user, ok := c.Users.GerritUserFor(ctx, gh); ok {
		return c.GerritAs(user), user
	}
	return c.Gerrit, ""
}

// setReviewAs posts in as GitHub user login's Gerrit account user (Run-As;
// "": as the bridge), falling back to the bridge if Gerrit refuses to let
// the bridge act for them. user is the account in was written for, looked
// up once: looked up again, it could come back otherwise (a lookup error,
// a rename), and words written to be its author's would be posted as the
// bridge's own (sixth audit).
func (c *Comments) setReviewAs(ctx context.Context, login, user string, n int, rev string, in gerrit.ReviewInput) error {
	if user == "" || gerrit.AmbiguousUsername(user) || c.GerritAs == nil {
		in.Tag, in.Labels = commentTag, nil
		return c.Gerrit.SetReview(ctx, n, rev, in)
	}
	g := c.GerritAs(user)
	in.Tag = mirrorTag
	err := g.SetReview(ctx, n, rev, in)
	var ge *gerrit.Error
	if len(in.Labels) == 0 && errors.As(err, &ge) && (ge.Status == http.StatusForbidden || ge.Status == http.StatusUnprocessableEntity) {
		// With votes, a refusal may be about the vote: the caller lowers
		// or drops it. The bridge itself never votes for anyone.
		c.Logger.Warn("Run-As refused; posting as the bridge", "change", n, "user", user, "err", err)
		in.Tag, in.Labels = commentTag, nil
		// The comments were written for posting as their author, so say
		// whose they are, and defuse them as anything the bridge posts.
		in.Message = strings.TrimSpace(fmt.Sprintf("From @%s on GitHub.\n\n%s", login, forGerrit(in.Message)))
		comments := map[string][]gerrit.CommentInput{}
		for path, cs := range in.Comments {
			for _, ci := range cs {
				ci.Message = byBridgeFor(ci.Message)
				comments[path] = append(comments[path], ci)
			}
		}
		in.Comments = comments
		return c.Gerrit.SetReview(ctx, n, rev, in)
	}
	return err
}

// byBridgeFor is a comment written to be posted as its GitHub author, as
// the bridge posts it when Run-As is refused: said to be someone else's,
// and defused. It never starts with the attribution header recover()
// reads back, whatever the author wrote.
func byBridgeFor(msg string) string {
	return "(From GitHub; posted by the bridge.)\n\n" + forGerrit(msg)
}

// castVote sets labels as login's account user, or Code-Review +1 if +2
// is refused.
func (c *Comments) castVote(ctx context.Context, login, user string, n int, rev string, labels map[string]int) {
	err := c.setReviewAs(ctx, login, user, n, rev, gerrit.ReviewInput{Labels: labels})
	var ge *gerrit.Error
	if errors.As(err, &ge) && (ge.Status == http.StatusForbidden || ge.Status == http.StatusBadRequest) && labels["Code-Review"] == 2 {
		err = c.setReviewAs(ctx, login, user, n, rev, gerrit.ReviewInput{Labels: map[string]int{"Code-Review": 1}})
	}
	if err != nil {
		c.Logger.Warn("casting a vote without its comments", "change", n, "github_login", login, "err", err)
	}
}

// postBatch posts one GitHub review (or comment) to Gerrit as its author,
// degrading gracefully: fix suggestions become text on sites without the
// feature flag, and a vote the user may not give is lowered (+2 to +1)
// or dropped, so the comments always get through.
func (c *Comments) postBatch(ctx context.Context, n int, login, user string, ps int, comments, plain map[string][]gerrit.CommentInput, labels map[string]int) error {
	rev := strconv.Itoa(ps)
	// Not OmitDuplicateComments: claim already keeps a comment from being
	// posted twice, and two GitHub comments may well say the same thing
	// in the same place ("Done").
	in := gerrit.ReviewInput{Comments: comments}
	if user != "" {
		in.Labels = labels
	}
	want := in.Labels
	for attempt := 0; ; attempt++ {
		err := c.setReviewAs(ctx, login, user, n, rev, in)
		var ge *gerrit.Error
		switch {
		case err == nil:
			return nil
		case attempt > 4 || !errors.As(err, &ge):
			return err
		case len(want) > 0 && len(in.Comments) > 0 && in.Labels == nil &&
			(ge.Status == http.StatusBadRequest || ge.Status == http.StatusConflict || ge.Status == http.StatusRequestEntityTooLarge):
			// Gerrit will not take the comments, with or without the vote
			// (a change's comment limits, say): the vote alone, which it
			// still takes, so nobody's vote is lost to someone else's
			// comments. The caller records the comments as refused.
			c.castVote(ctx, login, user, n, rev, want)
			return err
		case ge.Status == http.StatusConflict && len(in.Labels) > 0:
			c.Logger.Info("Gerrit refused the vote (closed change?); posting the comment only", "change", n, "github_login", login, "err", err)
			in.Labels = nil
		case ge.Status >= 500 && hasFixes(in.Comments):
			// Fix suggestions in human comments are behind Gerrit's
			// experiments.enabled = GerritBackendFeature__allow_fix_suggestions_in_comments
			// flag; without it, keep the suggestion as text.
			c.Logger.Warn("Gerrit refused fix suggestions; posting them as text", "change", n, "err", err)
			in.Comments = plain
		case (ge.Status == http.StatusForbidden || ge.Status == http.StatusBadRequest) && in.Labels["Code-Review"] == 2:
			c.Logger.Info("user may not give Code-Review+2; voting +1", "change", n, "github_login", login)
			in.Labels = map[string]int{"Code-Review": 1}
		case (ge.Status == http.StatusForbidden || ge.Status == http.StatusBadRequest) && len(in.Labels) > 0:
			c.Logger.Info("user may not vote; posting the comment only", "change", n, "github_login", login, "err", err)
			in.Labels = nil
		default:
			return err
		}
	}
}
