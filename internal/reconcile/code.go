// LinkTag tags the Gerrit change message that links a change to its PR.
const LinkTag = "autogenerated:github-bridge:link"

// Code mirrors Gerrit changes to GitHub branches, PRs and stacks (design
// §5.1, §5.4, §6.0, §6.6). It reconciles one target branch at a time.
type Code struct {
	Project string
	Gerrit  *gerrit.Client
	GitHub  *github.Client
	// GitHubURL is the repository's HTTPS clone URL. Mirror.Config must
	// hold gitmirror.CredentialHelper for https://github.com.
	GitHubURL     string
	Mirror        *gitmirror.Repo
	Store         *state.Store
	DefaultBranch string
	DryRun        bool
	Logger        *slog.Logger
	// Importer, if set, imports GitHub-born PRs before each reconcile.
	Importer *Importer
	// OnExported, if set, is called (under the branch lock) for each
	// change whose current patch set reached GitHub in this reconcile.
	OnExported func(ctx context.Context, n int) error
	// Identity maps GitHub logins to Gerrit usernames, and BridgeLogin is
	// the bridge's own GitHub login: closing or reopening a PR on GitHub
	// abandons or restores its change as whoever did it.
	Identity    Identity
	BridgeLogin string
	// BridgeUser is the bridge's Gerrit username, BridgeAccount its account.
	BridgeUser    string
	BridgeAccount int
	// Trusted reports whether a Gerrit account is in CI's trusted group
	// (known is false if that cannot be told). Only they, and a change's
	// owner, have their Gerrit patch sets pushed to a PR author's branch.
	Trusted func(ctx context.Context, account int) (trusted, known bool)

	// configCache remembers changesConfig answers by branch tip and
	// commit.
	wmu         sync.Mutex
	configCache map[string]bool

	// locks serializes reconciles of one target branch. The queue already
	// does for Branch keys; Change and PR keys resolve to a branch here.
	mu    sync.Mutex
	locks map[string]*branchLock
}

// branchLock is a mutex whose urgent waiters go first.
type branchLock struct {
	mu     sync.Mutex
	cond   *sync.Cond
	held   bool
	urgent int // urgent waiters
}

func (l *branchLock) lock(urgent bool) {
	l.mu.Lock()
	defer l.mu.Unlock()
	if urgent {
		l.urgent++
		defer func() { l.urgent-- }()
	}
	for l.held || (!urgent && l.urgent > 0) {
		l.cond.Wait()
	}
	l.held = true
}

func (l *branchLock) unlock() {
	l.mu.Lock()
	l.held = false
	l.cond.Broadcast()
	l.mu.Unlock()
}

func (c *Code) branchLock(branch string) *branchLock {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.locks == nil {
		c.locks = map[string]*branchLock{}
	}
	l := c.locks[branch]
	if l == nil {
		l = &branchLock{}
		l.cond = sync.NewCond(&l.mu)
		c.locks[branch] = l
	}
	return l
}

func (c *Code) lock(branch string) func() {
	l := c.branchLock(branch)
	l.lock(false)
	return l.unlock
}

// lockUrgent is lock, ahead of anyone waiting for it without urgency: a
// merge in Gerrit must reach the PRs before replication does (§6.7),
// whatever comment syncs are waiting.
func (c *Code) lockUrgent(branch string) func() {
	l := c.branchLock(branch)
	l.lock(true)
	return l.unlock
}

// maxPasses bounds plan/apply rounds per reconcile. New PRs need one pass
// to exist before a second can stack them and fill in the chain links.
const maxPasses = 5

// Reconcile mirrors the target branch named by k.Branch.
func (c *Code) Reconcile(ctx context.Context, k Key) error {
	branch := k.Branch
	defer c.lock(branch)()
	if c.Importer != nil {
		c.Importer.link = c.linkPR
		c.Importer.onImported = c.exported
		if err := c.Importer.Import(ctx, branch); err != nil {
			return fmt.Errorf("importing GitHub PRs for %s: %w", branch, err)
		}
	}
	handled := map[int]bool{} // PRs whose GitHub side was mirrored this time
	skip := map[int]bool{}    // changes whose PR GitHub refused an action on
	for pass := 0; pass < maxPasses; pass++ {
		snap, err := c.observe(ctx, branch)
		if err != nil {
			return fmt.Errorf("observing %s: %w", branch, err)
		}
		snap.hold(handled)
		if !c.DryRun {
			changed, err := c.mirrorPRStates(ctx, snap, handled)
			if err != nil {
				return fmt.Errorf("mirroring PR closes on %s: %w", branch, err)
			}
			edited, err := c.mirrorPREdits(ctx, snap, handled)
			if err != nil {
				return fmt.Errorf("mirroring PR edits on %s: %w", branch, err)
			}
			if changed || edited {
				continue // observe what changed in Gerrit
			}
		}
		plan := MakePlan(snap)
		plan.drop(skip)
		if len(plan.Actions) == 0 {
			if c.DryRun {
				c.Logger.Info("in sync", "branch", branch, "changes", len(plan.Desired))
				return nil
			}
			return c.record(ctx, snap, plan)
		}
		for _, a := range plan.Actions {
			c.Logger.Info(map[bool]string{true: "dry run: would", false: "applying"}[c.DryRun], "branch", branch, "action", a.String())
		}
		if c.DryRun {
			return nil
		}
		if err := c.apply(ctx, snap, plan, skip); err != nil {
			return err
		}
	}
	return fmt.Errorf("branch %s did not converge in %d passes", branch, maxPasses)
}

func (c *Code) changeURL(n int) string { return c.Gerrit.ChangeURL(c.Project, n) }

// withheldPaths are where GitHub reads repository configuration from:
// workflows (and the rest of .github/) on any branch pushed to the
// repository, and CODEOWNERS (also at the root and in docs/) on a PR's
// base branch, which for a stacked PR is a branch the bridge pushed.
var withheldPaths = []string{".github", "CODEOWNERS", "docs/CODEOWNERS"}

// withheldWhat names withheldPaths in notices.
const withheldWhat = ".github/ or CODEOWNERS"

// changesConfig reports whether commit has files under withheldPaths
// that branch's tip does not have as they are (an old base counts: it
// would bring back what the branch has changed since), or any commit of
// it not on branch changes them (a change below it, say, even if a later
// one changes them back). Neither needs a merge base.
func (c *Code) changesConfig(ctx context.Context, branch, commit string) (bool, error) {
	tip, err := c.Mirror.Git(ctx, nil, "rev-parse", "--verify", "refs/remotes/gerrit/heads/"+branch+"^{commit}")
	if err != nil {
		return false, err
	}
	key := strings.TrimSpace(string(tip)) + " " + commit
	c.wmu.Lock()
	w, ok := c.configCache[key]
	c.wmu.Unlock()
	if ok {
		return w, nil
	}
	// Only what it has there counts: lacking the branch's files is safe.
	_, err = c.Mirror.Git(ctx, nil, append([]string{"diff", "--quiet", "--no-renames", "--diff-filter=d", strings.TrimSpace(string(tip)), commit, "--"}, withheldPaths...)...)
	var xe *exec.ExitError
	switch {
	case err == nil:
		out, err := c.Mirror.Git(ctx, nil, append([]string{"rev-list", "--full-history", "-1", commit, "^" + strings.TrimSpace(string(tip)), "--"}, withheldPaths...)...)
		if err != nil {
			return false, err
		}
		w = strings.TrimSpace(string(out)) != ""
	case errors.As(err, &xe) && xe.ExitCode() == 1:
		w = true // differs
	default:
		return false, err
	}
	c.wmu.Lock()
	if c.configCache == nil || len(c.configCache) > 4096 {
		c.configCache = map[string]bool{}
	}
	c.configCache[key] = w
	c.wmu.Unlock()
	return w, nil
}

// withhold marks the open changes that change withheldPaths (design §7.1):
// anyone registered on Gerrit can upload one, and GitHub would run it,
// with the repository's secrets, from the branch the bridge pushes. Each
// gets a notice in Gerrit, once per patch set. Nothing here fails the
// branch: a change that cannot be checked is withheld, and a notice Gerrit
// will not take is not retried.
func (c *Code) withhold(ctx context.Context, s *Snapshot, branch string) error {
	s.Withheld = map[int]bool{}
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		if ch.Status != "NEW" || ch.Private {
			continue
		}
		w, err := c.changesConfig(ctx, branch, ch.Revision)
		if err != nil {
			c.Logger.Warn("cannot tell whether a change touches "+withheldWhat+"; withheld", "change", n, "err", err)
			s.Withheld[n] = true
			continue
		}
		if !w {
			continue
		}
		s.Withheld[n] = true
		if st := s.State[n]; c.DryRun || (st != nil && st.State.WithheldNotice == ch.PatchSet) {
			continue
		}
		msg := fmt.Sprintf("Patch set %d is not mirrored to GitHub: it changes %s (here, in a change below it, or by being based on an "+
			"older version of the branch), and GitHub would use that, with the repository's secrets, from the branch the bridge pushes. "+
			"Review it here, or rebase it.", ch.PatchSet, withheldWhat)
		if !c.notice(ctx, n, ch, msg) {
			continue
		}
		if err := c.updateState(ctx, n, "withheld notice", func(st *state.Change) { st.State.WithheldNotice = ch.PatchSet }); err != nil {
			return err
		}
		c.Logger.Info("withheld from GitHub: changes "+withheldWhat, "change", n, "patch_set", ch.PatchSet)
	}
	return nil
}

// notice posts msg on change n's current patch set as the bridge, and
// reports whether it is done with: posted, or refused for good (a 4xx,
// such as the change's comment limit), which is logged.
func (c *Code) notice(ctx context.Context, n int, ch *GerritChange, msg string) bool {
	err := c.Gerrit.SetReview(ctx, n, ch.Revision, gerrit.ReviewInput{Message: msg, Tag: commentTag})
	var ge *gerrit.Error
	switch {
	case err == nil:
		return true
	case errors.As(err, &ge) && ge.Status >= 400 && ge.Status < 500:
		c.Logger.Warn("Gerrit refused a notice; not posting it", "change", n, "err", err)
		return true
	default:
		c.Logger.Warn("posting a notice", "change", n, "err", err)
		return false
	}
}

// mayPushToAuthor reports whether a patch set uploaded in Gerrit by
// uploader (on their behalf by real, if not 0) may go to a GitHub-born
// PR's branch, which is its author's: only if each is the change's owner,
// the bridge, or in CI's trusted group. known is false if the group could
// not be read (then only the owner and the bridge count).
func mayPushToAuthor(ctx context.Context, trusted func(context.Context, int) (bool, bool), bridge, owner, uploader, real int) (ok, known bool) {
	known = true
	allowed := func(account int) bool {
		if account != 0 && (account == owner || account == bridge) {
			return true
		}
		if trusted == nil || account == 0 {
			return false
		}
		t, k := trusted(ctx, account)
		known = known && k
		return t && k
	}
	return allowed(uploader) && (real == 0 || allowed(real)), known
}

// markForeign marks the GitHub-born changes whose current patch set was
// uploaded, or uploaded on someone's behalf, in Gerrit by someone other
// than the change's owner, the bridge or a member of CI's trusted group
// (Snapshot.Foreign). Each gets a notice in Gerrit, once per patch set.
func (c *Code) markForeign(ctx context.Context, s *Snapshot) error {
	s.Foreign = map[int]bool{}
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		if ch.Status != "NEW" || !s.githubBorn(n) {
			continue
		}
		ok, known := mayPushToAuthor(ctx, c.Trusted, c.BridgeAccount, ch.OwnerID, ch.UploaderID, ch.RealUploaderID)
		if ok {
			continue
		}
		s.Foreign[n] = true
		if st := s.State[n]; c.DryRun || !known || (st != nil && st.State.ForeignNotice == ch.PatchSet) {
			continue
		}
		msg := fmt.Sprintf("Patch set %d is not pushed to the GitHub PR's branch, which is its author's: only the change's owner, "+
			"and members of CI's trusted group, have their patch sets pushed there.", ch.PatchSet)
		if !c.notice(ctx, n, ch, msg) {
			continue
		}
		if err := c.updateState(ctx, n, "foreign patch set notice", func(st *state.Change) { st.State.ForeignNotice = ch.PatchSet }); err != nil {
			return err
		}
		c.Logger.Info("not pushed to the author's branch: uploaded by someone else", "change", n, "patch_set", ch.PatchSet,
			"uploader", ch.UploaderID, "real_uploader", ch.RealUploaderID)
	}
	return nil
}

// observe gathers a Snapshot for branch from Gerrit, the mirror, GitHub
// and refs/bridge.
func (c *Code) observe(ctx context.Context, branch string) (*Snapshot, error) {
	s := &Snapshot{
		Branch: branch, DefaultBranch: c.DefaultBranch,
		Changes: map[int]*GerritChange{}, OnBranch: map[string]bool{},
		GitHubBranches: map[string]string{}, PRs: map[int]*github.PullRequest{},
		State: map[int]*state.Change{},
		Repo:  c.GitHub.Owner + "/" + c.GitHub.Repo,
	}
	infos, err := c.Gerrit.QueryChanges(ctx,
		"project:"+gerrit.QueryString(c.Project)+" branch:"+gerrit.QueryString(branch)+" status:open",
		"CURRENT_REVISION", "CURRENT_COMMIT", "DETAILED_ACCOUNTS")
	if err != nil {
		return nil, err
	}
	// Open PRs, listed up front: a closed change whose PR is still open
	// (a merge waiting for replication, design §6.7) stays in the snapshot,
	// so its PR is still managed and its head branch kept.
	openPRs, err := c.GitHub.ListPulls(ctx, "open")
	if err != nil {
		return nil, err
	}
	prOpen := map[int]bool{}
	for _, pr := range openPRs {
		prOpen[pr.Number] = true
	}
	// Changes we mirrored that may have closed since.
	open := map[int]bool{}
	for _, ci := range infos {
		open[ci.Number] = true
	}
	for _, n := range c.Store.ChangesOnBranch(branch) {
		st, err := c.Store.Load(ctx, n)
		if err != nil {
			return nil, err
		}
		s.State[n] = st
		if open[n] || (st.State.Lifecycle != "NEW" && !prOpen[st.State.PR]) {
			continue
		}
		ci, err := c.Gerrit.GetChange(ctx, n, "CURRENT_REVISION", "CURRENT_COMMIT", "DETAILED_ACCOUNTS")
		if err != nil {
			return nil, err
		}
		infos = append(infos, *ci)
	}

	refspecs := []string{"+refs/heads/" + branch + ":refs/remotes/gerrit/heads/" + branch}
	for _, ci := range infos {
		rev, ok := ci.Current()
		if !ok {
			continue
		}
		s.Changes[ci.Number] = &GerritChange{
			Number: ci.Number, ChangeID: ci.ChangeID, Status: ci.Status,
			WIP: ci.WorkInProgress, Private: ci.IsPrivate,
			Subject: rev.Commit.Subject, Message: rev.Commit.Message,
			PatchSet: rev.Number, Revision: ci.CurrentRevision, Parent: rev.Commit.Parent(),
			URL: c.changeURL(ci.Number), Owner: ci.Owner.Username, Uploader: rev.Uploader.Username,
			OwnerID: ci.Owner.AccountID, UploaderID: rev.Uploader.AccountID,
		}
		if rev.RealUploader != nil {
			s.Changes[ci.Number].RealUploaderID = rev.RealUploader.AccountID
		}
		if ci.Status == "NEW" && !ci.IsPrivate {
			refspecs = append(refspecs, "+"+rev.Ref+":refs/remotes/gerrit/"+strings.TrimPrefix(rev.Ref, "refs/"))
		}
		if s.State[ci.Number] == nil {
			st, err := c.Store.Load(ctx, ci.Number)
			if err != nil {
				return nil, err
			}
			s.State[ci.Number] = st
		}
	}
	if _, err := c.Mirror.Git(ctx, nil, append([]string{"fetch", "--quiet", "origin"}, refspecs...)...); err != nil {
		return nil, err
	}
	if err := c.withhold(ctx, s, branch); err != nil {
		return nil, err
	}
	if err := c.markForeign(ctx, s); err != nil {
		return nil, err
	}
	revs := map[string]bool{}
	for _, ch := range s.Changes {
		revs[ch.Revision] = true
	}
	for _, ch := range s.Changes {
		if ch.Parent == "" || revs[ch.Parent] || s.OnBranch[ch.Parent] {
			continue
		}
		_, err := c.Mirror.Git(ctx, nil, "merge-base", "--is-ancestor", ch.Parent, "refs/remotes/gerrit/heads/"+branch)
		var ge *gitmirror.Error
		switch {
		case err == nil:
			s.OnBranch[ch.Parent] = true
		case errors.As(err, &ge) && ge.Stderr == "":
			// Exit 1: not an ancestor.
		default:
			return nil, err
		}
	}

	// GitHub: bridge branches, PRs and stacks.
	env, err := c.githubEnv(ctx)
	if err != nil {
		return nil, err
	}
	// Which merged revisions has replication brought to GitHub yet?
	s.OnGitHubBranch = map[string]bool{}
	if _, err := c.Mirror.GitEnv(ctx, env, nil, "-c", fsckFetch, "fetch", "--quiet", c.GitHubURL,
		"+refs/heads/"+branch+":refs/remotes/github/heads/"+branch); err == nil {
		for _, ch := range s.Changes {
			if ch.Status != "MERGED" {
				continue
			}
			if _, err := c.Mirror.Git(ctx, nil, "merge-base", "--is-ancestor", ch.Revision, "refs/remotes/github/heads/"+branch); err == nil {
				s.OnGitHubBranch[ch.Revision] = true
			}
		}
	}
	out, err := c.Mirror.GitEnv(ctx, env, nil, "ls-remote", c.GitHubURL, "refs/heads/"+headPrefix+"*", "refs/heads/"+frozenPrefix+"*")
	if err != nil {
		return nil, err
	}
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		sha, ref, ok := strings.Cut(line, "\t")
		if !ok {
			continue
		}
		name := strings.TrimPrefix(ref, "refs/heads/")
		if strings.HasPrefix(name, headPrefix) || strings.HasPrefix(name, frozenPrefix) {
			s.GitHubBranches[name] = sha
		}
	}

	heads := map[string]bool{}
	for n, ch := range s.Changes {
		heads[s.head(n, ch.ChangeID)] = true
	}
	repoName := c.GitHub.Owner + "/" + c.GitHub.Repo
	for i := range openPRs {
		pr := &openPRs[i]
		if heads[pr.HeadKey(repoName)] {
			s.PRs[pr.Number] = pr
		}
	}
	for n, st := range s.State {
		if pr := st.State.PR; pr != 0 && s.PRs[pr] == nil && s.Changes[n] != nil {
			got, err := c.GitHub.GetPull(ctx, pr)
			if github.IsNotFound(err) {
				continue
			}
			if err != nil {
				return nil, err
			}
			s.PRs[pr] = got
		}
	}
	// GitHub-born changes live on the user's branch: take its head from
	// the PR.
	s.SameTree = map[int]string{}
	s.NoPush = map[int]bool{}
	for n := range s.Changes {
		st := s.State[n]
		if !s.githubBorn(n) || st.State.PR == 0 || s.PRs[st.State.PR] == nil {
			continue
		}
		pr := s.PRs[st.State.PR]
		if pr.State != "open" || pr.Head.SHA == "" {
			continue
		}
		s.GitHubBranches[st.State.HeadBranch] = pr.Head.SHA
		if _, _, fork := github.SplitHeadKey(st.State.HeadBranch); fork {
			full, err := c.GitHub.GetPull(ctx, pr.Number) // listed PRs lack maintainer_can_modify
			if err != nil {
				return nil, err
			}
			s.NoPush[n] = !full.MaintainerCanModify
		}
	}

	if err := c.observeHistory(ctx, s, env); err != nil {
		return nil, err
	}

	stacks, err := c.GitHub.ListStacks(ctx)
	if err != nil {
		return nil, err
	}
	for i := range stacks {
		st := &stacks[i]
		if !st.Open {
			continue
		}
		for _, n := range st.Numbers() {
			if s.PRs[n] != nil {
				s.Stacks = append(s.Stacks, st)
				break
			}
		}
	}
	return s, nil
}

// observeHistory fills in HasParent and SameTree for changes whose GitHub
// head stands for an older patch set: a new patch set goes on top of that
// history (design §5.2.1).
func (c *Code) observeHistory(ctx context.Context, s *Snapshot, env []string) error {
	s.HasParent = map[int]bool{}
	var todo []int
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		gh, ok := s.GitHubBranches[s.head(n, ch.ChangeID)]
		if ch.Status != "NEW" || ch.Private || !ok || gh == ch.Revision {
			continue
		}
		if _, known := s.githubFor(n)[gh]; known {
			todo = append(todo, n)
		}
	}
	if len(todo) == 0 {
		return nil
	}
	// The heads are commits the bridge made, but the mirror may not have
	// them (a fresh mirror, or another replica made them).
	var specs []string
	for _, n := range todo {
		head := s.head(n, s.Changes[n].ChangeID)
		if _, _, fork := github.SplitHeadKey(head); fork {
			// GitHub keeps every PR's head in the base repository.
			pr := s.State[n].State.PR
			specs = append(specs, fmt.Sprintf("+refs/pull/%d/head:refs/remotes/github/pull/%d", pr, pr))
			continue
		}
		specs = append(specs, "+refs/heads/"+head+":refs/remotes/github/heads/"+head)
	}
	if _, err := c.Mirror.GitEnv(ctx, env, nil, append([]string{"-c", fsckFetch, "fetch", "--quiet", c.GitHubURL}, specs...)...); err != nil {
		return err
	}
	for _, n := range todo {
		ch := s.Changes[n]
		gh := s.GitHubBranches[s.head(n, ch.ChangeID)]
		_, err := c.Mirror.Git(ctx, nil, "merge-base", "--is-ancestor", s.ghCommit(ch.Parent), gh)
		var ge *gitmirror.Error
		switch {
		case err == nil:
			s.HasParent[n] = true
		case errors.As(err, &ge) && ge.Stderr == "":
			// Exit 1: rebased onto something the head does not contain.
		default:
			return err
		}
		if s.HasParent[n] {
			out, err := c.Mirror.Git(ctx, nil, "rev-parse", ch.Revision+"^{tree}", gh+"^{tree}")
			if f := strings.Fields(string(out)); err == nil && len(f) == 2 && f[0] == f[1] {
				s.SameTree[n] = gh
			}
		}
	}
	return nil
}

// mirrorPRStates carries a PR closed or reopened on GitHub over to Gerrit
// (design §6.6): closing abandons the change, reopening restores it, each
// as the person who did it (Run-As), so Gerrit's permissions decide. If
// Gerrit refuses, or they have no Gerrit account, nothing changes there:
// the plan then puts the PR back the way Gerrit says, and a notice says
// why. It reports whether a change was abandoned or restored.
func (c *Code) mirrorPRStates(ctx context.Context, s *Snapshot, handled map[int]bool) (bool, error) {
	changed := false
	for _, n := range sortedKeys(s.Changes) {
		ch, st := s.Changes[n], s.State[n]
		if st == nil || st.State.PR == 0 || s.PRs[st.State.PR] == nil || handled[st.State.PR] {
			continue
		}
		pr := s.PRs[st.State.PR]
		var action, past string
		switch {
		case ch.Status == "NEW" && pr.State == "closed" && !pr.Merged:
			action, past = "abandon", "closed"
		case ch.Status == "ABANDONED" && pr.State == "open":
			action, past = "restore", "reopened"
		default:
			continue
		}
		ev, err := c.GitHub.LastStateEvent(ctx, pr.Number)
		if err != nil {
			return changed, err
		}
		if ev == nil || ev.Event != past || (c.BridgeLogin != "" && strings.EqualFold(ev.Actor.Login, c.BridgeLogin)) {
			continue // the bridge's own doing, or nobody's: the plan decides
		}
		// A close older than Gerrit's own last abandon or restore is
		// history (say the change was restored in Gerrit since): Gerrit
		// wins, and the plan puts the PR back the way Gerrit says.
		if last, err := c.lastStatusChange(ctx, n); err != nil {
			return changed, err
		} else if !ev.CreatedAt.After(last) {
			continue
		}
		login := ev.Actor.Login
		user, ok := "", false
		if c.Identity != nil {
			user, ok = c.Identity.GerritUser(ctx, login)
		}
		var why string
		if !ok {
			why = fmt.Sprintf("@%s has no Gerrit account to %s it with", login, action)
		} else {
			msg := fmt.Sprintf("PR #%d %s on GitHub.", pr.Number, past)
			err := c.Gerrit.As(user).Do(ctx, http.MethodPost, fmt.Sprintf("changes/%d/%s", n, action), map[string]string{"message": msg}, nil)
			if err == nil {
				c.Logger.Info("mirrored GitHub "+past+" to Gerrit", "change", n, "pr", pr.Number, "action", action, "as", user)
				changed, handled[pr.Number] = true, true
				continue
			}
			var ge *gerrit.Error
			if !errors.As(err, &ge) || ge.Status >= 500 {
				return changed, fmt.Errorf("%s change %d as %s: %w", action, n, user, err)
			}
			why = fmt.Sprintf("Gerrit would not let %s %s it (%s)", user, action, forGitHub(strings.TrimSpace(ge.Body)))
		}
		undo := "Reopening it"
		if action == "restore" {
			undo = "Closing it again"
		}
		note := fmt.Sprintf("@%s %s this PR, which would %s [change %d](%s) in Gerrit, but %s. %s.\n\n%s",
			login, past, action, n, ch.URL, why, undo, noticeMarker)
		if _, err := c.GitHub.CreateIssueComment(ctx, pr.Number, note); err != nil {
			return changed, err
		}
		c.Logger.Info("GitHub "+past+" not mirrored", "change", n, "pr", pr.Number, "by", login, "why", why)
		if action == "abandon" {
			// The plan reopens it; state it so it does even if the
			// close notice was posted before.
			if err := c.updateState(ctx, n, "PR close refused", func(st *state.Change) { st.State.ClosedNoticePosted = false }); err != nil {
				return changed, err
			}
		} else {
			// The plan closes it again, without repeating the notice.
			if err := c.updateState(ctx, n, "PR reopen refused", func(st *state.Change) { st.State.ClosedNoticePosted = true }); err != nil {
				return changed, err
			}
		}
	}
	return changed, nil
}

// gerritText is the PR text a commit message stands for, and githubText
// a PR's own, each as one comparable string.
func gerritText(message string) string {
	title, body := prTextFromMessage(message)
	return title + "\x00" + body
}

func githubText(pr *github.PullRequest) string {
	return strings.TrimSpace(pr.Title) + "\x00" + prBodyForMessage(pr.Body)
}

func wipState(wip bool) string { return map[bool]string{true: "wip", false: "ready"}[wip] }

// mirrorPREdits carries PR edits made on GitHub over to Gerrit (design
// §6.0): a new title or description becomes the change's commit message,
// and a draft toggle its work-in-progress state, whichever side changed
// last. They are made as whoever made them on GitHub (Run-As; see
// asEditor for when the bridge will not); if Gerrit or the bridge refuses,
// a notice says why and the plan puts Gerrit's version back. If both sides
// changed, Gerrit's wins. It reports whether Gerrit changed.
func (c *Code) mirrorPREdits(ctx context.Context, s *Snapshot, handled map[int]bool) (bool, error) {
	changed := false
	for _, n := range sortedKeys(s.Changes) {
		ch, st := s.Changes[n], s.State[n]
		if ch.Status != "NEW" || ch.Private || st == nil || st.State.PR == 0 || s.PRs[st.State.PR] == nil || handled[st.State.PR] {
			continue
		}
		pr := s.PRs[st.State.PR]
		if pr.State != "open" {
			continue
		}
		gt, ht := hashString(gerritText(ch.Message)), hashString(githubText(pr))
		gw, hw := wipState(ch.WIP), wipState(pr.Draft)
		textEdited := gt != ht && st.State.SyncedText != "" && ht != st.State.SyncedText
		draftToggled := gw != hw && st.State.SyncedWIP != "" && hw != st.State.SyncedWIP
		if !textEdited && !draftToggled {
			continue
		}
		act, err := c.GitHub.Activity(ctx, pr.Number)
		if err != nil {
			return changed, err
		}
		// Who edited is asked after the edit was seen: if the PR moved on
		// meanwhile, the editor named may have made a later edit, not this
		// one. Leave it to the next reconcile, which sees both together.
		if now, err := c.GitHub.GetPull(ctx, pr.Number); err != nil {
			return changed, err
		} else if now.Title != pr.Title || now.Body != pr.Body || now.Draft != pr.Draft {
			c.Logger.Info("PR edited again while being mirrored; next round", "change", n, "pr", pr.Number)
			changed, handled[pr.Number] = true, true // re-observe
			continue
		}
		var notes []string
		if textEdited {
			if gt != st.State.SyncedText {
				notes = append(notes, fmt.Sprintf("This PR's title or description was edited on GitHub while [change %d](%s)'s commit message changed in Gerrit; Gerrit's is kept.", n, ch.URL))
			} else {
				title, body := strings.TrimSpace(pr.Title), prBodyForMessage(pr.Body)
				msg := commitMessage(title, body, ch.Message)
				if note, err := c.asEditor(ctx, ch, pr, act.TextEditor, true, http.MethodPut, "message", map[string]string{"message": msg},
					"edited this PR's title or description", "change the commit message of"); err != nil {
					return changed, err
				} else if note != "" {
					notes = append(notes, note)
				} else {
					// Both sides have it now: a further edit before the
					// next record is a new edit, not Gerrit's to undo.
					if err := c.updateState(ctx, n, "PR text mirrored", func(st *state.Change) { st.State.SyncedText = ht }); err != nil {
						return changed, err
					}
					changed, handled[pr.Number] = true, true
				}
			}
		}
		if draftToggled {
			if gw != st.State.SyncedWIP {
				notes = append(notes, fmt.Sprintf("This PR's draft state changed on GitHub while [change %d](%s)'s work-in-progress state changed in Gerrit; Gerrit's is kept.", n, ch.URL))
			} else {
				past := map[bool]string{true: "marked this PR as a draft", false: "marked this PR ready for review"}[pr.Draft]
				if note, err := c.asEditor(ctx, ch, pr, act.DraftActor, false, http.MethodPost, hw, map[string]string{"message": fmt.Sprintf("PR #%d %s on GitHub.", pr.Number, map[bool]string{true: "marked draft", false: "marked ready for review"}[pr.Draft])},
					past, "change the work-in-progress state of"); err != nil {
					return changed, err
				} else if note != "" {
					notes = append(notes, note)
				} else {
					// As for text: toggling back before the next record
					// is a new toggle.
					if err := c.updateState(ctx, n, "PR draft state mirrored", func(st *state.Change) { st.State.SyncedWIP = hw }); err != nil {
						return changed, err
					}
					changed, handled[pr.Number] = true, true
				}
			}
		}
		for _, note := range notes {
			if _, err := c.GitHub.CreateIssueComment(ctx, pr.Number, note+"\n\n"+noticeMarker); err != nil {
				return changed, err
			}
			c.Logger.Info("GitHub PR edit not mirrored", "change", n, "pr", pr.Number, "why", note)
		}
	}
	return changed, nil
}

// asEditor calls changes/n/<endpoint> as GitHub user login's Gerrit
// account. It returns a notice instead ("@login <did>, which would <would>
// change N in Gerrit, but ...") when Gerrit refuses, or when the bridge
// will not act for login:
//   - Someone without a Gerrit account acts only on their own PR's
//     bridge-owned change, and then as the bridge (as their pushes are):
//     the bridge's account must not lend anyone rights in Gerrit.
//   - An edit that makes a new patch set (newPatchSet, a commit message
//     edit) is made only by the current patch set's uploader: CI trusts
//     the uploader, and retitling someone else's PR on GitHub must not
//     make the editor vouch for its code.
func (c *Code) asEditor(ctx context.Context, ch *GerritChange, pr *github.PullRequest, login string, newPatchSet bool, method, endpoint string, in any, did, would string) (string, error) {
	n := ch.Number
	who := "@" + login
	if login == "" {
		who = "Someone"
	}
	refuse := func(why string) string {
		return fmt.Sprintf("%s %s, which would %s [change %d](%s) in Gerrit, but %s. Putting Gerrit's back.", who, did, would, n, c.changeURL(n), why)
	}
	user, ok := "", false
	if c.Identity != nil && login != "" {
		user, ok = c.Identity.GerritUser(ctx, login)
	}
	g, as := c.Gerrit, "the bridge"
	switch {
	case ok && newPatchSet && !strings.EqualFold(user, ch.Uploader):
		return refuse("only the uploader of its current patch set can make a new one from GitHub, since CI trusts the uploader; edit it in Gerrit"), nil
	case ok:
		g, as = c.Gerrit.As(user), user
	case login != "" && strings.EqualFold(login, pr.User.Login) && c.BridgeUser != "" && strings.EqualFold(ch.Owner, c.BridgeUser) &&
		(!newPatchSet || strings.EqualFold(ch.Uploader, c.BridgeUser)):
		// Their own PR, which the bridge owns for them.
	case login == "":
		return refuse("GitHub does not say who, so there is no Gerrit account to do it as"), nil
	default:
		return refuse(fmt.Sprintf("%s has no Gerrit account to do that with", who)), nil
	}
	err := g.Do(ctx, method, fmt.Sprintf("changes/%d/%s", n, endpoint), in, nil)
	var ge *gerrit.Error
	switch {
	case err == nil:
		c.Logger.Info("mirrored GitHub PR edit to Gerrit", "change", n, "endpoint", endpoint, "as", as)
		return "", nil
	case errors.As(err, &ge) && ge.Status < 500:
		return refuse(fmt.Sprintf("Gerrit would not let %s (%s)", as, forGitHub(strings.TrimSpace(ge.Body)))), nil
	default:
		return "", fmt.Errorf("%s %s change %d as %s: %w", method, endpoint, n, as, err)
	}
}

// commitMessage is the commit message for a PR's title and description:
// those, plus the bridge's trailers (Change-Id, sign-offs, GitHub-PR)
// from the current message, kept in the last paragraph if the description
// already ends in trailers.
func commitMessage(title, body, current string) string {
	msg := title
	if body != "" {
		msg += "\n\n" + body
	}
	trailers := bridgeTrailers.FindAllString(strings.ReplaceAll(current, "\r\n", "\n"), -1)
	if len(trailers) == 0 {
		return msg + "\n"
	}
	sep := "\n\n"
	if paras := strings.Split(body, "\n\n"); body != "" && isTrailers(paras[len(paras)-1]) {
		sep = "\n"
	}
	return msg + sep + strings.Join(trailers, "\n") + "\n"
}

var trailerLine = regexp.MustCompile(`^[A-Za-z0-9-]+: \S`)

// isTrailers reports whether every line of paragraph p is a "Key: value"
// trailer.
func isTrailers(p string) bool {
	for _, l := range strings.Split(strings.TrimSpace(p), "\n") {
		if !trailerLine.MatchString(l) {
			return false
		}
	}
	return strings.TrimSpace(p) != ""
}

// lastStatusChange is when change n was last abandoned or restored in
// Gerrit (zero if never).
func (c *Code) lastStatusChange(ctx context.Context, n int) (time.Time, error) {
	ci, err := c.Gerrit.GetChange(ctx, n, "MESSAGES")
	if err != nil {
		return time.Time{}, err
	}
	var last time.Time
	for _, m := range ci.Messages {
		if m.Tag != "autogenerated:gerrit:abandon" && m.Tag != "autogenerated:gerrit:restore" {
			continue
		}
		// Gerrit's timestamps are UTC: "2006-01-02 15:04:05.000000000".
		if t, err := time.Parse("2006-01-02 15:04:05.999999999", m.Date); err == nil && t.After(last) {
			last = t
		}
	}
	return last, nil
}

func (c *Code) githubEnv(ctx context.Context) ([]string, error) {
	tok, err := c.GitHub.Tokens.Token(ctx)
	if err != nil {
		return nil, err
	}
	return gitmirror.CredentialEnv("https://github.com", "x-access-token", tok), nil
}

// apply runs a plan's actions in order. An action on one change's PR that
// GitHub refuses as such (refusedByGitHub) is logged, and that change is
// added to skip and left out for the rest of the reconcile: anyone can
// make their own change's PR unacceptable to GitHub, and that must not
// stop everyone else's. Any other error stops it; the next reconcile
// re-plans from whatever state that left.
func (c *Code) apply(ctx context.Context, s *Snapshot, p *Plan, skip map[int]bool) error {
	for _, a := range p.Actions {
		if a.Change != 0 && skip[a.Change] {
			continue
		}
		if err := c.applyOne(ctx, s, a); err != nil {
			if a.Change != 0 && refusedByGitHub(err) {
				c.Logger.Warn("GitHub refused an action on one change's PR; leaving that change out", "change", a.Change, "action", a.String(), "err", err)
				skip[a.Change] = true
				continue
			}
			return fmt.Errorf("%s: %w", a, err)
		}
	}
	return nil
}

// refusedByGitHub reports whether GitHub refused a request for what it
// asked (a 4xx), not for who asked or how often (401, 403, 429).
func refusedByGitHub(err error) bool {
	var ae *github.APIError
	return errors.As(err, &ae) && ae.Status >= 400 && ae.Status < 500 &&
		ae.Status != http.StatusUnauthorized && ae.Status != http.StatusForbidden && ae.Status != http.StatusTooManyRequests
}

func (c *Code) applyOne(ctx context.Context, s *Snapshot, a Action) error {
	gh := c.GitHub
	switch a.Kind {
	case PushBranches, DeleteBranches:
		// One atomic push to the repository, plus one per fork whose PR
		// branch gets a Gerrit edit (allowed by maintainer_can_modify).
		// Gerrit owns these; only replication writes them.
		for _, name := range append(sortedStringKeys(a.Refs), sortedStringKeys(a.Appends)...) {
			if name == s.Branch || name == c.DefaultBranch {
				return fmt.Errorf("refusing to push to %s, which Gerrit owns", name)
			}
			if _, _, fork := github.SplitHeadKey(name); !fork {
				// Any branch Gerrit has is replication's, not the bridge's.
				if owned, err := c.Gerrit.BranchExists(ctx, c.Project, name); err != nil {
					return err
				} else if owned {
					return fmt.Errorf("refusing to push to %s, which Gerrit owns", name)
				}
			}
		}
		urls := []string{c.GitHubURL}
		specs := map[string][]string{}
		// Whatever the plan says, nothing goes to the repository that
		// changes .github/ (GitHub would run it; withhold).
		guard := func(name, commit string) error {
			if _, _, fork := github.SplitHeadKey(name); fork || commit == "" {
				return nil // runs in the fork, with its own secrets; or a deletion
			}
			if w, err := c.changesConfig(ctx, s.Branch, commit); err != nil || w {
				return cmp.Or(err, fmt.Errorf("refusing to push %s to %s: it changes %s", short(commit), name, withheldWhat))
			}
			return nil
		}
		for _, name := range sortedStringKeys(a.Refs) {
			if err := guard(name, a.Refs[name]); err != nil {
				return err
			}
			ref := "refs/heads/" + name
			specs[c.GitHubURL] = append(specs[c.GitHubURL], "--force-with-lease="+ref+":"+a.Leases[name], a.Refs[name]+":"+ref)
		}
		appended := map[string]string{}
		for _, name := range sortedStringKeys(a.Appends) {
			commit := a.Appends[name].Revision
			if !a.Appends[name].Force {
				var err error
				if commit, err = c.appendCommit(ctx, a.Appends[name]); err != nil {
					return err
				}
			}
			if err := guard(name, commit); err != nil {
				return err
			}
			appended[name] = commit
			url, branch := c.GitHubURL, name
			if fork, b, ok := github.SplitHeadKey(name); ok {
				url, branch = "https://github.com/"+fork+".git", b
				if !slices.Contains(urls, url) {
					urls = append(urls, url)
				}
			}
			ref := "refs/heads/" + branch
			specs[url] = append(specs[url], "--force-with-lease="+ref+":"+a.Leases[name], commit+":"+ref)
		}
		env, err := c.githubEnv(ctx)
		if err != nil {
			return err
		}
		for _, url := range urls {
			if len(specs[url]) == 0 {
				continue
			}
			args := append([]string{"push", "--porcelain", "--atomic", url}, specs[url]...)
			if out, err := c.Mirror.GitEnv(ctx, env, nil, args...); err != nil {
				return fmt.Errorf("%w\n%s", err, out)
			}
		}
		for name, commit := range appended {
			ap := a.Appends[name]
			tree, parentTree := c.trees(ctx, ap.Revision)
			err := c.updateState(ctx, ap.Change, fmt.Sprintf("Export patch set %d to %s", ap.PatchSet, name), func(st *state.Change) {
				st.Revisions = append(st.Revisions, state.Revision{PatchSet: ap.PatchSet, GerritSHA: ap.Revision,
					GitHubSHA: commit, Tree: tree, ParentTree: parentTree, At: time.Now()})
			})
			if err != nil {
				return err
			}
			if err := c.exported(ctx, ap.Change); err != nil {
				return err
			}
		}
		return nil
	case CreatePR:
		pr, err := gh.CreatePull(ctx, *a.New)
		if err != nil {
			return err
		}
		c.Logger.Info("created PR", "change", a.Change, "pr", pr.Number, "url", pr.HTMLURL)
		return c.link(ctx, s, a.Change, pr)
	case UpdatePR:
		_, err := gh.UpdatePull(ctx, a.PR, *a.Update)
		return err
	case SetDraft:
		return gh.SetDraft(ctx, a.NodeID, a.Draft)
	case Unstack:
		return gh.Unstack(ctx, a.Stack)
	case CreateStack:
		st, err := gh.CreateStack(ctx, a.PRs)
		if err == nil {
			c.Logger.Info("created stack", "stack", st.Number, "prs", a.PRs)
		}
		return err
	case AddToStack:
		_, err := gh.AddToStack(ctx, a.Stack, a.PRs)
		return err
	case ClosePR:
		if s.Changes[a.Change].Status == "MERGED" {
			// GitHub may have just marked it merged (replication landed
			// its head on the target branch while this plan was made):
			// then there is nothing to close or explain.
			cur, err := gh.GetPull(ctx, a.PR)
			if err != nil {
				return err
			}
			if cur.Merged || cur.State != "open" {
				return c.updateState(ctx, a.Change, "PR merged on GitHub", func(st *state.Change) {
					st.State.ClosedNoticePosted = true
					st.State.Lifecycle = s.Changes[a.Change].Status
				})
			}
		}
		if a.Comment != "" {
			if _, err := gh.CreateIssueComment(ctx, a.PR, a.Comment+"\n\n"+noticeMarker); err != nil {
				return err
			}
		}
		if _, err := gh.UpdatePull(ctx, a.PR, github.PullUpdate{State: ptr("closed")}); err != nil {
			return err
		}
		return c.updateState(ctx, a.Change, "Close PR", func(st *state.Change) {
			st.State.ClosedNoticePosted = true
			st.State.Lifecycle = s.Changes[a.Change].Status
		})
	}
	return fmt.Errorf("unknown action %v", a.Kind)
}

// link records a new change <-> PR link and announces it on the change.
func (c *Code) link(ctx context.Context, s *Snapshot, n int, pr *github.PullRequest) error {
	origin := "gerrit"
	if s.githubBorn(n) {
		origin = "github"
	}
	return c.linkPR(ctx, n, origin, s.Branch, s.Changes[n].ChangeID, pr)
}

func (c *Code) linkPR(ctx context.Context, n int, origin, branch, changeID string, pr *github.PullRequest) error {
	err := c.updateState(ctx, n, fmt.Sprintf("Link PR #%d", pr.Number), func(st *state.Change) {
		st.State.Change = n
		st.State.ChangeID = changeID
		st.State.Branch = branch
		if st.State.Origin == "" {
			st.State.Origin = origin
		}
		st.State.PR = pr.Number
		st.State.PRNodeID = pr.NodeID
		st.State.HeadBranch = pr.HeadKey(c.GitHub.Owner + "/" + c.GitHub.Repo)
		st.State.Lifecycle = "NEW"
	})
	if err != nil {
		return err
	}
	return c.Gerrit.SetReview(ctx, n, "current", gerrit.ReviewInput{
		Message: fmt.Sprintf("GitHub: %s", pr.HTMLURL),
		Tag:     LinkTag,
		Notify:  "NONE",
	})
}

// appendCommit makes a commit with a patch set's tree on top of a GitHub
// head (design §5.2: a fast-forward, so `git pull` works), merging in the
// new base of a rebased patch set.
func (c *Code) appendCommit(ctx context.Context, a Append) (string, error) {
	out, err := c.Mirror.Git(ctx, nil, "log", "-1", "--format=%T%x00%an%x00%ae%x00%ad", "--date=raw", a.Revision)
	if err != nil {
		return "", err
	}
	f := strings.SplitN(strings.TrimSpace(string(out)), "\x00", 4)
	if len(f) != 4 {
		return "", fmt.Errorf("parsing %s", a.Revision)
	}
	env := []string{"GIT_AUTHOR_NAME=" + f[1], "GIT_AUTHOR_EMAIL=" + f[2], "GIT_AUTHOR_DATE=" + f[3]}
	msg := fmt.Sprintf("Patch set %d from Gerrit\n\n%s\n", a.PatchSet, c.changeURL(a.Change))
	parents := []string{"-p", a.Onto}
	if a.Merge != "" {
		msg = fmt.Sprintf("Patch set %d from Gerrit, rebased\n\n%s\n", a.PatchSet, c.changeURL(a.Change))
		parents = append(parents, "-p", a.Merge)
	}
	if a.KeepMessage {
		// Same message, author and dates: deterministic, so a retry
		// makes the same commit.
		raw, err := c.Mirror.Git(ctx, nil, "log", "-1", "--format=%B%x00%cn%x00%ce%x00%cd", "--date=raw", a.Revision)
		if err != nil {
			return "", err
		}
		g := strings.SplitN(string(raw), "\x00", 4)
		if len(g) != 4 {
			return "", fmt.Errorf("parsing %s", a.Revision)
		}
		msg = g[0]
		env = append(env, "GIT_COMMITTER_NAME="+g[1], "GIT_COMMITTER_EMAIL="+g[2], "GIT_COMMITTER_DATE="+strings.TrimSpace(g[3]))
	}
	commit, err := c.Mirror.GitEnv(ctx, env, []byte(msg), append(append([]string{"commit-tree", f[0]}, parents...), "-F", "-")...)
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(commit)), nil
}

func (c *Code) exported(ctx context.Context, n int) error {
	if c.OnExported == nil {
		return nil
	}
	return c.OnExported(ctx, n)
}

// record saves the converged state of every linked change.
func (c *Code) record(ctx context.Context, s *Snapshot, p *Plan) error {
	newRevision := map[int]bool{}
	defer func() {
		for _, n := range sortedKeys(newRevision) {
			if err := c.exported(ctx, n); err != nil {
				c.Logger.Warn("post-export sync failed", "change", n, "err", err)
			}
		}
	}()
	stackOf := map[int]int{}
	for _, st := range s.Stacks {
		for _, n := range st.Numbers() {
			stackOf[n] = st.Number
		}
	}
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		d := p.Desired[n]
		st := s.State[n]
		if d == nil {
			// Not mirrored (closed or private): remember the status so we
			// stop fetching it.
			if st != nil && st.Version != "" && st.State.Lifecycle != ch.Status {
				if err := c.updateState(ctx, n, "Lifecycle "+ch.Status, func(st *state.Change) {
					st.State.Lifecycle = ch.Status
				}); err != nil {
					return err
				}
			}
			continue
		}
		if d.PR == 0 {
			continue
		}
		pr := s.PRs[d.PR]
		if st == nil || st.State.PR != d.PR {
			// Adopted without state, or state lost: relink.
			if err := c.link(ctx, s, n, pr); err != nil {
				return err
			}
		}
		tree, parentTree := c.trees(ctx, ch.Revision)
		err := c.updateState(ctx, n, fmt.Sprintf("Sync patch set %d", ch.PatchSet), func(st *state.Change) {
			st.State.BaseBranch = d.Base
			st.State.Stack = stackOf[d.PR]
			st.State.Lifecycle = ch.Status
			st.State.Title = ch.Subject
			st.State.BodyHash = d.BodyHash
			st.State.ClosedNoticePosted = false
			// Where the PR and the change agree, neither side has news for
			// the other (mirrorPREdits).
			// So do they where the PR shows what the bridge wrote (a
			// description shortened for GitHub, say).
			if pr != nil && (githubText(pr) == gerritText(ch.Message) || (pr.Body == d.Body && strings.TrimSpace(pr.Title) == d.Title)) {
				st.State.SyncedText = hashString(githubText(pr))
			}
			if pr != nil && pr.Draft == ch.WIP {
				st.State.SyncedWIP = wipState(ch.WIP)
			}
			// Commits the bridge built (imports, appends, re-parented
			// exports) are recorded where they are made, with both SHAs.
			// A foreign patch set is not on GitHub even where its tree is
			// (a commit-message edit, say).
			if gh := s.bridgeHead(n, d.Head); gh != "" && !s.Foreign[n] &&
				!slices.ContainsFunc(st.Revisions, func(r state.Revision) bool { return r.GerritSHA == ch.Revision && r.GitHubSHA == gh }) {
				newRevision[n] = true
				st.Revisions = append(st.Revisions, state.Revision{
					PatchSet: ch.PatchSet, GerritSHA: ch.Revision, GitHubSHA: gh,
					Tree: tree, ParentTree: parentTree, At: time.Now(),
				})
			}
		})
		if err != nil {
			return err
		}
	}
	return nil
}

func (c *Code) trees(ctx context.Context, rev string) (tree, parent string) {
	if out, err := c.Mirror.Git(ctx, nil, "rev-parse", rev+"^{tree}", rev+"^^{tree}"); err == nil {
		f := strings.Fields(string(out))
		if len(f) == 2 {
			return f[0], f[1]
		}
	}
	return "", ""
}

// updateState loads, mutates and saves change n's state, retrying once on
// a concurrent write.
func (c *Code) updateState(ctx context.Context, n int, msg string, f func(*state.Change)) error {
	for try := 0; ; try++ {
		st, err := c.Store.Load(ctx, n)
		if err != nil {
			return err
		}
		f(st)
		err = c.Store.Save(ctx, n, st, msg)
		if errors.Is(err, state.ErrConflict) && try == 0 {
			continue
		}
		return err
	}
}

// BranchLister lists what a full resync must visit: every branch with open
// changes, and every branch the bridge has state for.
type BranchLister struct {
	Gerrit  *gerrit.Client
	Project string
	Store   *state.Store
}

// ResyncKeys implements Lister.
func (l BranchLister) ResyncKeys(ctx context.Context) ([]Key, error) {
	infos, err := l.Gerrit.QueryChanges(ctx, "project:"+gerrit.QueryString(l.Project)+" status:open")
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	var keys []Key
	add := func(b string) {
		if b != "" && !seen[b] {
			seen[b] = true
			keys = append(keys, Key{Branch: b})
		}
	}
	for _, ci := range infos {
		add(ci.Branch)
	}
	for _, b := range l.Store.Branches() {
		add(b)
		// Comments of every mirrored open change.
		for _, n := range l.Store.ChangesOnBranch(b) {
			st, err := l.Store.Load(ctx, n)
			if err != nil {
				return nil, err
			}
			if st.State.PR != 0 && st.State.Lifecycle == "NEW" {
				keys = append(keys, Key{Comments: n})
			}
		}
	}
	return keys, nil
}

func sortedStringKeys[V any](m map[string]V) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

// PrepareSubmit readies the PRs of the changes a submit of change n will
// merge, before the bridge submits it (/submit): each PR whose head is
// (or, for a Gerrit-born change, is made) exactly its change's commit
// leaves its stack and is retargeted to the target branch. When
// replication then lands the commits, GitHub shows every PR merged, which
// it only does for PRs based on that branch (design §6.7). Doing it before
// the submit means the bridge never races replication. If the submit
// fails, the next reconcile restores the stack, and the next patch set
// goes on top of Gerrit's commit. The caller holds the branch lock.
func (c *Code) PrepareSubmit(ctx context.Context, n int) error {
	together, err := c.Gerrit.SubmittedTogether(ctx, n)
	if err != nil {
		return err
	}
	if len(together) == 0 {
		ch, err := c.Gerrit.GetChange(ctx, n, "CURRENT_REVISION")
		if err != nil {
			return err
		}
		together = []gerrit.ChangeInfo{*ch}
	}
	var prs []*github.PullRequest
	unstack := map[int]bool{}
	specs := map[string][]string{} // push URL -> heads to swap for Gerrit's commits
	var fetch []string             // where to fetch those commits from
	for _, ch := range together {
		st, err := c.Store.Load(ctx, ch.Number)
		if err != nil {
			return err
		}
		if st.State.PR == 0 {
			continue
		}
		pr, err := c.GitHub.GetPull(ctx, st.State.PR)
		if err != nil {
			return err
		}
		if pr.State != "open" {
			continue
		}
		rev, ok := ch.Current()
		switch {
		case pr.Head.SHA == ch.CurrentRevision || !ok:
		case len(st.Revisions) == 0 || st.Revisions[len(st.Revisions)-1].GitHubSHA != pr.Head.SHA:
			// A push not imported yet: never overwritten.
			c.Logger.Warn("PR head is not the patch set being submitted; not swapping it", "change", ch.Number, "pr", pr.Number, "head", pr.Head.SHA)
		default:
			// GitHub's head is the patch sets' history (Gerrit-born) or the
			// commits Gerrit squashed (GitHub-born): swap in Gerrit's
			// commit, which has the same files.
			url, branch := c.GitHubURL, st.State.HeadBranch
			fork, b, isFork := github.SplitHeadKey(st.State.HeadBranch)
			if isFork {
				if !pr.MaintainerCanModify {
					continue // the author's fork: closed with a notice instead
				}
				url, branch = "https://github.com/"+fork+".git", b
			} else if ch.Status != "MERGED" {
				// Not yet on the branch: the push guard's rule applies.
				if _, err := c.Mirror.Git(ctx, nil, "fetch", "--quiet", "origin", rev.Ref); err != nil {
					return err
				}
				if w, err := c.changesConfig(ctx, ch.Branch, ch.CurrentRevision); err != nil || w {
					c.Logger.Warn("not swapping in a commit that changes "+withheldWhat, "change", ch.Number, "pr", pr.Number, "err", err)
					continue
				}
			}
			ref := "refs/heads/" + branch
			specs[url] = append(specs[url], "--force-with-lease="+ref+":"+pr.Head.SHA, ch.CurrentRevision+":"+ref)
			fetch = append(fetch, rev.Ref)
		}
		if pr.Base.Ref == ch.Branch {
			continue
		}
		pr.Base.Ref = ch.Branch // the target, for below
		prs = append(prs, pr)
		if pr.Stack != nil {
			unstack[pr.Stack.Number] = true
		}
	}
	if c.DryRun {
		if len(prs) > 0 {
			c.Logger.Info("dry run: would retarget PRs before submit", "change", n, "prs", len(prs), "swapped_heads", len(fetch))
		}
		return nil
	}
	if len(specs) > 0 {
		if _, err := c.Mirror.Git(ctx, nil, append([]string{"fetch", "--quiet", "origin"}, fetch...)...); err != nil {
			return err
		}
		env, err := c.githubEnv(ctx)
		if err != nil {
			return err
		}
		for _, url := range sortedStringKeys(specs) {
			args := append([]string{"push", "--porcelain", "--atomic", url}, specs[url]...)
			if out, err := c.Mirror.GitEnv(ctx, env, nil, args...); err != nil {
				return fmt.Errorf("swapping in Gerrit's commits before submit: %w\n%s", err, out)
			}
		}
		c.Logger.Info("swapped PR heads for Gerrit's commits before submit", "change", n, "heads", len(fetch))
	}
	for _, sn := range sortedKeys(unstack) {
		if err := c.GitHub.Unstack(ctx, sn); err != nil && !github.IsNotFound(err) {
			return err
		}
	}
	for _, pr := range prs {
		if _, err := c.GitHub.UpdatePull(ctx, pr.Number, github.PullUpdate{Base: ptr(pr.Base.Ref)}); err != nil {
			return fmt.Errorf("retargeting #%d: %w", pr.Number, err)
		}
		c.Logger.Info("retargeted PR before submit", "change", n, "pr", pr.Number, "base", pr.Base.Ref)
	}
	return nil
}
