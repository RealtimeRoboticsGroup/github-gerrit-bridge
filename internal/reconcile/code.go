// LinkTag tags the Gerrit change message that links a change to its PR.
const LinkTag = "autogenerated:github-bridge:link"

// Code mirrors Gerrit changes to GitHub branches, PRs and stacks (design
// §5.1, §5.4, §6.0, §6.6). It reconciles one target branch at a time.
type Code struct {
	Project string
	Gerrit  *gerrit.Client
	GitHub  *github.Client
	// GitHubURL is the repository's HTTPS clone URL. Mirror.Config must
	// hold gitmirror.CredentialHelper for https://github.com.
	GitHubURL string
	Mirror    *gitmirror.Repo
	// CommitterName and CommitterEmail, if set, commit what the bridge
	// writes for GitHub instead of Mirror's identity.
	CommitterName, CommitterEmail string
	Store                         *state.Store
	DefaultBranch                 string
	DryRun                        bool
	Logger                        *slog.Logger
	// Importer, if set, imports GitHub-born PRs before each reconcile.
	Importer *Importer
	// OnExported, if set, is called for each change whose current patch
	// set reached GitHub in a reconcile, once it has let go of the
	// branch.
	OnExported func(ctx context.Context, n int) error
	// Identity maps GitHub logins to Gerrit usernames, and BridgeLogin is
	// the bridge's own GitHub login: closing or reopening a PR on GitHub
	// abandons or restores its change as whoever did it.
	Identity    Identity
	BridgeLogin string
	// BridgeUser is the bridge's Gerrit username, BridgeAccount its account.
	BridgeUser    string
	BridgeAccount int
	// Trusted reports whether a Gerrit account is in CI's trusted group
	// (known is false if that cannot be told). Only they, and a change's
	// owner, have their Gerrit patch sets pushed to a PR author's branch.
	Trusted func(ctx context.Context, account int) (trusted, known bool)
	// TextBudget, if set, bounds the PR title and description updates
	// each account's commit messages make the bridge write, and
	// LinksBudget the updates of each PR's relation chain alone, which
	// anyone's upload in the chain changes (fourth audit: anyone
	// registered can add patch sets to every open change).
	TextBudget, LinksBudget *Budget
	// PRBudget, if set, bounds the new PRs each change owner's changes
	// get (Snapshot.Deferred).
	PRBudget *Budget
	// GitHubOwned says GitHub owns the target branches (design §3.1):
	// PRs merge there, and Gerrit's branches follow GitHub's.
	GitHubOwned bool
	// Publishable, where GitHub owns the branches, reports whether a
	// Gerrit account's linked GitHub account may push to the repository
	// (known is false if that cannot be told). Only their patch sets
	// reach GitHub: a pushed branch runs the repository's workflows,
	// with its secrets, so nobody gets more through Gerrit than they
	// have on GitHub. It stands in for Trusted for pushes to GitHub-born
	// PRs' branches too. Unset there, no Gerrit patch set is pushed.
	Publishable func(ctx context.Context, account int) (ok, known bool)
	// Below, if set, is what parentsTrusted reads (tests); else the
	// mirror and Gerrit.
	Below belowReader
	// LinkURL is where people link their GitHub accounts, for notices.
	LinkURL string
	// OpenAs, where GitHub owns the branches, is the GitHub client a
	// Gerrit account's linked GitHub account opens PRs with (ok false:
	// not linked, or no longer). A Gerrit-born change's PR is its
	// owner's, so that GitHub knows whose it is: it counts no one's
	// approval of their own PR (nineteenth review, the owner's call:
	// opened as the bot, their own approval counted until the bridge
	// next dismissed it). Unset there, no PR is opened.
	OpenAs func(ctx context.Context, account int) (opener PullOpener, ok bool, err error)
	// LinkedAs is the GitHub account a Gerrit account linked, if any
	// (where GitHub owns the branches: whose PRs are the owner's).
	LinkedAs func(ctx context.Context, account int) (github.User, bool, error)

	// configCache remembers changesConfig answers by branch tip and
	// commit.
	wmu         sync.Mutex
	configCache map[string]bool

	// locks serializes reconciles of one target branch. The queue already
	// does for Branch keys; Change and PR keys resolve to a branch here.
	// Comment syncs share it (rlock), with one another but not with the
	// branch's reconcile or a merge.
	mu    sync.Mutex
	locks map[string]*branchLock
}

// branchLock is a readers-writer lock whose urgent writers go first, and
// whose waiting writers go ahead of new readers: a stream of comment
// syncs must not keep a merge or the branch's reconcile waiting.
type branchLock struct {
	mu      sync.Mutex
	cond    *sync.Cond
	held    bool // by a writer
	readers int
	urgent  int // urgent writers waiting
	writers int // other writers waiting
}

func (l *branchLock) lock(urgent bool) {
	l.mu.Lock()
	defer l.mu.Unlock()
	if urgent {
		l.urgent++
		defer func() { l.urgent-- }()
	} else {
		l.writers++
		defer func() { l.writers-- }()
	}
	for l.held || l.readers > 0 || (!urgent && l.urgent > 0) {
		l.cond.Wait()
	}
	l.held = true
}

func (l *branchLock) unlock() {
	l.mu.Lock()
	l.held = false
	l.cond.Broadcast()
	l.mu.Unlock()
}

func (l *branchLock) rlock() {
	l.mu.Lock()
	defer l.mu.Unlock()
	for l.held || l.urgent > 0 || l.writers > 0 {
		l.cond.Wait()
	}
	l.readers++
}

func (l *branchLock) runlock() {
	l.mu.Lock()
	l.readers--
	l.cond.Broadcast()
	l.mu.Unlock()
}

func (c *Code) branchLock(branch string) *branchLock {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.locks == nil {
		c.locks = map[string]*branchLock{}
	}
	l := c.locks[branch]
	if l == nil {
		l = &branchLock{}
		l.cond = sync.NewCond(&l.mu)
		c.locks[branch] = l
	}
	return l
}

// lock takes branch for its reconcile, or a /submit, alone.
func (c *Code) lock(branch string) func() {
	l := c.branchLock(branch)
	l.lock(false)
	return l.unlock
}

// lockUrgent is lock, ahead of anyone waiting for it without urgency: a
// merge in Gerrit must reach the PRs before replication does (§6.7),
// whatever comment syncs are waiting.
func (c *Code) lockUrgent(branch string) func() {
	l := c.branchLock(branch)
	l.lock(true)
	return l.unlock
}

// rlock takes branch shared, for a comment sync: alongside others, never
// alongside the branch's reconcile or a merge, which change PRs and
// their state.
func (c *Code) rlock(branch string) func() {
	l := c.branchLock(branch)
	l.rlock()
	return l.runlock
}

// maxPasses bounds plan/apply rounds per reconcile. New PRs need one pass
// to exist before a second can stack them and fill in the chain links.
const maxPasses = 5

// Reconcile mirrors the target branch named by k.Branch.
func (c *Code) Reconcile(ctx context.Context, k Key) error {
	var exported []int
	err := c.reconcile(withExported(ctx, &exported), k.Branch)
	// Handed on once the branch is let go of: what follows an export
	// (the new head's statuses) must not hold it.
	slices.Sort(exported)
	for _, n := range slices.Compact(exported) {
		if c.OnExported != nil {
			if err := c.OnExported(ctx, n); err != nil {
				c.Logger.Warn("post-export sync failed", "change", n, "err", err)
			}
		}
	}
	return err
}

func (c *Code) reconcile(ctx context.Context, branch string) error {
	ctx = context.WithValue(ctx, closedPRsKey{}, map[int]*github.PullRequest{})
	wait := trace.Region(ctx, "wait for branch "+branch+", alone")
	defer c.lock(branch)()
	wait()
	// Where GitHub owns the branch, Gerrit's is GitHub's first: what
	// merged there merges here, before anything is planned from it. If
	// Gerrit refuses it (a commit validator, a limit), the rest of the
	// branch is still mirrored, from Gerrit's older copy (what merged
	// waits for it), and the branch is tried again.
	followErr := c.Follow(ctx, branch)
	if followErr != nil {
		followErr = fmt.Errorf("following GitHub's %s: %w", branch, followErr)
		c.Logger.Warn("cannot copy GitHub's branch into Gerrit; mirroring the rest anyway", "branch", branch, "err", followErr)
	}
	// An import that failed (or wants a retry) does not hold back the
	// export of everything else; its error comes back at the end, so the
	// branch is tried again.
	var importErr error
	if c.Importer != nil {
		c.Importer.link = c.linkPR
		c.Importer.onImported = c.exported
		end := trace.Region(ctx, "import")
		listed := &openPulls{}
		before := exportedCount(ctx)
		err := c.Importer.Import(withOpenPulls(ctx, listed), branch)
		end()
		if exportedCount(ctx) == before && err == nil {
			// It changed nothing: what it listed is what export's first
			// look would list.
			ctx = withOpenPulls(ctx, listed)
		}
		if err != nil {
			importErr = fmt.Errorf("importing GitHub PRs for %s: %w", branch, err)
			c.Logger.Warn("import incomplete; exporting anyway", "branch", branch, "err", err)
		}
	}
	defer trace.Region(ctx, "export")()
	return cmp.Or(c.export(ctx, branch), importErr, followErr)
}

type exportedKey struct{}

// closedPRsKey carries the closed PRs a reconcile read one by one, so
// its later passes need not read them again (observe).
type closedPRsKey struct{}

// exportedCount is how many changes ctx's reconcile has exported so far.
func exportedCount(ctx context.Context) int {
	if list, ok := ctx.Value(exportedKey{}).(*[]int); ok {
		return len(*list)
	}
	return 0
}

// openPulls carries the open PRs one step of a reconcile listed to the
// next (the import's to export's first look): the same sync's read, used
// once.
type openPulls struct {
	prs    []github.PullRequest
	listed bool
}

type openPullsKey struct{}

func withOpenPulls(ctx context.Context, o *openPulls) context.Context {
	return context.WithValue(ctx, openPullsKey{}, o)
}

// listOpenPulls lists the open PRs: what the step before listed, if ctx
// carries it and nobody used it yet, else GitHub's answer now (kept for
// the step after, if ctx carries a place for it).
func listOpenPulls(ctx context.Context, gh *github.Client) ([]github.PullRequest, error) {
	o, _ := ctx.Value(openPullsKey{}).(*openPulls)
	if o != nil && o.listed {
		o.listed = false
		return slices.Clone(o.prs), nil
	}
	prs, err := gh.ListPulls(ctx, "open")
	if o != nil && err == nil {
		o.prs, o.listed = slices.Clone(prs), true
	}
	return prs, err
}

// withExported returns ctx collecting into list the changes exported
// under it (exported), for Reconcile to hand on.
func withExported(ctx context.Context, list *[]int) context.Context {
	return context.WithValue(ctx, exportedKey{}, list)
}

// export mirrors the target branch's changes to GitHub.
func (c *Code) export(ctx context.Context, branch string) error {
	handled := map[int]bool{}   // PRs whose GitHub side was mirrored this time
	skip := newSkips()          // what GitHub refused
	refused := map[int]string{} // changes whose push is refused: by the guard (""), or by GitHub
	for pass := 0; pass < maxPasses; pass++ {
		end := trace.Region(ctx, fmt.Sprintf("observe (pass %d)", pass+1))
		snap, err := c.observe(ctx, branch, refused)
		end()
		if err != nil {
			return fmt.Errorf("observing %s: %w", branch, err)
		}
		snap.hold(handled)
		if !c.DryRun && pass > 0 {
			// GitHub's side is mirrored on the first pass only: anything
			// newer waits for the next reconcile, and the plan leaves it
			// as it is (fourth audit: an edit to another PR before each
			// pass kept the branch from converging).
			snap.holdPending()
		}
		if !c.DryRun && pass == 0 {
			changed, err := c.mirrorPRStates(ctx, snap, handled)
			if err != nil {
				return fmt.Errorf("mirroring PR closes on %s: %w", branch, err)
			}
			edited, err := c.mirrorPREdits(ctx, snap, handled)
			if err != nil {
				return fmt.Errorf("mirroring PR edits on %s: %w", branch, err)
			}
			if changed || edited {
				continue // observe what changed in Gerrit
			}
		}
		plan := MakePlan(snap)
		plan.drop(skip)
		if len(plan.Actions) == 0 {
			if c.DryRun {
				c.Logger.Info("in sync", "branch", branch, "changes", len(plan.Desired))
				return nil
			}
			defer trace.Region(ctx, "record")()
			return c.record(ctx, snap, plan, skip)
		}
		for _, a := range plan.Actions {
			c.Logger.Info(map[bool]string{true: "dry run: would", false: "applying"}[c.DryRun], "branch", branch, "action", a.String())
		}
		if c.DryRun {
			return nil
		}
		more, err := c.refusedPushes(ctx, snap, plan)
		if err != nil {
			return err
		}
		if len(more) > 0 {
			// Withheld, and planned again without them.
			for _, n := range sortedKeys(more) {
				c.Logger.Warn("its push would bring "+withheldWhat+" changes to GitHub; withheld", "change", n)
				refused[n] = ""
			}
			continue
		}
		end = trace.Region(ctx, fmt.Sprintf("apply %d actions", len(plan.Actions)))
		err = c.apply(ctx, snap, plan, skip)
		end()
		if err != nil {
			var gr *githubRefused
			if !errors.As(err, &gr) {
				return err
			}
			// Withheld, and planned again without them.
			for _, n := range gr.changes {
				refused[n] = byGitHub
			}
		}
	}
	return fmt.Errorf("branch %s did not converge in %d passes", branch, maxPasses)
}

func (c *Code) changeURL(n int) string { return c.Gerrit.ChangeURL(c.Project, n) }

// withheldPaths are where GitHub reads repository configuration from:
// workflows (and the rest of .github/) on any branch pushed to the
// repository, and CODEOWNERS (also at the root and in docs/) on a PR's
// base branch, which for a stacked PR is a branch the bridge pushed. In
// any case: GitHub takes .GitHub/CODEOWNERS, CodeOwners and
// DOCS/CODEOWNERS too (eighth audit, checked live).
var withheldPaths = []string{":(icase).github", ":(icase)CODEOWNERS", ":(icase)docs/CODEOWNERS"}

// withheldWhat names withheldPaths in notices.
const withheldWhat = ".github/ or CODEOWNERS"

// changesConfig reports whether commit has files under withheldPaths
// that branch's tip, or the default branch's, does not have as they are
// (an old base counts: it would bring back what the branch has changed
// since), or, with history, any commit of it not on either changes them
// (a change below it, say, even if a later one changes them back: it
// would be pushed too, as the base of this one's PR). Neither needs a
// merge base. The default branch's workflows are the ones the site vets
// (§9.1); another branch's, an old release's or one pushed without
// review, need not keep away from bridge branches, so a change targeting
// it runs them as it is (eighth audit).
func (c *Code) changesConfig(ctx context.Context, branch, commit string, history bool) (bool, error) {
	for i, b := range []string{branch, c.DefaultBranch} {
		if b == "" || (i > 0 && b == branch) {
			continue
		}
		w, err := c.changesConfigOf(ctx, b, commit, history)
		if err != nil || w {
			return w, err
		}
	}
	return false, nil
}

// changesConfigOf is changesConfig for one branch.
func (c *Code) changesConfigOf(ctx context.Context, branch, commit string, history bool) (bool, error) {
	tip, err := c.Mirror.Git(ctx, nil, "rev-parse", "--verify", "refs/remotes/gerrit/heads/"+branch+"^{commit}")
	if err != nil {
		return false, err
	}
	key := fmt.Sprint(strings.TrimSpace(string(tip)), " ", commit, " ", history)
	c.wmu.Lock()
	w, ok := c.configCache[key]
	c.wmu.Unlock()
	if ok {
		return w, nil
	}
	// Only what it has there counts: lacking the branch's files is safe.
	_, err = c.Mirror.Git(ctx, nil, append([]string{"diff", "--quiet", "--no-renames", "--diff-filter=d", strings.TrimSpace(string(tip)), commit, "--"}, withheldPaths...)...)
	var xe *exec.ExitError
	switch {
	case err == nil && !history:
		w = false
	case err == nil:
		out, err := c.Mirror.Git(ctx, nil, append([]string{"rev-list", "--full-history", "-1", commit, "^" + strings.TrimSpace(string(tip)), "--"}, withheldPaths...)...)
		if err != nil {
			return false, err
		}
		w = strings.TrimSpace(string(out)) != ""
	case errors.As(err, &xe) && xe.ExitCode() == 1:
		w = true // differs
	default:
		return false, err
	}
	c.wmu.Lock()
	if c.configCache == nil || len(c.configCache) > 4096 {
		c.configCache = map[string]bool{}
	}
	c.configCache[key] = w
	c.wmu.Unlock()
	return w, nil
}

// withhold marks the open changes that change withheldPaths (design §7.1):
// anyone registered on Gerrit can upload one, and GitHub would run it,
// with the repository's secrets, from the branch the bridge pushes. So
// are those in refused, whose push the guard refuses (refusedPushes),
// and, where GitHub owns the branches, Gerrit-born ones from someone
// without a linked GitHub account that may push there (unpublished).
// Each gets a notice in Gerrit, once per patch set. Nothing here fails
// the branch: a change that cannot be checked is withheld, and a notice
// Gerrit will not take is not retried.
func (c *Code) withhold(ctx context.Context, s *Snapshot, branch string, refused map[int]string) error {
	s.Withheld = map[int]bool{}
	linked := map[int][2]bool{} // this look's answers, by account
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		if ch.Status != "NEW" || ch.Private {
			continue
		}
		why, w := refused[n]
		var err error
		if !w {
			w, err = c.changesConfig(ctx, branch, ch.Revision, true)
		}
		if err != nil {
			c.Logger.Warn("cannot tell whether a change touches "+withheldWhat+"; withheld", "change", n, "err", err)
			s.Withheld[n] = true
			continue
		}
		below := "" // what below it is not trusted, if that is why
		if !w && c.GitHubOwned && !s.githubBorn(n) {
			var known bool
			w, known, below, err = c.unpublished(ctx, s, ch, s.State[n], branch, linked)
			// Not known, and nothing named (GitHub could not say who may
			// push, say): withheld, and asked again next time, unsaid.
			if err != nil || (!known && below == "") {
				c.Logger.Warn("cannot tell whether a change's uploaders may push to GitHub; withheld", "change", n, "err", err)
				s.Withheld[n] = true
				continue
			}
			if w {
				why = notLinked
			}
		}
		if !w && c.GitHubOwned && !s.githubBorn(n) && (s.State[n] == nil || s.State[n].State.PR == 0) &&
			(ch.OwnerID == 0 || ch.OwnerID != c.BridgeAccount) {
			// (Not a change the bridge owns: an import whose link is not
			// saved yet, adopted by the importer, whose owner can never
			// link; twenty-first review.)
			// Its PR is opened as its owner (OpenAs): until they may,
			// nothing of it reaches GitHub.
			ok, known := false, true
			if c.Publishable != nil && c.OpenAs != nil {
				ok, known = c.Publishable(ctx, ch.OwnerID)
			}
			if !known {
				c.Logger.Warn("cannot tell whether a change's owner may push to GitHub; withheld", "change", n)
				s.Withheld[n] = true
				continue
			}
			if !ok {
				w, why = true, ownerNotLinked
			}
		}
		if !w {
			continue
		}
		s.Withheld[n] = true
		if st := s.State[n]; c.DryRun || (st != nil && st.State.WithheldNotice == ch.PatchSet) {
			continue
		}
		msg := fmt.Sprintf("Patch set %d is not mirrored to GitHub: it changes %s (here, below it in Gerrit or in the GitHub commits it "+
			"builds on, or by being based on an older version of the branch), and GitHub would use that, with the repository's secrets, from the branch the bridge pushes. "+
			"Review it here, or rebase it.", ch.PatchSet, withheldWhat)
		if c.GitHubOwned {
			// Nothing merges in Gerrit here: the way in is GitHub's.
			msg = fmt.Sprintf("Patch set %d is not mirrored to GitHub: it changes %s (here, below it in Gerrit or in the GitHub commits it "+
				"builds on, or by being based on an older version of the branch), which the bridge never pushes: GitHub would use that, "+
				"with the repository's secrets, from the branch it pushes. GitHub owns this repository's branches, so this cannot merge "+
				"from Gerrit: push it to a branch on GitHub yourself and open a PR there.", ch.PatchSet, withheldWhat)
		}
		switch why {
		case byGitHub:
			msg = fmt.Sprintf("Patch set %d is not mirrored to GitHub: GitHub refused its push (its push protection, on something in it "+
				"that looks like a secret, say). Review it here.", ch.PatchSet)
		case notLinked:
			msg = fmt.Sprintf("Patch set %d is not mirrored to GitHub: GitHub owns this repository's branches, and a change reaches it "+
				"only when %s", ch.PatchSet, c.whoMayPush(false, below))
		case ownerNotLinked:
			msg = fmt.Sprintf("Patch set %d is not mirrored to GitHub: GitHub owns this repository's branches, and a change's PR is "+
				"opened as its owner, so that GitHub knows whose it is. It gets one once its owner has linked a GitHub account that "+
				"may push to the repository.", ch.PatchSet)
			if c.LinkURL != "" {
				msg += " Link yours at " + c.LinkURL + "."
			}
		}
		if !c.notice(ctx, n, ch, msg) {
			continue
		}
		if err := c.updateState(ctx, n, "withheld notice", func(st *state.Change) { st.State.WithheldNotice = ch.PatchSet }); err != nil {
			return err
		}
		c.Logger.Info("withheld from GitHub", "change", n, "patch_set", ch.PatchSet, "why", cmp.Or(why, "changes "+withheldWhat))
	}
	return nil
}

// notice posts msg on change n's current patch set as the bridge, and
// reports whether it is done with: posted, or refused for good (a 4xx,
// such as the change's comment limit), which is logged.
func (c *Code) notice(ctx context.Context, n int, ch *GerritChange, msg string) bool {
	err := c.Gerrit.SetReview(ctx, n, ch.Revision, gerrit.ReviewInput{Message: msg, Tag: commentTag})
	var ge *gerrit.Error
	switch {
	case err == nil:
		return true
	case errors.As(err, &ge) && ge.Status >= 400 && ge.Status < 500:
		c.Logger.Warn("Gerrit refused a notice; not posting it", "change", n, "err", err)
		return true
	default:
		c.Logger.Warn("posting a notice", "change", n, "err", err)
		return false
	}
}

// deferOverBudget marks the changes that would get a new PR beyond their
// owner's PRBudget (lowest numbers first) as Deferred.
func (c *Code) deferOverBudget(ctx context.Context, s *Snapshot) {
	s.Deferred = map[int]bool{}
	if c.PRBudget == nil {
		return
	}
	want := map[int]int{}
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		if ch.Status != "NEW" || ch.Private || s.Withheld[n] {
			continue
		}
		if st := s.State[n]; st != nil && st.State.PR != 0 {
			continue
		}
		if _, onGitHub := s.GitHubBranches[s.head(n, ch.ChangeID)]; onGitHub {
			continue // begun already
		}
		if want[ch.OwnerID]++; want[ch.OwnerID] > c.PRBudget.Left(ctx, ch.OwnerID) {
			s.Deferred[n] = true
		}
	}
	if len(s.Deferred) > 0 {
		c.Logger.Info("new PRs deferred: their owners made too many lately", "changes", len(s.Deferred))
	}
}

// found reports whether rv records a commit found on GitHub (someone
// pushed Gerrit's commit to a GitHub-born PR's branch), not one the
// bridge put there or imported. main (a01d401) wrote those without Found
// (fifteenth review): on a GitHub-born change, a record that is not
// vetted (this branch vets every one it writes there) with one commit
// on both sides (an import's Gerrit commit carries a Change-Id the
// GitHub one may lack, an append's is Gerrit's own) is taken for one.
// That may take an old import of a commit that already had its Change-Id
// for found: that fails closed (a notice, a patch set looked at again).
func found(st *state.Change, rv state.Revision) bool {
	return rv.Found || (st != nil && st.State.Origin == "github" && !rv.Vetted && rv.GerritSHA == rv.GitHubSHA)
}

// ownerPass is the owner whose Gerrit patch sets may go to a GitHub-born
// change's PR branch, head, as theirs (mayPushToAuthor): owner, or, where
// GitHub owns the branches and head is the repository's own branch, none
// (0). That branch runs the repository's workflows with its secrets, so
// owning the change is no pass there, only being able to push to it (the
// owner may have lost write access since); a fork's branch is its
// author's.
func ownerPass(githubOwned bool, owner int, head string) int {
	if githubOwned && !isForkHead(head) {
		return 0
	}
	return owner
}

// pushTrust is who, besides a change's owner and the bridge, may have
// Gerrit patch sets pushed to a GitHub-born PR's branch: CI's trusted
// group, or, where GitHub owns the branches, publishable, which must be
// set there (nobody, unset).
// Chosen by the mode, never by which is set: GitHub-owned without
// publishable is nobody (twelfth review: the importer took a missing
// Publishable for Gerrit-owned).
func pushTrust(githubOwned bool, publishable, trusted func(context.Context, int) (bool, bool)) func(context.Context, int) (bool, bool) {
	if !githubOwned {
		return trusted
	}
	if publishable == nil {
		return func(context.Context, int) (bool, bool) { return false, true }
	}
	return publishable
}

// pushTrust is Code's pushTrust.
func (c *Code) pushTrust() func(context.Context, int) (bool, bool) {
	return pushTrust(c.GitHubOwned, c.Publishable, c.Trusted)
}

// PushTrust is who may have Gerrit code pushed to GitHub in this mode
// (pushTrust), for the budgets' exemption; it reads Code's fields when
// called, so set them first.
func (c *Code) PushTrust() func(context.Context, int) (bool, bool) {
	return func(ctx context.Context, account int) (bool, bool) { return c.pushTrust()(ctx, account) }
}

// unpublished reports whether Gerrit-born change ch may not reach GitHub,
// which owns the branches (design §3.1): someone responsible for its
// current patch set (its uploader, and whoever made its code or chose its
// parent: codeFrom) has no linked GitHub account that may push to the
// repository. known is false if that could not be told.
func (c *Code) unpublished(ctx context.Context, s *Snapshot, ch *GerritChange, st *state.Change, branch string, memo map[int][2]bool) (bool, bool, string, error) {
	may := func(ctx context.Context, account int) (bool, bool) {
		if r, ok := memo[account]; ok {
			return r[0], r[1]
		}
		ok, known := c.pushTrust()(ctx, account)
		memo[account] = [2]bool{ok, known}
		return ok, known
	}
	// Owner 0: owning the change is no pass; every one of them must be
	// publishable themselves.
	ok, known, why, err := c.mayReach(ctx, c.snapReader(s), ch, st, branch, 0, may)
	if err != nil {
		return true, false, "", err
	}
	return !ok, known, why, nil
}

// mayPushToAuthor reports whether a patch set uploaded in Gerrit by
// uploader (on their behalf by real, if not 0) may go to a GitHub-born
// PR's branch, which is its author's: only if each is the change's owner,
// the bridge, or in CI's trusted group. known is false if the group could
// not be read (then only the owner and the bridge count).
func mayPushToAuthor(ctx context.Context, trusted func(context.Context, int) (bool, bool), bridge, owner, uploader, real int) (ok, known bool) {
	known = true
	allowed := func(account int) bool {
		if account != 0 && (account == owner || account == bridge) {
			return true
		}
		if trusted == nil || account == 0 {
			return false
		}
		t, k := trusted(ctx, account)
		known = known && k
		return t && k
	}
	return allowed(uploader) && (real == 0 || allowed(real)), known
}

// gitHubHas is markForeign's, and the importer's, exception: a
// GitHub-born change's patch set GitHub already has
// (onGitHub) is nobody's to keep off its branch.
//
// In both directions (thirteenth review: where Gerrit owns the branches a
// stacked PR's own import, or an author's after they linked, was foreign).
func gitHubHas(st *state.Change, revision string) bool {
	return onGitHub(st, revision)
}

// onGitHub reports whether st records revision (a Gerrit commit) as one
// GitHub has: imported from the PR, or pushed there.
func onGitHub(st *state.Change, revision string) bool {
	if st == nil || revision == "" {
		return false
	}
	for _, r := range st.Revisions {
		// One found there (someone pushed Gerrit's commit to the PR's
		// branch) is GitHub's, but not this PR's author's: its text
		// would become their description (twelfth review).
		if r.GerritSHA == revision && r.GitHubSHA != "" && !found(st, r) {
			return true
		}
	}
	return false
}

// markForeign marks the GitHub-born changes whose current patch set was
// uploaded, or uploaded on someone's behalf, in Gerrit by someone other
// than the change's owner, the bridge or a member of CI's trusted group,
// or whose code or parent is such a patch set's below it (codeFrom; fourth audit:
// the owner's commit-message edit of a stranger's patch set carried it
// to the author's branch) (Snapshot.Foreign). Each gets a notice in
// Gerrit, once per patch set.
func (c *Code) markForeign(ctx context.Context, s *Snapshot) error {
	s.Foreign = map[int]bool{}
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		if ch.Status != "NEW" || !s.githubBorn(n) {
			continue
		}
		head := ""
		if st := s.State[n]; st != nil {
			head = st.State.HeadBranch
		}
		if gitHubHas(s.State[n], ch.Revision) {
			// GitHub has it already (imported from the PR, or pushed
			// there): there is nothing to keep off the branch, and the
			// PR still gets its description, with the Change-Id its
			// merge needs.
			continue
		}
		owner := ownerPass(c.GitHubOwned, ch.OwnerID, head)
		ok, known, below, err := c.mayReach(ctx, c.snapReader(s), ch, s.State[n], s.Branch, owner, c.pushTrust())
		if err != nil {
			c.Logger.Warn("cannot tell whose code a change's patch set is, or is below it; not pushing it", "change", n, "err", err)
			s.Foreign[n] = true
			continue
		}
		if ok {
			continue
		}
		s.Foreign[n] = true
		if st := s.State[n]; c.DryRun || (!known && below == "") || (st != nil && st.State.ForeignNotice == ch.PatchSet) {
			continue
		}
		msg := fmt.Sprintf("Patch set %d is not pushed to the GitHub PR's branch, which is its author's: a patch set is pushed there "+
			"only when %s", ch.PatchSet, c.whoMayPush(true, below))
		if !c.notice(ctx, n, ch, msg) {
			continue
		}
		if err := c.updateState(ctx, n, "foreign patch set notice", func(st *state.Change) { st.State.ForeignNotice = ch.PatchSet }); err != nil {
			return err
		}
		c.Logger.Info("not pushed to the author's branch: uploaded by someone else", "change", n, "patch_set", ch.PatchSet,
			"uploader", ch.UploaderID, "real_uploader", ch.RealUploaderID)
	}
	return nil
}

// codeFrom reports whether allowed holds for whoever is responsible for
// the code of patch set ps of revs, as gerrit-buildkite's codeTrusted
// decides it: for whoever chose its parent, the lowest patch set below it
// with the same parent commits (a REWORK keeps its parent when it edits
// the patch set below, Gerrit's web editor say, so a parent someone chose
// rebasing on the uploader's behalf stays theirs: sixth audit), and, for
// a merge, the same for its other parents, which a rebase of it keeps
// (seventh audit); and for whoever made its diff, the first REWORK below
// it, past commit-message edits and rebases. A kind this does not know,
// or a patch set whose commit is not said, is nobody's (fifth audit).
//
// Two differences from codeTrusted, on purpose (twelfth review): a
// message-only patch set onto other parent commits chose them here (it
// skips them; parentsTrusted then reads those parents either way), and a
// REWORK need not be its uploader's own commit (codeTrusted's own(),
// eighth audit): for a build, a trusted user with Forge Committer must not
// vouch for someone else's commit unread, but who may push here may push
// anyone's commit to GitHub themselves.
func codeFrom(revs map[int]gerrit.RevisionInfo, ps int, allowed func(gerrit.RevisionInfo) bool) bool {
	if r, ok := revs[chooser(revs, ps, slices.Equal[[]string])]; !ok || !allowed(r) {
		return false
	}
	if r := revs[ps]; len(r.Commit.Parents) > 1 {
		others := func(a, b []string) bool { return len(a) > 1 && len(b) > 1 && slices.Equal(a[1:], b[1:]) }
		if r, ok := revs[chooser(revs, ps, others)]; !ok || !allowed(r) {
			return false
		}
	}
	for ; ps >= 1; ps-- {
		r, ok := revs[ps]
		if !ok {
			return false
		}
		switch r.Kind {
		case "NO_CODE_CHANGE", "NO_CHANGE":
			continue // only the message changed: the code is below's
		case "TRIVIAL_REBASE", "TRIVIAL_REBASE_WITH_MESSAGE_UPDATE", "MERGE_FIRST_PARENT_UPDATE":
			continue // the same diff: whose is it?
		case "REWORK":
			return allowed(r)
		}
		return false
	}
	return false
}

// chooser is the patch set of revs that chose patch set ps's parents, as
// same compares their SHAs: walking down from it past patch sets with the
// same parents, the lowest; 0 if one is missing, or its commit was not
// read (no ALL_COMMITS).
func chooser(revs map[int]gerrit.RevisionInfo, ps int, same func(a, b []string) bool) int {
	for ; ps > 1; ps-- {
		r, ok := revs[ps]
		below, okBelow := revs[ps-1]
		if !ok || !okBelow {
			return 0
		}
		if !same(r.Commit.ParentSHAs(), below.Commit.ParentSHAs()) {
			break
		}
	}
	if r, ok := revs[ps]; !ok || r.Commit.Parents == nil {
		return 0
	}
	return ps
}

// revisionsByNumber is ci's revisions by patch set number.
func revisionsByNumber(ci *gerrit.ChangeInfo) map[int]gerrit.RevisionInfo {
	revs := map[int]gerrit.RevisionInfo{}
	for _, r := range ci.Revisions {
		revs[r.Number] = r
	}
	return revs
}

// authorsCode reports whether patch set ps of revs, a GitHub-born
// change's whose owner is owner, may reach its author's branch: its
// uploader may push there (its message is theirs), and so may whoever is
// responsible for its code (codeFrom). known is false if CI's trusted
// group could not be read. markForeign and the importer ask the same.
func authorsCode(ctx context.Context, trusted func(context.Context, int) (bool, bool), bridge, owner int, revs map[int]gerrit.RevisionInfo, ps int) (ok, known bool) {
	known = true
	allowed := func(r gerrit.RevisionInfo) bool {
		real := 0
		if r.RealUploader != nil {
			if r.RealUploader.AccountID == 0 {
				// Someone uploaded it on the uploader's behalf, and
				// Gerrit did not say who: nobody's (gerrit-buildkite's
				// RealUnknown; twelfth review).
				return false
			}
			real = r.RealUploader.AccountID
		}
		a, k := mayPushToAuthor(ctx, trusted, bridge, owner, r.Uploader.AccountID, real)
		known = known && k
		return a
	}
	cur, found := revs[ps]
	return found && allowed(cur) && codeFrom(revs, ps, allowed), known
}

// belowReader is what parentsTrusted reads, as gerrit-buildkite's reader
// is: a commit's parents, whether a commit is in a branch, the changes
// that have a commit as a patch set; and, the bridge's own, whether a
// change's state records a commit as on one of the repository's own
// branches (imported from it, or pushed there).
type belowReader interface {
	parentsOf(ctx context.Context, rev string) ([]string, error)
	inBranch(ctx context.Context, branch, sha string) (bool, error)
	changesOf(ctx context.Context, sha string) ([]gerrit.ChangeInfo, error)
	onRepoBranch(ctx context.Context, change int, sha, into string) (bool, error)
	// headOf is a GitHub-born change's PR branch as its state records it
	// (a fork's "owner/repo:branch"), "" if none.
	headOf(ctx context.Context, change int) (string, error)
}

// mirrorReader is belowReader from the bridge's mirror (whose
// refs/remotes/gerrit/heads/* observe has just fetched), Gerrit for what
// the mirror lacks, and the bridge's state.
type mirrorReader struct {
	g       *gerrit.Client
	m       *gitmirror.Repo
	store   *state.Store
	project string
}

func (r mirrorReader) parentsOf(ctx context.Context, rev string) ([]string, error) {
	out, err := r.m.Git(ctx, nil, "rev-list", "--parents", "-n1", rev)
	if err != nil {
		return nil, err
	}
	f := strings.Fields(string(out))
	if len(f) == 0 || f[0] != rev {
		return nil, fmt.Errorf("no commit %s in the mirror", short(rev))
	}
	return f[1:], nil
}

func (r mirrorReader) inBranch(ctx context.Context, branch, sha string) (bool, error) {
	_, err := r.m.Git(ctx, nil, "merge-base", "--is-ancestor", sha, "refs/remotes/gerrit/heads/"+branch)
	var ge *gitmirror.Error
	switch {
	case err == nil:
		return true, nil
	case errors.As(err, &ge) && ge.Stderr == "":
		return false, nil // exit 1: not an ancestor
	}
	// Not in the mirror (an old patch set's commit, or no copy of the
	// branch here): Gerrit says.
	return r.g.InBranch(ctx, r.project, branch, sha)
}

func (r mirrorReader) changesOf(ctx context.Context, sha string) ([]gerrit.ChangeInfo, error) {
	return r.g.QueryChanges(ctx, "project:"+gerrit.QueryString(r.project)+" commit:"+sha, "ALL_REVISIONS", "ALL_COMMITS", "DETAILED_ACCOUNTS")
}

func (r mirrorReader) onRepoBranch(ctx context.Context, change int, sha, into string) (bool, error) {
	if r.store == nil {
		return false, nil
	}
	st, err := r.store.Load(ctx, change)
	if err != nil {
		return false, err
	}
	return recordedOnRepoBranch(st, sha, into), nil
}

func (r mirrorReader) headOf(ctx context.Context, change int) (string, error) {
	if r.store == nil {
		return "", nil
	}
	st, err := r.store.Load(ctx, change)
	if err != nil {
		return "", err
	}
	return st.State.HeadBranch, nil
}

// recordedOnRepoBranch reports whether st records Gerrit commit sha as
// imported from, or pushed to, its PR's branch, one of the repository's
// own (not a fork's: code there never ran with the repository's secrets),
// its code vetted on the way (Vetted): GitHub has it there, and pushed
// again it brings nothing new. Not one found there (Found: whoever put it
// there is not known), nor one pushed unvetted (fourteenth review: where
// Gerrit owns the branches every registered user's change is pushed to
// one, and was taken for vouched-for code below a trusted user's).
//
// A fork's record counts only for a push into that same fork (into, the
// pushed change's head): its own code going back to it brings nothing
// new (fourteenth review: an author's fork stack was refused the swap).
func recordedOnRepoBranch(st *state.Change, sha, into string) bool {
	if st == nil {
		return false
	}
	if fork, _, ok := github.SplitHeadKey(st.State.HeadBranch); ok {
		if target, _, intoFork := github.SplitHeadKey(into); !intoFork || !strings.EqualFold(target, fork) {
			return false
		}
	}
	for _, r := range st.Revisions {
		// A GitHub-born change's records are imports, or appends that
		// passed markForeign: vetted, whenever written; a Gerrit-born
		// one's only if marked so.
		if r.GerritSHA == sha && r.GitHubSHA != "" && !found(st, r) && (r.Vetted || st.State.Origin == "github") {
			return true
		}
	}
	return false
}

// memoReader answers each question of r once: for one look at a branch
// (or one import), never longer (thirteenth review: a chain's walks asked
// the same commits again for every change).
type memoReader struct {
	r       belowReader
	in      map[string]bool
	changes map[string][]gerrit.ChangeInfo
	onRepo  map[string]bool
}

func newMemoReader(r belowReader) *memoReader {
	return &memoReader{r: r, in: map[string]bool{}, changes: map[string][]gerrit.ChangeInfo{}, onRepo: map[string]bool{}}
}

func (m *memoReader) parentsOf(ctx context.Context, rev string) ([]string, error) {
	return m.r.parentsOf(ctx, rev)
}

func (m *memoReader) inBranch(ctx context.Context, branch, sha string) (bool, error) {
	k := branch + " " + sha
	if v, ok := m.in[k]; ok {
		return v, nil
	}
	v, err := m.r.inBranch(ctx, branch, sha)
	if err == nil {
		m.in[k] = v
	}
	return v, err
}

func (m *memoReader) changesOf(ctx context.Context, sha string) ([]gerrit.ChangeInfo, error) {
	if v, ok := m.changes[sha]; ok {
		return v, nil
	}
	v, err := m.r.changesOf(ctx, sha)
	if err == nil {
		m.changes[sha] = v
	}
	return v, err
}

func (m *memoReader) headOf(ctx context.Context, change int) (string, error) {
	return m.r.headOf(ctx, change)
}

func (m *memoReader) onRepoBranch(ctx context.Context, change int, sha, into string) (bool, error) {
	k := fmt.Sprint(change, " ", sha, " ", into)
	if v, ok := m.onRepo[k]; ok {
		return v, nil
	}
	v, err := m.r.onRepoBranch(ctx, change, sha, into)
	if err == nil {
		m.onRepo[k] = v
	}
	return v, err
}

// maxBelow bounds the commits below a patch set parentsTrusted reads, as
// gerrit-buildkite's does.
const maxBelow = 50

// parentsTrusted is gerrit-buildkite's parentsTrusted (trust.go), the
// same question for a push to GitHub as for a build: whether commit rev's
// parents, of a patch set on branch, are trusted code, by trusted (as
// authorsCode asks it, owning a change no pass): in the branch already,
// the commit a change merged as, or a patch set of a change (any:
// outdated, abandoned, the one below in a chain) whose code authorsCode
// trusts, on parents trusted the same way. Whoever chose a parent need
// not have read it: anyone may add a patch set to the change below a
// trusted user's, which Gerrit's Rebase then puts under theirs (twelfth
// review: the bridge had its own, weaker rule). known is false if that
// could not be told (trusted could not say, or a parent is one the bridge
// cannot see); why names what is not trusted.
//
// The bridge's own, besides: a commit this change already has on its
// PR's branch (already), or that a change's state records as on one of
// the repository's own branches (recordedOnRepoBranch), is as the branch
// is, and the walk stops there (thirteenth review: an in-repo PR's code
// has run with the repository's secrets already; and a chain of mirrored
// changes is a step each, not a walk each).
//
// owner is the pushed change's owner where it has the owner's pass
// (ownerPass), else 0: a change below that it also owns passes on the
// same terms as its own, every patch set's code its or the trusted's
// (fifteenth review, a Gerrit-owned regression: an author's own Gerrit
// change below their GitHub-born PR made it foreign). Anyone else's
// below has no owner's pass.
func parentsTrusted(ctx context.Context, r belowReader, branch, into string, parents []string, already map[string]bool,
	trusted func(context.Context, int) (bool, bool), bridge, owner int) (ok, known bool, why string, err error) {
	known = true
	seen := map[string]bool{}
	for todo := parents; len(todo) > 0; todo = todo[1:] {
		sha := todo[0]
		if seen[sha] {
			continue
		}
		if seen[sha] = true; len(seen) > maxBelow {
			return false, known, fmt.Sprintf("more than %d commits below it that are neither on the branch nor on GitHub", maxBelow), nil
		}
		if already[sha] {
			continue
		}
		in, err := r.inBranch(ctx, branch, sha)
		if err != nil {
			return false, known, "", fmt.Errorf("is %s in %s? %w", short(sha), branch, err)
		}
		if in {
			continue
		}
		cs, err := r.changesOf(ctx, sha)
		if err != nil {
			return false, known, "", fmt.Errorf("finding %s's change: %w", short(sha), err)
		}
		if len(cs) == 0 {
			// Not in the branch, and no patch set the bridge can see (a
			// private change's, say): not known to be anyone's.
			return false, false, fmt.Sprintf("commit %s below it, which is neither on the branch nor a patch set the bridge can see", short(sha)), nil
		}
		for i := range cs {
			ci := &cs[i]
			if ci.Status == "MERGED" && ci.CurrentRevision == sha {
				continue
			}
			p, found := ci.Revisions[sha]
			if !found {
				return false, false, fmt.Sprintf("commit %s below it", short(sha)), nil
			}
			on, err := r.onRepoBranch(ctx, ci.Number, sha, into)
			if err != nil {
				return false, known, "", fmt.Errorf("reading change %d's state: %w", ci.Number, err)
			}
			if on {
				continue // GitHub has it, and all below it, on a branch of its own
			}
			// No pass for the bridge's own uploads below: an import of
			// an unlinked author's PR (a fork's, say) is theirs, and
			// CI's trusted group has no bridge in it either. The owner's
			// pass is a person's: where the pushed change is the
			// bridge's (an unlinked author's import), only for the
			// bridge's change of a PR from the same fork, the same
			// author's (sixteenth review: given to the bridge, other
			// strangers' imports below passed; seventeenth: withheld
			// from it, an unlinked author's own change below was a
			// stranger's).
			lower := 0
			switch {
			case owner == 0 || ci.Owner.AccountID != owner:
			case owner != bridge:
				lower = owner
			default:
				same, err := sameFork(ctx, r, into, ci.Number)
				if err != nil {
					return false, known, "", fmt.Errorf("reading change %d's state: %w", ci.Number, err)
				}
				if same {
					lower = owner
				}
			}
			revs := revisionsByNumber(ci)
			for n, rv := range revs {
				if bridge != 0 && rv.RealUploader != nil && rv.RealUploader.AccountID == bridge {
					// The bridge's import as its uploader (Run-As) is
					// their push: theirs, as if they had uploaded it
					// (sixteenth review: an author's own import below
					// their PR made it foreign). The bridge's own
					// uploads still have no pass.
					rv.RealUploader = nil
					revs[n] = rv
				}
			}
			ok, k := authorsCode(ctx, trusted, 0, lower, revs, p.Number)
			if !ok && !k {
				// Could not be told (GitHub did not say who may push):
				// nobody is blamed; asked again next time.
				return false, false, "", nil
			}
			known = known && k
			if !ok {
				return false, known, fmt.Sprintf("change %d's patch set %d below it (commit %s)", ci.Number, p.Number, short(sha)), nil
			}
			todo = append(todo, p.Commit.ParentSHAs()...)
		}
	}
	return true, known, "", nil
}

// mayReach is the one answer to whether change ch's current patch set may
// be pushed to GitHub (design §3.1, §6.5; twelfth review: four places
// asked it four ways): whoever uploaded it, made its code and chose its
// parents is trusted (authorsCode; owner, if not 0, passes for this
// change), and so is the code below it (parentsTrusted, read through r).
// The callers only decide what a no means: withheld, foreign, not
// restored. known is false if that could not be told; why, when below,
// names what is not trusted; err, if Gerrit or the mirror could not be
// read (then not ok).
func (c *Code) mayReach(ctx context.Context, r belowReader, ch *GerritChange, st *state.Change, branch string, owner int,
	trusted func(context.Context, int) (bool, bool)) (ok, known bool, why string, err error) {
	// A first patch set that is a REWORK is its uploader's: no need to
	// read the rest.
	first := gerrit.RevisionInfo{Number: 1, Kind: "REWORK", Uploader: gerrit.AccountInfo{AccountID: ch.UploaderID}}
	if ch.PatchSet == 1 && ch.Kind == "REWORK" {
		// Its parents from the mirror, which observe fetched it into.
		parents, err := r.parentsOf(ctx, ch.Revision)
		if err != nil {
			return false, false, "", err
		}
		first.Commit.Parents = make([]struct {
			Commit string `json:"commit"`
		}, 0, len(parents))
		for _, p := range parents {
			first.Commit.Parents = append(first.Commit.Parents, struct {
				Commit string `json:"commit"`
			}{p})
		}
	}
	if ch.RealUploaderID != 0 {
		first.RealUploader = &gerrit.AccountInfo{AccountID: ch.RealUploaderID}
	}
	revs := map[int]gerrit.RevisionInfo{1: first}
	if ch.PatchSet > 1 || ch.Kind != "REWORK" || ch.RealUploaderUnknown {
		ci, err := c.Gerrit.GetChange(ctx, ch.Number, "ALL_REVISIONS", "ALL_COMMITS")
		if err != nil {
			return false, false, "", err
		}
		revs = revisionsByNumber(ci)
	}
	return mayReach(ctx, r, trusted, c.BridgeAccount, owner, revs, ch.PatchSet, branch, st)
}

// mayReach is Code.mayReach for patch set ps of revs (whose commits, and
// so parents, are read: authorsCode refuses one whose are not).
func mayReach(ctx context.Context, r belowReader, trusted func(context.Context, int) (bool, bool), bridge, owner int,
	revs map[int]gerrit.RevisionInfo, ps int, branch string, st *state.Change) (ok, known bool, why string, err error) {
	ok, known = authorsCode(ctx, trusted, bridge, owner, revs, ps)
	if !ok {
		return false, known, "", nil
	}
	already := map[string]bool{}
	if st != nil {
		for _, rv := range st.Revisions {
			if rv.GitHubSHA != "" && !found(st, rv) {
				already[rv.GerritSHA] = true
			}
		}
	}
	into := ""
	if st != nil {
		into = st.State.HeadBranch
	}
	ok, k, why, err := parentsTrusted(ctx, r, branch, into, revs[ps].Commit.ParentSHAs(), already, trusted, bridge, owner)
	return ok && err == nil, known && k, why, err
}

// sameFork reports whether change's PR is from the fork into (the pushed
// change's PR branch) is: one author's, as recordedOnRepoBranch takes a
// fork's records for its own.
func sameFork(ctx context.Context, r belowReader, into string, change int) (bool, error) {
	fork, _, ok := github.SplitHeadKey(into)
	if !ok || fork == "" {
		return false, nil
	}
	head, err := r.headOf(ctx, change)
	if err != nil {
		return false, err
	}
	other, _, ok := github.SplitHeadKey(head)
	return ok && strings.EqualFold(other, fork), nil
}

// snapReader is the reader for one look at a branch: s's, made once.
func (c *Code) snapReader(s *Snapshot) belowReader {
	if s.below == nil {
		s.below = newMemoReader(c.belowReader())
	}
	return s.below
}

// belowReader is the Code's: Below, or its mirror, Gerrit and state.
func (c *Code) belowReader() belowReader {
	if c.Below != nil {
		return c.Below
	}
	return mirrorReader{c.Gerrit, c.Mirror, c.Store, c.Project}
}

// observe gathers a Snapshot for branch from Gerrit, the mirror, GitHub
// and refs/bridge.
func (c *Code) observe(ctx context.Context, branch string, refused map[int]string) (*Snapshot, error) {
	s := &Snapshot{
		Branch: branch, DefaultBranch: c.DefaultBranch,
		Changes: map[int]*GerritChange{}, OnBranch: map[string]bool{},
		GitHubBranches: map[string]string{}, PRs: map[int]*github.PullRequest{},
		State:       map[int]*state.Change{},
		Repo:        c.GitHub.Owner + "/" + c.GitHub.Repo,
		GitHubOwned: c.GitHubOwned,
	}
	infos, err := c.Gerrit.QueryChanges(ctx,
		"project:"+gerrit.QueryString(c.Project)+" branch:"+gerrit.QueryString(branch)+" status:open",
		"CURRENT_REVISION", "CURRENT_COMMIT", "DETAILED_ACCOUNTS")
	if err != nil {
		return nil, err
	}
	// Open PRs, listed up front: a closed change whose PR is still open
	// (a merge waiting for replication, design §6.7) stays in the snapshot,
	// so its PR is still managed and its head branch kept.
	openPRs, err := listOpenPulls(ctx, c.GitHub)
	if err != nil {
		return nil, err
	}
	prOpen := map[int]bool{}
	for _, pr := range openPRs {
		prOpen[pr.Number] = true
	}
	// Changes we mirrored that may have closed since.
	open := map[int]bool{}
	for _, ci := range infos {
		open[ci.Number] = true
	}
	for _, n := range c.Store.ChangesOnBranch(branch) {
		st, err := c.Store.Load(ctx, n)
		if err != nil {
			return nil, err
		}
		s.State[n] = st
		if open[n] || (st.State.Lifecycle != "NEW" && !prOpen[st.State.PR]) {
			continue
		}
		ci, err := c.Gerrit.GetChange(ctx, n, "CURRENT_REVISION", "CURRENT_COMMIT", "DETAILED_ACCOUNTS")
		var ge *gerrit.Error
		if errors.As(err, &ge) && ge.Status == http.StatusNotFound {
			// Made private (or deleted): the bridge can no longer see it,
			// and its PR closes as for a private change, the rest of the
			// branch going on (eighth audit: its owner stopped it).
			s.Changes[n] = &GerritChange{Number: n, ChangeID: st.State.ChangeID, Status: "NEW", Private: true, URL: c.changeURL(n)}
			continue
		}
		if err != nil {
			return nil, err
		}
		infos = append(infos, *ci)
	}

	refspecs := []string{"+refs/heads/" + branch + ":refs/remotes/gerrit/heads/" + branch}
	if c.DefaultBranch != "" && c.DefaultBranch != branch {
		// What withhold compares with too.
		refspecs = append(refspecs, "+refs/heads/"+c.DefaultBranch+":refs/remotes/gerrit/heads/"+c.DefaultBranch)
	}
	for _, ci := range infos {
		rev, ok := ci.Current()
		if !ok {
			continue
		}
		s.Changes[ci.Number] = &GerritChange{
			Number: ci.Number, ChangeID: ci.ChangeID, Status: ci.Status,
			WIP: ci.WorkInProgress, Private: ci.IsPrivate,
			Subject: rev.Commit.Subject, Message: rev.Commit.Message,
			PatchSet: rev.Number, Revision: ci.CurrentRevision, Parent: rev.Commit.Parent(),
			URL: c.changeURL(ci.Number), Owner: ci.Owner.Username, Uploader: rev.Uploader.Username,
			OwnerID: ci.Owner.AccountID, UploaderID: rev.Uploader.AccountID, Kind: rev.Kind,
		}
		if rev.RealUploader != nil {
			s.Changes[ci.Number].RealUploaderID = rev.RealUploader.AccountID
			// Not said who (0): mayReach reads the patch set to refuse it.
			s.Changes[ci.Number].RealUploaderUnknown = rev.RealUploader.AccountID == 0
		}
		if ci.Status == "NEW" && !ci.IsPrivate {
			refspecs = append(refspecs, "+"+rev.Ref+":refs/remotes/gerrit/"+strings.TrimPrefix(rev.Ref, "refs/"))
		}
		if s.State[ci.Number] == nil {
			st, err := c.Store.Load(ctx, ci.Number)
			if err != nil {
				return nil, err
			}
			s.State[ci.Number] = st
		}
	}
	if _, err := c.Mirror.Git(ctx, nil, append([]string{"fetch", "--quiet", "origin"}, refspecs...)...); err != nil {
		return nil, err
	}
	if err := c.withhold(ctx, s, branch, refused); err != nil {
		return nil, err
	}
	if err := c.markForeign(ctx, s); err != nil {
		return nil, err
	}
	c.deferOverBudget(ctx, s)
	// Open changes' revisions are no branch's; a merged change's is its
	// merge, on the branch (a squash on GitHub, say: the change above it,
	// imported onto it, was frozen at it, its approvals dismissed).
	revs := map[string]bool{}
	for _, ch := range s.Changes {
		if ch.Status == "NEW" {
			revs[ch.Revision] = true
		}
	}
	for _, ch := range s.Changes {
		if ch.Parent == "" || revs[ch.Parent] || s.OnBranch[ch.Parent] {
			continue
		}
		_, err := c.Mirror.Git(ctx, nil, "merge-base", "--is-ancestor", ch.Parent, "refs/remotes/gerrit/heads/"+branch)
		var ge *gitmirror.Error
		switch {
		case err == nil:
			s.OnBranch[ch.Parent] = true
		case errors.As(err, &ge) && ge.Stderr == "":
			// Exit 1: not an ancestor.
		default:
			return nil, err
		}
	}

	// GitHub: bridge branches, PRs and stacks.
	env, err := c.githubEnv(ctx)
	if err != nil {
		return nil, err
	}
	// Which merged revisions has replication brought to GitHub yet?
	s.OnGitHubBranch = map[string]bool{}
	// Only where Gerrit owns the branch (replication); where GitHub does,
	// Follow has fetched it already.
	if !c.GitHubOwned {
		if _, err := c.Mirror.GitEnv(ctx, env, nil, "-c", fsckFetch, "fetch", "--quiet", c.GitHubURL,
			"+refs/heads/"+branch+":refs/remotes/github/heads/"+branch); err == nil {
			for _, ch := range s.Changes {
				if ch.Status != "MERGED" {
					continue
				}
				if _, err := c.Mirror.Git(ctx, nil, "merge-base", "--is-ancestor", ch.Revision, "refs/remotes/github/heads/"+branch); err == nil {
					s.OnGitHubBranch[ch.Revision] = true
				}
			}
		}
	}
	out, err := c.Mirror.GitEnv(ctx, env, nil, "ls-remote", c.GitHubURL, "refs/heads/"+headPrefix+"*", "refs/heads/"+frozenPrefix+"*")
	if err != nil {
		return nil, err
	}
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		sha, ref, ok := strings.Cut(line, "\t")
		if !ok {
			continue
		}
		name := strings.TrimPrefix(ref, "refs/heads/")
		if strings.HasPrefix(name, headPrefix) || strings.HasPrefix(name, frozenPrefix) {
			s.GitHubBranches[name] = sha
		}
	}

	heads := map[string]int{}
	linkedPR := map[int]bool{}
	for n, ch := range s.Changes {
		heads[s.head(n, ch.ChangeID)] = n
		if st := s.State[n]; st != nil && st.State.PR != 0 {
			linkedPR[st.State.PR] = true
		}
	}
	repoName := c.GitHub.Owner + "/" + c.GitHub.Repo
	byNumber := map[int]*github.PullRequest{}
	for i := range openPRs {
		pr := &openPRs[i]
		byNumber[pr.Number] = pr
		n, ok := heads[pr.HeadKey(repoName)]
		if !ok {
			continue
		}
		if c.GitHubOwned && !linkedPR[pr.Number] && !c.adoptable(ctx, s.Changes[n], pr) {
			continue
		}
		s.PRs[pr.Number] = pr
	}
	if err := c.markUnlinked(ctx, s, repoName, byNumber); err != nil {
		return nil, err
	}
	closedPRs, _ := ctx.Value(closedPRsKey{}).(map[int]*github.PullRequest)
	for n, st := range s.State {
		if pr := st.State.PR; pr != 0 && s.PRs[pr] == nil && s.Changes[n] != nil {
			if got := closedPRs[pr]; got != nil && !prOpen[pr] {
				// Read closed earlier in this reconcile and not open now
				// (the list above is this pass's): still closed, and a
				// closed PR's head does not move.
				s.PRs[pr] = got
				continue
			}
			got, err := c.GitHub.GetPull(ctx, pr)
			if github.IsNotFound(err) {
				continue
			}
			if err != nil {
				return nil, err
			}
			s.PRs[pr] = got
			if closedPRs != nil && got.State != "open" {
				closedPRs[pr] = got
			}
		}
	}
	// GitHub-born changes live on the user's branch: take its head from
	// the PR.
	s.SameTree = map[int]string{}
	s.NoPush = map[int]bool{}
	for n := range s.Changes {
		st := s.State[n]
		if !s.githubBorn(n) || st.State.PR == 0 || s.PRs[st.State.PR] == nil {
			continue
		}
		pr := s.PRs[st.State.PR]
		if pr.State != "open" || pr.Head.SHA == "" {
			continue
		}
		s.GitHubBranches[st.State.HeadBranch] = pr.Head.SHA
		if _, _, fork := github.SplitHeadKey(st.State.HeadBranch); fork {
			full, err := c.GitHub.GetPull(ctx, pr.Number) // listed PRs lack maintainer_can_modify
			if err != nil {
				return nil, err
			}
			s.NoPush[n] = !full.MaintainerCanModify
		}
	}

	if err := c.observeHistory(ctx, s, env); err != nil {
		return nil, err
	}

	stacks, err := c.GitHub.ListStacks(ctx)
	if err != nil {
		return nil, err
	}
	for i := range stacks {
		st := &stacks[i]
		if !st.Open {
			continue
		}
		for _, n := range st.Numbers() {
			if s.PRs[n] != nil {
				s.Stacks = append(s.Stacks, st)
				break
			}
		}
	}
	return s, nil
}

// markUnlinked sets s.Unlinked, given repo's open PRs by number. The
// trailer that counts is patch set 1's, which its owner uploaded: anyone
// may add a later patch set with one naming the owner's own open PR, and
// so hide their change (fifth audit).
func (c *Code) markUnlinked(ctx context.Context, s *Snapshot, repo string, open map[int]*github.PullRequest) error {
	s.Unlinked = map[int]bool{}
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		num, ok := importedFrom(ch.Message, repo)
		if st := s.State[n]; !ok || (st != nil && st.State.PR != 0) {
			continue
		}
		if ch.PatchSet != 1 {
			ci, err := c.Gerrit.GetChange(ctx, n, "ALL_REVISIONS", "ALL_COMMITS")
			if err != nil {
				// It waits; the rest of the branch does not (sixth
				// audit: anyone can make one change hard to read).
				c.Logger.Warn("cannot read a change's patch sets; not exporting it for now", "change", n, "err", err)
				s.Unlinked[n] = true
				continue
			}
			first, ok := revisionsByNumber(ci)[1]
			if n1, ok1 := importedFrom(first.Commit.Message, repo); !ok || !ok1 || n1 != num {
				continue
			}
		}
		if ch.OwnerID != 0 && ch.OwnerID == c.BridgeAccount {
			s.Unlinked[n] = true
		} else if pr := open[num]; pr != nil && c.Identity != nil {
			author, ok, err := c.Identity.Lookup(ctx, pr.User)
			if err != nil {
				return err
			}
			s.Unlinked[n] = ok && strings.EqualFold(author, ch.Owner)
		}
	}
	return nil
}

// observeHistory fills in HasParent and SameTree for changes whose GitHub
// head stands for an older patch set: a new patch set goes on top of that
// history (design §5.2.1).
func (c *Code) observeHistory(ctx context.Context, s *Snapshot, env []string) error {
	s.HasParent = map[int]bool{}
	var todo []int
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		gh, ok := s.GitHubBranches[s.head(n, ch.ChangeID)]
		if ch.Status != "NEW" || ch.Private || !ok || gh == ch.Revision {
			continue
		}
		if _, known := s.githubFor(n)[gh]; known {
			todo = append(todo, n)
		}
	}
	if len(todo) == 0 {
		return nil
	}
	// The heads are commits the bridge made, but the mirror may not have
	// them (a fresh mirror, or another replica made them).
	var specs []string
	for _, n := range todo {
		head := s.head(n, s.Changes[n].ChangeID)
		local := "refs/remotes/github/heads/" + head
		spec := "+refs/heads/" + head + ":" + local
		if _, _, fork := github.SplitHeadKey(head); fork {
			// GitHub keeps every PR's head in the base repository.
			pr := s.State[n].State.PR
			local = fmt.Sprintf("refs/remotes/github/pull/%d", pr)
			spec = fmt.Sprintf("+refs/pull/%d/head:%s", pr, local)
		}
		// todo has only heads GitHub listed (GitHubBranches), so never ""
		// for a ref the mirror lacks.
		if have, err := c.Mirror.RevParse(ctx, local); err == nil && have == s.GitHubBranches[head] {
			continue // fetched already (the import's, say): at what GitHub just said
		}
		specs = append(specs, spec)
	}
	if len(specs) > 0 {
		if _, err := c.Mirror.GitEnv(ctx, env, nil, append([]string{"-c", fsckFetch, "fetch", "--quiet", c.GitHubURL}, specs...)...); err != nil {
			return err
		}
	}
	for _, n := range todo {
		ch := s.Changes[n]
		gh := s.GitHubBranches[s.head(n, ch.ChangeID)]
		_, err := c.Mirror.Git(ctx, nil, "merge-base", "--is-ancestor", s.ghCommit(ch.Parent), gh)
		var ge *gitmirror.Error
		switch {
		case err == nil:
			s.HasParent[n] = true
		case errors.As(err, &ge) && ge.Stderr == "":
			// Exit 1: rebased onto something the head does not contain.
		default:
			return err
		}
		if s.HasParent[n] {
			out, err := c.Mirror.Git(ctx, nil, "rev-parse", ch.Revision+"^{tree}", gh+"^{tree}")
			if f := strings.Fields(string(out)); err == nil && len(f) == 2 && f[0] == f[1] {
				s.SameTree[n] = gh
			}
		}
	}
	return nil
}

// mirrorPRStates carries a PR closed or reopened on GitHub over to Gerrit
// (design §6.6): closing abandons the change, reopening restores it, each
// as the person who did it (Run-As), so Gerrit's permissions decide. If
// Gerrit refuses, or they have no Gerrit account, nothing changes there:
// the plan then puts the PR back the way Gerrit says, and a notice says
// why. It reports whether a change was abandoned or restored.
func (c *Code) mirrorPRStates(ctx context.Context, s *Snapshot, handled map[int]bool) (bool, error) {
	changed := false
	for _, n := range sortedKeys(s.Changes) {
		ch, st := s.Changes[n], s.State[n]
		if st == nil || st.State.PR == 0 || s.PRs[st.State.PR] == nil || handled[st.State.PR] {
			continue
		}
		pr := s.PRs[st.State.PR]
		if ch.Status == "NEW" && pr.Merged {
			did, err := c.mergedOnGitHub(ctx, s, n, ch, pr)
			if err != nil {
				return changed, err
			}
			if did {
				changed, handled[pr.Number] = true, true
			}
			continue
		}
		var action, past string
		switch {
		case ch.Status == "NEW" && pr.State == "closed" && !pr.Merged:
			action, past = "abandon", "closed"
		case ch.Status == "ABANDONED" && pr.State == "open":
			action, past = "restore", "reopened"
		default:
			continue
		}
		ev, err := c.GitHub.LastStateEvent(ctx, pr.Number)
		if err != nil {
			return changed, err
		}
		if ev == nil || ev.Event != past || (c.BridgeLogin != "" && strings.EqualFold(ev.Actor.Login, c.BridgeLogin)) {
			continue // the bridge's own doing, or nobody's: the plan decides
		}
		// A close older than Gerrit's own last abandon or restore is
		// history (say the change was restored in Gerrit since): Gerrit
		// wins, and the plan puts the PR back the way Gerrit says.
		if last, err := c.lastStatusChange(ctx, n); err != nil {
			return changed, err
		} else if !ev.CreatedAt.After(last) {
			continue
		}
		login := ev.Actor.Login
		user, ok := "", false
		if c.Identity != nil {
			var err error
			if user, ok, err = c.Identity.Lookup(ctx, ev.Actor); err != nil {
				return false, err
			}
		}
		g := c.Gerrit
		if ok {
			g = c.Gerrit.As(user)
		} else if sameGitHubUser(ev.Actor, pr.User) && c.BridgeUser != "" && strings.EqualFold(ch.Owner, c.BridgeUser) {
			// Their own PR, which the bridge owns for them (as asEditor
			// says; fourth audit: refused, each close was reopened, over
			// and over).
			user, ok = c.BridgeUser, true
		}
		var why string
		if !ok {
			why = c.noAccount("@" + login)
		} else {
			msg := fmt.Sprintf("PR #%d %s on GitHub.", pr.Number, past)
			err := g.Do(ctx, http.MethodPost, fmt.Sprintf("changes/%d/%s", n, action), map[string]string{"message": msg}, nil)
			if err == nil {
				c.Logger.Info("mirrored GitHub "+past+" to Gerrit", "change", n, "pr", pr.Number, "action", action, "as", user)
				changed, handled[pr.Number] = true, true
				continue
			}
			var ge *gerrit.Error
			if !errors.As(err, &ge) || ge.Status >= 500 {
				return changed, fmt.Errorf("%s change %d as %s: %w", action, n, user, err)
			}
			why = fmt.Sprintf("Gerrit refused it as %s (%s). Only the change's owner and users with the Abandon permission can %s it.", user, forGitHub(strings.TrimSpace(ge.Body)), action)
		}
		undo := "The PR is reopened"
		if action == "restore" {
			undo = "The PR is closed again"
		}
		note := fmt.Sprintf("@%s %s this PR, but the bridge can't %s [change %d](%s) in Gerrit to match. %s %s.\n\n%s",
			login, past, action, n, ch.URL, why, undo, noticeMarker)
		if _, err := c.GitHub.CreateIssueComment(ctx, pr.Number, note); err != nil {
			return changed, err
		}
		c.Logger.Info("GitHub "+past+" not mirrored", "change", n, "pr", pr.Number, "by", login, "why", why)
		if action == "abandon" {
			// The plan reopens it; state it so it does even if the
			// close notice was posted before.
			if err := c.updateState(ctx, n, "PR close refused", func(st *state.Change) { st.State.ClosedNoticePosted = false }); err != nil {
				return changed, err
			}
		} else {
			// The plan closes it again, without repeating the notice.
			if err := c.updateState(ctx, n, "PR reopen refused", func(st *state.Change) { st.State.ClosedNoticePosted = true }); err != nil {
				return changed, err
			}
		}
	}
	return changed, nil
}

// mergedOnGitHub closes change n, whose PR pr merged on GitHub, which
// owns the branch (design §3.1), where Gerrit did not: Gerrit closes a
// change as merged only for a commit whose last paragraph has its
// Change-Id, and GitHub's merge commit may not (the trailer edited out in
// the merge dialog, or co-author lines GitHub adds after it). Once that
// commit is on Gerrit's copy of the branch (Follow), the bridge marks the
// change merged there (Gerrit's check-and-fix, which inserts the commit
// as its last patch set; it needs Maintain Server). If Gerrit will not,
// or the PR merged into another branch (a stacked PR into the one below,
// whose change then carries the code), the change is abandoned, with a
// note saying where it merged. It reports whether it closed the change.
func (c *Code) mergedOnGitHub(ctx context.Context, s *Snapshot, n int, ch *GerritChange, pr *github.PullRequest) (bool, error) {
	sha := pr.MergeCommitSHA
	if !fullSHA.MatchString(sha) {
		return false, nil
	}
	by := "someone"
	if pr.MergedBy != nil && pr.MergedBy.Login != "" {
		by = "@" + pr.MergedBy.Login
	}
	if !s.GitHubOwned && pr.Base.Ref == s.Branch {
		// Into the target branch, where Gerrit owns it: replication's
		// doing (only it writes there, perhaps with the bridge's GitHub
		// account), the submit racing this look: nothing to say
		// (fourteenth review; fifteenth: credited to the bridge's login,
		// it said "stays open").
		return false, nil
	}
	if pr.MergedBy != nil && c.BridgeLogin != "" && strings.EqualFold(pr.MergedBy.Login, c.BridgeLogin) {
		// GitHub's own doing after a push of the bridge's (a chain
		// reordered: a lower branch now holds an upper PR's head), not a
		// merge anyone made: nothing to close (thirteenth review). Said
		// once, on the PR and in Gerrit, and logged once (fourteenth
		// review: silent, with a warning every reconcile).
		if st := s.State[n]; st == nil || st.State.MergedNoticePosted || c.DryRun {
			return false, nil
		}
		// Said only while Gerrit still says the change is open: this
		// look's may be older than a submit (fifteenth review).
		if now, err := c.Gerrit.GetChange(ctx, n); err != nil {
			return false, err
		} else if now.Status != "NEW" {
			return false, nil
		}
		note := fmt.Sprintf("GitHub shows this PR merged into `%s`, by the bridge's own push (its branch came to hold this PR's commits, "+
			"after its Gerrit change was moved in a chain), not by anyone's merge: [change %d](%s) stays open in Gerrit, and this PR no "+
			"longer follows it.\n\n%s", forGitHub(pr.Base.Ref), n, ch.URL, noticeMarker)
		if _, err := c.GitHub.CreateIssueComment(ctx, pr.Number, note); err != nil {
			return false, err
		}
		c.notice(ctx, n, ch, forGerrit(fmt.Sprintf("GitHub shows PR #%d merged by the bridge's own push (after this change was moved in a chain), "+
			"not by anyone's merge: this change stays open here, and that PR no longer follows it.", pr.Number)))
		c.Logger.Warn("GitHub shows a PR merged by the bridge's own push; leaving its change", "change", n, "pr", pr.Number, "into", pr.Base.Ref)
		return false, c.updateState(ctx, n, "merged by the bridge's push notice", func(st *state.Change) { st.State.MergedNoticePosted = true })
	}
	if !s.GitHubOwned {
		// Gerrit's change is Gerrit's: a merge on GitHub (into a bridge
		// branch, say, which any writer may press) abandons nothing, as
		// nobody's say-so but the bridge's would (thirteenth review:
		// closing a PR abandons only as its closer, if Gerrit lets them).
		// (Into the target branch: nothing, above.) Said once on the PR,
		// once Gerrit still says the change is open; the plan never
		// edits a merged PR.
		if st := s.State[n]; st == nil || st.State.MergedNoticePosted || c.DryRun {
			return false, nil
		}
		if now, err := c.Gerrit.GetChange(ctx, n); err != nil {
			return false, err
		} else if now.Status != "NEW" {
			return false, nil
		}
		note := fmt.Sprintf("This PR was merged on GitHub into `%s`, but Gerrit owns this repository's branches: [change %d](%s) stays open "+
			"there, as it is, and this PR no longer follows it. Abandon it in Gerrit if it is not to be merged.\n\n%s", forGitHub(pr.Base.Ref), n, ch.URL, noticeMarker)
		if _, err := c.GitHub.CreateIssueComment(ctx, pr.Number, note); err != nil {
			return false, err
		}
		c.Logger.Warn("a PR merged on GitHub where Gerrit owns the branches; its change is left", "change", n, "pr", pr.Number, "into", pr.Base.Ref)
		return false, c.updateState(ctx, n, "merged on GitHub notice", func(st *state.Change) { st.State.MergedNoticePosted = true })
	}
	if pr.Base.Ref != s.Branch {
		return c.abandonMergedElsewhere(ctx, s, n, ch, pr, fmt.Sprintf("Merged on GitHub by %s in PR #%d into %s, not %s, so it will not merge here as this change: "+
			"abandoned. Whatever it merged into carries its code (a stacked PR's branch: the change below it).", by, pr.Number, pr.Base.Ref, s.Branch))
	}
	if _, err := c.Mirror.Git(ctx, nil, "merge-base", "--is-ancestor", sha, "refs/remotes/gerrit/heads/"+s.Branch); err != nil {
		// Not followed yet (or not there at all): the change waits.
		return false, nil
	}
	if c.DryRun {
		c.Logger.Info("dry run: would close a change merged on GitHub", "change", n, "pr", pr.Number, "commit", sha)
		return false, nil
	}
	var fixed gerrit.ChangeInfo
	err := c.Gerrit.Do(ctx, http.MethodPost, fmt.Sprintf("changes/%d/check", n), map[string]string{"expect_merged_as": sha}, &fixed)
	var ge *gerrit.Error
	switch {
	case err == nil && fixed.Status == "MERGED":
		c.notice(ctx, n, ch, forGerrit(fmt.Sprintf("Merged on GitHub by %s in PR #%d, as %s on %s.", by, pr.Number, sha, s.Branch)))
		c.Logger.Info("marked a change merged on GitHub as merged", "change", n, "pr", pr.Number, "commit", sha)
		return true, nil
	case err == nil, errors.As(err, &ge) && ge.Status < 500:
		c.Logger.Warn("Gerrit would not mark a change merged on GitHub as merged (grant the bridge Maintain Server); abandoning it", "change", n, "pr", pr.Number, "err", err)
	default:
		return false, fmt.Errorf("marking change %d merged on GitHub as merged: %w", n, err)
	}
	return c.abandonMerged(ctx, n, pr, fmt.Sprintf("Merged on GitHub by %s in PR #%d, as %s on %s, but Gerrit could not show it merged. Abandoned, since it is merged.",
		by, pr.Number, sha, s.Branch))
}

// abandonMergedElsewhere abandons change n, whose PR pr merged on GitHub
// into another branch, as whoever merged it (Run-As), so that Gerrit's
// Abandon permission decides, as for a close (twentieth review: anyone
// who may merge on GitHub abandoned anyone's change, as the bridge). As
// the bridge only where it owns the change for the merger, the PR's
// author. Otherwise it stays open, said once.
func (c *Code) abandonMergedElsewhere(ctx context.Context, s *Snapshot, n int, ch *GerritChange, pr *github.PullRequest, msg string) (bool, error) {
	if c.DryRun {
		c.Logger.Info("dry run: would abandon a change merged on GitHub elsewhere", "change", n, "pr", pr.Number)
		return false, nil
	}
	var merger github.User
	if pr.MergedBy != nil {
		merger = *pr.MergedBy
	}
	user, ok := "", false
	if c.Identity != nil && merger.Login != "" {
		var err error
		if user, ok, err = c.Identity.Lookup(ctx, merger); err != nil {
			return false, err
		}
	}
	if !ok && merger.Login != "" && sameGitHubUser(merger, pr.User) && c.BridgeUser != "" && strings.EqualFold(ch.Owner, c.BridgeUser) {
		return c.abandonMerged(ctx, n, pr, msg) // their own PR, which the bridge owns for them
	}
	if ok {
		err := c.Gerrit.As(user).Do(ctx, http.MethodPost, fmt.Sprintf("changes/%d/abandon", n), map[string]string{"message": forGerrit(msg)}, nil)
		var ge *gerrit.Error
		switch {
		case err == nil:
			c.Logger.Info("abandoned a change merged on GitHub elsewhere, as its merger", "change", n, "pr", pr.Number, "as", user)
			return true, nil
		case !errors.As(err, &ge) || ge.Status >= 500:
			return false, fmt.Errorf("abandoning change %d as %s: %w", n, user, err)
		}
		c.Logger.Info("Gerrit refused to abandon a change as its GitHub merger", "change", n, "pr", pr.Number, "as", user, "err", err)
	}
	if st := s.State[n]; st == nil || st.State.MergedNoticePosted {
		return false, nil
	}
	who := "@" + merger.Login
	if merger.Login == "" {
		who = "Whoever merged it"
	}
	note := fmt.Sprintf("This PR was merged on GitHub into `%s`, not `%s`. %s may not abandon [change %d](%s) in Gerrit, so it stays "+
		"open there, and this PR no longer follows it. Abandon it in Gerrit if it is not to be merged.\n\n%s",
		forGitHub(pr.Base.Ref), forGitHub(s.Branch), who, n, ch.URL, noticeMarker)
	if _, err := c.GitHub.CreateIssueComment(ctx, pr.Number, note); err != nil {
		return false, err
	}
	c.Logger.Warn("a PR merged on GitHub into another branch by someone who may not abandon its change; left open", "change", n, "pr", pr.Number, "merger", merger.Login)
	return false, c.updateState(ctx, n, "merged elsewhere notice", func(st *state.Change) { st.State.MergedNoticePosted = true })
}

// abandonMerged abandons change n, whose PR pr merged on GitHub, saying
// msg; it reports whether it did.
func (c *Code) abandonMerged(ctx context.Context, n int, pr *github.PullRequest, msg string) (bool, error) {
	if c.DryRun {
		c.Logger.Info("dry run: would abandon a change merged on GitHub", "change", n, "pr", pr.Number)
		return false, nil
	}
	err := c.Gerrit.Do(ctx, http.MethodPost, fmt.Sprintf("changes/%d/abandon", n), map[string]string{"message": forGerrit(msg)}, nil)
	var ge *gerrit.Error
	if errors.As(err, &ge) && ge.Status < 500 {
		c.Logger.Warn("Gerrit refused to abandon a change merged on GitHub (grant the bridge Abandon)", "change", n, "pr", pr.Number, "err", err)
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("abandoning change %d, merged on GitHub: %w", n, err)
	}
	c.Logger.Info("abandoned a change merged on GitHub", "change", n, "pr", pr.Number)
	return true, nil
}

// gerritText is the PR text a commit message stands for, and githubText
// a PR's own, each as one comparable string.
func gerritText(message string) string {
	title, body := prTextFromMessage(message)
	// Cleaned as the PR's own is (tenth audit: a commit message with an
	// upload's URL never matched its PR's text).
	return title + "\x00" + noAttachments(body, "")
}

// keepsAttachments reports whether description, a PR's own (without the
// links block), is commit message's description with the files uploaded
// to GitHub left in: GitHub keeps showing it as it is, rather than the
// notes the commit message has in their place.
func keepsAttachments(description, message string) bool {
	_, body := prTextFromMessage(message)
	return attachmentURL.MatchString(description) && prBodyForMessage(description) == noAttachments(body, "")
}

func githubText(pr *github.PullRequest) string {
	return strings.TrimSpace(pr.Title) + "\x00" + prBodyForMessage(pr.Body)
}

// githubTextFor is githubText, plus the sign-offs PR pr's description adds
// to commit message: the PR text leaves sign-offs out, as Gerrit's
// business, but one written in it is news for Gerrit.
func githubTextFor(pr *github.PullRequest, message string) string {
	t := githubText(pr)
	if add := signOffsToAdd(pr, message); len(add) > 0 {
		t += "\x00" + strings.Join(add, "\n")
	}
	return t
}

// signOffsToAdd are the sign-offs PR pr's description has that commit
// message lacks.
func signOffsToAdd(pr *github.PullRequest, message string) []string {
	user, _ := splitBody(pr.Body)
	have := signOffs(message)
	var add []string
	for _, so := range signOffs(user) {
		if !slices.Contains(have, so) {
			add = append(add, so)
		}
	}
	return add
}

func wipState(wip bool) string { return map[bool]string{true: "wip", false: "ready"}[wip] }

// editedOnGitHub reports whether PR pr's text, or its draft state,
// differs from change ch's because of an edit on GitHub since they were
// last in sync (mirrorPREdits).
func editedOnGitHub(ch *GerritChange, st *state.Change, pr *github.PullRequest) (text, draft bool) {
	gt, ht := hashString(gerritText(ch.Message)), hashString(githubTextFor(pr, ch.Message))
	gw, hw := wipState(ch.WIP), wipState(pr.Draft)
	return gt != ht && st.State.SyncedText != "" && ht != st.State.SyncedText,
		gw != hw && st.State.SyncedWIP != "" && hw != st.State.SyncedWIP
}

// holdPending holds the changes whose PRs have a close, reopen, edit or
// draft toggle that mirrorPRStates or mirrorPREdits might carry to Gerrit.
func (s *Snapshot) holdPending() {
	for n, st := range s.State {
		ch := s.Changes[n]
		if ch == nil || st == nil || st.State.PR == 0 || s.PRs[st.State.PR] == nil {
			continue
		}
		pr := s.PRs[st.State.PR]
		text, draft := editedOnGitHub(ch, st, pr)
		closed := ch.Status == "NEW" && pr.State == "closed" && !pr.Merged
		reopened := ch.Status == "ABANDONED" && pr.State == "open"
		if closed || reopened || (ch.Status == "NEW" && pr.State == "open" && (text || draft)) {
			s.Hold[n] = true
		}
	}
}

// mirrorPREdits carries PR edits made on GitHub over to Gerrit (design
// §6.0): a new title or description becomes the change's commit message,
// and a draft toggle its work-in-progress state, whichever side changed
// last. They are made as whoever made them on GitHub (Run-As; see
// asEditor for when the bridge will not); if Gerrit or the bridge refuses,
// a notice says why and the plan puts Gerrit's version back. If both sides
// changed, Gerrit's wins. It reports whether Gerrit changed.
func (c *Code) mirrorPREdits(ctx context.Context, s *Snapshot, handled map[int]bool) (bool, error) {
	changed := false
	for _, n := range sortedKeys(s.Changes) {
		ch, st := s.Changes[n], s.State[n]
		if ch.Status != "NEW" || ch.Private || st == nil || st.State.PR == 0 || s.PRs[st.State.PR] == nil || handled[st.State.PR] {
			continue
		}
		pr := s.PRs[st.State.PR]
		if pr.State != "open" {
			continue
		}
		gt, ht := hashString(gerritText(ch.Message)), hashString(githubTextFor(pr, ch.Message))
		gw, hw := wipState(ch.WIP), wipState(pr.Draft)
		textEdited, draftToggled := editedOnGitHub(ch, st, pr)
		if !textEdited && !draftToggled {
			continue
		}
		act, err := c.GitHub.Activity(ctx, pr.Number)
		if err != nil {
			return changed, err
		}
		// Who edited is asked after the edit was seen: if the PR moved on
		// meanwhile, the editor named may have made a later edit, not this
		// one. Leave it to the next reconcile, which sees both together.
		if now, err := c.GitHub.GetPull(ctx, pr.Number); err != nil {
			return changed, err
		} else if now.Title != pr.Title || now.Body != pr.Body || now.Draft != pr.Draft {
			c.Logger.Info("PR edited again while being mirrored; next round", "change", n, "pr", pr.Number)
			changed, handled[pr.Number] = true, true // re-observe
			continue
		}
		var notes []string
		if textEdited {
			switch {
			case strings.Contains(pr.Body, strings.TrimSpace(tooLongForGitHub)):
				// Mirrored, it would cut the commit message short; and
				// Gerrit has not changed, whatever the hashes say (fourth
				// audit).
				notes = append(notes, fmt.Sprintf("This PR's description is shortened here (the commit message is longer than GitHub takes), so it cannot be edited on GitHub: edit [change %d](%s)'s commit message in Gerrit.", n, ch.URL))
			case gt != st.State.SyncedText:
				notes = append(notes, fmt.Sprintf("This PR's title or description was edited on GitHub while [change %d](%s)'s commit message changed in Gerrit; Gerrit's is kept.", n, ch.URL))
			default:
				title, body := strings.TrimSpace(pr.Title), prBodyForMessage(pr.Body)
				add := signOffsToAdd(pr, ch.Message)
				msg := commitMessage(title, body, ch.Message, add...)
				// Each part edited is its editor's (fourth audit: whoever
				// renamed a PR was taken for whoever edited its body).
				gTitle, gBody := prTextFromMessage(ch.Message)
				var editors []github.User
				if title != gTitle {
					editors = append(editors, act.TitleEditor)
				}
				if body != gBody || len(add) > 0 {
					editors = append(editors, act.BodyEditor)
				}
				var editor github.User
				if len(editors) > 0 && (len(editors) == 1 || sameGitHubUser(editors[0], editors[1])) {
					editor = editors[0]
				}
				if note, err := c.asEditor(ctx, ch, pr, editor, true, http.MethodPut, "message", map[string]string{"message": msg},
					"edited this PR's title or description", "change the commit message of",
					"Only the change's owner and users with the Add Patch Set permission can edit its commit message."); err != nil {
					return changed, err
				} else if note != "" {
					notes = append(notes, note)
				} else {
					// Both sides have it now: a further edit before the
					// next record is a new edit, not Gerrit's to undo.
					if err := c.updateState(ctx, n, "PR text mirrored", func(st *state.Change) { st.State.SyncedText = ht }); err != nil {
						return changed, err
					}
					changed, handled[pr.Number] = true, true
				}
			}
		}
		if draftToggled {
			if gw != st.State.SyncedWIP {
				notes = append(notes, fmt.Sprintf("This PR's draft state changed on GitHub while [change %d](%s)'s work-in-progress state changed in Gerrit; Gerrit's is kept.", n, ch.URL))
			} else {
				past := map[bool]string{true: "marked this PR as a draft", false: "marked this PR ready for review"}[pr.Draft]
				if note, err := c.asEditor(ctx, ch, pr, act.DraftActor, false, http.MethodPost, hw, map[string]string{"message": fmt.Sprintf("PR #%d %s on GitHub.", pr.Number, map[bool]string{true: "marked draft", false: "marked ready for review"}[pr.Draft])},
					past, "change the work-in-progress state of",
					"Only the change's owner, the uploader of its latest patch set and users with the Toggle Work In Progress State permission can change it."); err != nil {
					return changed, err
				} else if note != "" {
					notes = append(notes, note)
				} else {
					// As for text: toggling back before the next record
					// is a new toggle.
					if err := c.updateState(ctx, n, "PR draft state mirrored", func(st *state.Change) { st.State.SyncedWIP = hw }); err != nil {
						return changed, err
					}
					changed, handled[pr.Number] = true, true
				}
			}
		}
		for _, note := range notes {
			if _, err := c.GitHub.CreateIssueComment(ctx, pr.Number, note+"\n\n"+noticeMarker); err != nil {
				return changed, err
			}
			c.Logger.Info("GitHub PR edit not mirrored", "change", n, "pr", pr.Number, "why", note)
		}
	}
	return changed, nil
}

// asEditor calls changes/n/<endpoint> as GitHub user login's Gerrit
// account. It returns a notice instead ("@login <did>, but the bridge
// can't <would> change N in Gerrit to match. ...") when Gerrit refuses
// (saying, by may, who Gerrit lets do it), or
// when the bridge will not act for login:
//   - Someone without a Gerrit account acts only on their own PR's
//     bridge-owned change, and then as the bridge (as their pushes are):
//     the bridge's account must not lend anyone rights in Gerrit.
//   - An edit that makes a new patch set (newPatchSet, a commit message
//     edit) is made only by the current patch set's uploader, the change's
//     owner or a member of CI's trusted group. Its code is judged by who
//     wrote it, past message-only patch sets (codeFrom, and CI's
//     codeTrusted), so a trusted editor does not vouch for it; but anyone
//     else's patch set would not be pushed to the author's branch, nor
//     built.
func (c *Code) asEditor(ctx context.Context, ch *GerritChange, pr *github.PullRequest, gh github.User, newPatchSet bool, method, endpoint string, in any, did, would, may string) (string, error) {
	n, login := ch.Number, gh.Login
	who := "@" + login
	if login == "" {
		who = "Someone"
	}
	refuse := func(why string) string {
		return fmt.Sprintf("%s %s, but the bridge can't %s [change %d](%s) in Gerrit to match. %s The PR is set back to match Gerrit.", who, did, would, n, c.changeURL(n), why)
	}
	user, ok := "", false
	if c.Identity != nil && login != "" {
		var err error
		if user, ok, err = c.Identity.Lookup(ctx, gh); err != nil {
			return "", err
		}
	}
	g, as := c.Gerrit, "the bridge"
	switch {
	case ok && newPatchSet && !strings.EqualFold(user, ch.Uploader) && !strings.EqualFold(user, ch.Owner):
		if t, err := c.trustedUser(ctx, user); err != nil {
			return "", err
		} else if !t {
			return refuse("Only the change's owner, the uploader of its latest patch set and members of CI's trusted group can make a new patch set from GitHub. Edit the commit message in Gerrit instead."), nil
		}
		g, as = c.Gerrit.As(user), user
	case ok:
		g, as = c.Gerrit.As(user), user
	case login != "" && sameGitHubUser(gh, pr.User) && c.BridgeUser != "" && strings.EqualFold(ch.Owner, c.BridgeUser) &&
		(!newPatchSet || strings.EqualFold(ch.Uploader, c.BridgeUser)):
		// Their own PR, which the bridge owns for them.
	case login == "":
		return refuse("GitHub doesn't say who did it, so there is no Gerrit account to do it as."), nil
	default:
		return refuse(c.noAccount(who)), nil
	}
	err := g.Do(ctx, method, fmt.Sprintf("changes/%d/%s", n, endpoint), in, nil)
	var ge *gerrit.Error
	switch {
	case err == nil:
		c.Logger.Info("mirrored GitHub PR edit to Gerrit", "change", n, "endpoint", endpoint, "as", as)
		return "", nil
	case errors.As(err, &ge) && ge.Status < 500:
		return refuse(fmt.Sprintf("Gerrit refused it as %s (%s). %s", as, forGitHub(strings.TrimSpace(ge.Body)), may)), nil
	default:
		return "", fmt.Errorf("%s %s change %d as %s: %w", method, endpoint, n, as, err)
	}
}

// noAccount says that who has no Gerrit account the bridge can act as,
// and how to get one.
func (c *Code) noAccount(who string) string {
	return fmt.Sprintf("%s has no Gerrit account for the bridge to act as. To get one, sign in to [Gerrit](%s) with GitHub; "+
		"if you already have an account there under another username, ask a Gerrit admin to link it to your GitHub login.", who, c.Gerrit.BaseURL)
}

// trustedUser reports whether Gerrit user is in CI's trusted group. Not
// knowing is an error: the next reconcile asks again.
func (c *Code) trustedUser(ctx context.Context, user string) (bool, error) {
	if c.Trusted == nil {
		return false, nil
	}
	var acct gerrit.AccountInfo
	if err := c.Gerrit.Do(ctx, http.MethodGet, "accounts/"+url.PathEscape(user), nil, &acct); err != nil {
		return false, fmt.Errorf("Gerrit account %s: %w", user, err)
	}
	t, known := c.Trusted(ctx, acct.AccountID)
	if !known {
		return false, fmt.Errorf("cannot tell whether %s is in CI's trusted group", user)
	}
	return t, nil
}

// commitMessage is the commit message for a PR's title and description:
// those, plus the bridge's trailers (Change-Id, sign-offs, GitHub-PR)
// from the current message, kept in the last paragraph if the description
// already ends in trailers, and the sign-offs signed added after its own.
func commitMessage(title, body, current string, signed ...string) string {
	msg := title
	if body != "" {
		msg += "\n\n" + body
	}
	trailers := bridgeTrailers.FindAllString(strings.ReplaceAll(current, "\r\n", "\n"), -1)
	at := 0 // after the last sign-off, or first
	for i, t := range trailers {
		if signedOffBy.MatchString(t) {
			at = i + 1
		}
	}
	trailers = slices.Insert(trailers, at, signed...)
	if len(trailers) == 0 {
		return msg + "\n"
	}
	sep := "\n\n"
	if paras := strings.Split(body, "\n\n"); body != "" && isTrailers(paras[len(paras)-1]) {
		sep = "\n"
	}
	return msg + sep + strings.Join(trailers, "\n") + "\n"
}

var trailerLine = regexp.MustCompile(`^[A-Za-z0-9-]+: \S`)

// isTrailers reports whether every line of paragraph p is a "Key: value"
// trailer.
func isTrailers(p string) bool {
	for _, l := range strings.Split(strings.TrimSpace(p), "\n") {
		if !trailerLine.MatchString(l) {
			return false
		}
	}
	return strings.TrimSpace(p) != ""
}

// lastStatusChange is when change n was last abandoned or restored in
// Gerrit (zero if never): by Gerrit's own message, which has its tag and
// says so. Anyone may put the tag on a review, which says "Patch Set N:"
// first (eighth audit: one kept an owner's close on GitHub from
// abandoning their change, and the PR was reopened).
func (c *Code) lastStatusChange(ctx context.Context, n int) (time.Time, error) {
	ci, err := c.Gerrit.GetChange(ctx, n, "MESSAGES")
	if err != nil {
		return time.Time{}, err
	}
	var last time.Time
	for _, m := range ci.Messages {
		if !(m.Tag == "autogenerated:gerrit:abandon" && strings.HasPrefix(m.Message, "Abandoned")) &&
			!(m.Tag == "autogenerated:gerrit:restore" && strings.HasPrefix(m.Message, "Restored")) {
			continue
		}
		// Gerrit's timestamps are UTC: "2006-01-02 15:04:05.000000000".
		if t, err := time.Parse("2006-01-02 15:04:05.999999999", m.Date); err == nil && t.After(last) {
			last = t
		}
	}
	return last, nil
}

func (c *Code) githubEnv(ctx context.Context) ([]string, error) {
	tok, err := c.GitHub.Tokens.Token(ctx)
	if err != nil {
		return nil, err
	}
	return gitmirror.CredentialEnv("https://github.com", "x-access-token", tok), nil
}

// apply runs a plan's actions in order. An action on one change's PR that
// GitHub refuses as such (refusedByGitHub) is logged, and that change is
// added to skip and left out for the rest of the reconcile: anyone can
// make their own change's PR unacceptable to GitHub, and that must not
// stop everyone else's. So is a stack action GitHub refuses: stacks only
// arrange PRs. Any other error stops it; the next reconcile re-plans from
// whatever state that left.
func (c *Code) apply(ctx context.Context, s *Snapshot, p *Plan, skip *skips) error {
	for _, a := range p.Actions {
		if a.Change != 0 && skip.changes[a.Change] {
			continue
		}
		if err := c.applyOne(ctx, s, a); err != nil {
			var fr *forkRefused
			var or *ownerRefused
			switch {
			case errors.As(err, &or) && a.Change != 0:
				c.Logger.Warn("cannot open a change's PR as its owner; leaving that change out", "change", a.Change, "err", err)
				skip.changes[a.Change] = true
				continue
			case errors.As(err, &fr):
				for _, n := range fr.changes {
					skip.changes[n] = true
				}
				continue
			case errors.Is(err, errTooMany) && a.Change != 0:
				// Only the update waits: the change is still recorded,
				// so its statuses, votes and /submit do not (fifth
				// audit).
				c.Logger.Info("a PR's text update waits", "change", a.Change, "action", a.String())
				skip.texts[a.PR] = true
				continue
			case a.Change != 0 && refusedByGitHub(err):
				c.Logger.Warn("GitHub refused an action on one change's PR; leaving that change out", "change", a.Change, "action", a.String(), "err", err)
				skip.changes[a.Change] = true
				continue
			case isStackAction(a.Kind) && refusedByGitHub(err):
				c.Logger.Warn("GitHub refused a stack action; leaving it out", "action", a.String(), "err", err)
				skip.stacks[a.String()] = true
				continue
			}
			return fmt.Errorf("%s: %w", a, err)
		}
	}
	return nil
}

// errTooMany is an action that waits: whoever caused it caused too many
// lately (a Budget).
var errTooMany = errors.New("over budget; waits")

func userPart(body string) string { user, _ := splitBody(body); return user }

// forkRefused is a push the repository took, but forks did not, for
// changes.
type forkRefused struct{ changes []int }

func (e *forkRefused) Error() string {
	return fmt.Sprintf("forks refused the push for changes %v", e.changes)
}

// githubRefused is a push GitHub refused some changes of, for what they
// are: the rest went.
type githubRefused struct{ changes []int }

func (e *githubRefused) Error() string {
	return fmt.Sprintf("GitHub refused the push of changes %v", e.changes)
}

// adoptable reports whether pr, open from change ch's branch but not
// linked to it, may be taken for its PR where GitHub owns the branches:
// opened by the bot (before PRs were opened as owners) or by the owner's
// linked account (its link not saved). Anyone else's would make GitHub
// take them, not the owner, for its author (twenty-first review).
func (c *Code) adoptable(ctx context.Context, ch *GerritChange, pr *github.PullRequest) bool {
	if c.BridgeLogin != "" && strings.EqualFold(pr.User.Login, c.BridgeLogin) {
		return true
	}
	if ch == nil || c.LinkedAs == nil {
		return false
	}
	u, ok, err := c.LinkedAs(ctx, ch.OwnerID)
	if err != nil || !ok {
		return false
	}
	if !sameGitHubUser(u, pr.User) {
		c.Logger.Warn("not taking someone else's PR from a change's branch for its PR", "change", ch.Number, "pr", pr.Number, "author", pr.User.Login)
		return false
	}
	return true
}

// ownerRefused is a PR that could not be opened as its change's owner
// (Code.OpenAs): only that change waits.
type ownerRefused struct{ err error }

func (e *ownerRefused) Error() string { return "opening a PR as its owner: " + e.err.Error() }
func (e *ownerRefused) Unwrap() error { return e.err }

// byGitHub marks a change GitHub refused in the export's refused set.
const byGitHub = "github"

// whoMayPush says who mayReach lets push Gerrit code to GitHub, for the
// notices of withheld and foreign patch sets (twelfth review: the foreign
// one named CI's trusted group where GitHub owns the branches), ending
// with where to link, if linking is the way.
func (c *Code) whoMayPush(prBranch bool, below string) string {
	msg := ""
	if !c.GitHubOwned {
		msg = "whoever uploaded it, wrote its code and chose its parents is the change's owner or in CI's trusted group, " +
			"and so is whoever did for the code below it in Gerrit."
	} else {
		msg = "whoever uploaded it, wrote its code and chose its parents, and whoever did for the code below it in Gerrit, " +
			"has linked a GitHub account that may push to the repository"
		if prBranch {
			msg += " (owning the change counts only on the PR author's own fork)"
		}
		msg += "."
	}
	if below != "" {
		msg += " Here, not: " + below + "."
	}
	if c.GitHubOwned && c.LinkURL != "" {
		msg += " Link yours at " + c.LinkURL + ", then upload again."
	}
	return msg
}

