const notLinked = "not linked"

// refusedByGitHub reports whether GitHub refused a request for what it
// asked (a 4xx), not for who asked or how often (401, 403, 429).
func refusedByGitHub(err error) bool {
	var ae *github.APIError
	return errors.As(err, &ae) && ae.Status >= 400 && ae.Status < 500 &&
		ae.Status != http.StatusUnauthorized && ae.Status != http.StatusForbidden && ae.Status != http.StatusTooManyRequests
}

func (c *Code) applyOne(ctx context.Context, s *Snapshot, a Action) error {
	gh := c.GitHub
	switch a.Kind {
	case PushBranches, DeleteBranches:
		// One atomic push to the repository, plus one per fork whose PR
		// branch gets a Gerrit edit (allowed by maintainer_can_modify).
		// Gerrit owns these; only replication writes them.
		var protected []int // changes whose PR branch GitHub protects
		for _, name := range append(sortedStringKeys(a.Refs), sortedStringKeys(a.Appends)...) {
			if name == s.Branch || name == c.DefaultBranch {
				return fmt.Errorf("refusing to push to %s, which Gerrit owns", name)
			}
			if _, _, fork := github.SplitHeadKey(name); !fork {
				// Any branch Gerrit has is replication's, not the bridge's.
				if owned, err := c.Gerrit.BranchExists(ctx, c.Project, name); err != nil {
					return err
				} else if owned {
					return fmt.Errorf("refusing to push to %s, which Gerrit owns", name)
				}
				if c.GitHubOwned && !bridgeBranch(name) {
					// Nor one GitHub protects (the importer's rule; a
					// branch protected since): that change is withheld,
					// as if GitHub refused it, and the rest pushed
					// (seventeenth review: the whole push failed, every
					// change's, on every reconcile).
					if p, err := c.GitHub.BranchProtected(ctx, name); err != nil {
						return err
					} else if p {
						n := 0
						for m, ch := range s.Changes {
							if s.head(m, ch.ChangeID) == name {
								n = m
							}
						}
						if n == 0 {
							return fmt.Errorf("refusing to push to %s, which GitHub protects", name)
						}
						c.Logger.Warn("not pushing to a branch GitHub protects; the change is withheld", "branch", name, "change", n)
						protected = append(protected, n)
					}
				}
			}
		}
		if len(protected) > 0 {
			return &githubRefused{changes: protected}
		}
		urls := []string{c.GitHubURL}
		specs := map[string][]string{}
		// Each change's refs, to push them alone if the push of all is
		// refused.
		changeOf := map[string]int{}
		for n, ch := range s.Changes {
			changeOf[s.head(n, ch.ChangeID)] = n
			changeOf[FrozenBranch(s.Branch, s.DefaultBranch, ch.ChangeID)] = n
		}
		bySpec := map[int][]string{} // GitHubURL's specs, by change (0: none's)
		guard := func(name, commit string) error { return c.pushGuard(ctx, s.Branch, name, commit) }
		for _, name := range sortedStringKeys(a.Refs) {
			if err := guard(name, a.Refs[name]); err != nil {
				return err
			}
			ref := "refs/heads/" + name
			spec := []string{"--force-with-lease=" + ref + ":" + a.Leases[name], a.Refs[name] + ":" + ref}
			specs[c.GitHubURL] = append(specs[c.GitHubURL], spec...)
			bySpec[changeOf[name]] = append(bySpec[changeOf[name]], spec...)
		}
		appended := map[string]string{}
		urlOf := map[string]string{} // appended -> where to
		for _, name := range sortedStringKeys(a.Appends) {
			commit := a.Appends[name].Revision
			if !a.Appends[name].Force {
				var err error
				if commit, err = c.appendCommit(ctx, a.Appends[name]); err != nil {
					return err
				}
			}
			if err := guard(name, commit); err != nil {
				return err
			}
			appended[name] = commit
			url, branch := c.GitHubURL, name
			if fork, b, ok := github.SplitHeadKey(name); ok {
				url, branch = "https://github.com/"+fork+".git", b
				if !slices.Contains(urls, url) {
					urls = append(urls, url)
				}
			}
			ref := "refs/heads/" + branch
			spec := []string{"--force-with-lease=" + ref + ":" + a.Leases[name], commit + ":" + ref}
			specs[url] = append(specs[url], spec...)
			urlOf[name] = url
			if url == c.GitHubURL {
				bySpec[a.Appends[name].Change] = append(bySpec[a.Appends[name].Change], spec...)
			}
		}
		env, err := c.githubEnv(ctx)
		if err != nil {
			return err
		}
		failed := map[string]bool{}      // forks that refused
		pushed := map[string]time.Time{} // when each push was done
		var left, rejected []int         // left out: by forks; by GitHub, from the repository
		for _, url := range urls {
			if len(specs[url]) == 0 {
				continue
			}
			args := append([]string{"push", "--porcelain", "--atomic", url}, specs[url]...)
			out, err := c.Mirror.GitEnv(ctx, env, nil, args...)
			pushed[url] = time.Now()
			if err == nil {
				trace.Wrote(ctx, fmt.Sprintf("git push %s (%d refs)", url, len(specs[url])))
			}
			if err != nil {
				if url == c.GitHubURL {
					// One change GitHub refuses (its push protection on a
					// token-shaped string in it, say) must not stop the
					// rest: each change's alone, and those refused wait
					// (eighth audit).
					for _, n := range sortedKeys(bySpec) {
						one := append([]string{"push", "--porcelain", "--atomic", url}, bySpec[n]...)
						out1, err1 := c.Mirror.GitEnv(ctx, env, nil, one...)
						switch {
						case err1 == nil:
							trace.Wrote(ctx, fmt.Sprintf("git push %s (change %d)", url, n))
						case n == 0 || !strings.Contains(string(out1), "[remote rejected]"):
							// No one change's, or not refused for what it is
							// (a branch moved under the lease, the network):
							// tried again.
							return fmt.Errorf("%w\n%s", err, out)
						default:
							c.Logger.Warn("GitHub refused a change's push; withholding it", "change", n, "err", err1, "out", string(out1))
							rejected = append(rejected, n)
						}
					}
					pushed[url] = time.Now()
					continue
				}
				// A fork's owner can move its branch under the lease
				// whenever they like (fourth audit): only the changes
				// appended there wait.
				c.Logger.Warn("a fork refused the push; leaving its changes out", "url", url, "err", err, "out", string(out))
				failed[url] = true
			}
		}
		for _, name := range sortedStringKeys(appended) {
			commit, ap := appended[name], a.Appends[name]
			if failed[urlOf[name]] || (urlOf[name] == c.GitHubURL && slices.Contains(rejected, ap.Change)) {
				if failed[urlOf[name]] {
					left = append(left, ap.Change)
				}
				continue
			}
			tree, parentTree := c.trees(ctx, ap.Revision)
			err := c.updateState(ctx, ap.Change, fmt.Sprintf("Export patch set %d to %s", ap.PatchSet, name), func(st *state.Change) {
				st.Revisions = append(st.Revisions, state.Revision{PatchSet: ap.PatchSet, GerritSHA: ap.Revision,
					GitHubSHA: commit, Tree: tree, ParentTree: parentTree, At: time.Now(), Vetted: st.State.Origin == "github" || c.GitHubOwned,
					Exported: true})
				if st.State.PR != 0 {
					// The PR's head from the push on: a review a minute
					// on is about it, however long before a sync reads the
					// PR (in the rehearsal, a review of a rebase was not
					// counted).
					st.Heads = withHead(st.Heads, commit, pushed[urlOf[name]])
				}
			})
			if err != nil {
				return err
			}
			if err := c.exported(ctx, ap.Change); err != nil {
				return err
			}
		}
		if len(rejected) > 0 {
			return &githubRefused{changes: rejected}
		}
		if len(left) > 0 {
			return &forkRefused{changes: left}
		}
		return nil
	case CreatePR:
		var opener PullOpener = gh
		if c.GitHubOwned {
			// As its owner (OpenAs), never the bot: withhold kept it
			// back until they could; if they cannot now, it waits.
			ch := s.Changes[a.Change]
			if ch == nil || c.OpenAs == nil {
				return fmt.Errorf("no owner to open change %d's PR as", a.Change)
			}
			as, ok, err := c.OpenAs(ctx, ch.OwnerID)
			if err != nil {
				return &ownerRefused{err}
			}
			if !ok {
				return &ownerRefused{fmt.Errorf("change %d's owner has no linked GitHub account to open its PR with", a.Change)}
			}
			opener = as
		}
		pr, err := opener.CreatePull(ctx, *a.New)
		if err != nil && c.GitHubOwned {
			// Their token's answer is theirs: one owner's refused,
			// lapsed or rate-limited token stops only their change
			// (twenty-first review: it stopped the branch's every PR).
			return &ownerRefused{err}
		}
		if err != nil {
			return err
		}
		at := time.Now()
		if ch := s.Changes[a.Change]; ch != nil {
			c.PRBudget.Take(ctx, ch.OwnerID)
		}
		c.Logger.Info("created PR", "change", a.Change, "pr", pr.Number, "url", pr.HTMLURL)
		// Its head from the start, in the same save: a review a minute on
		// is about it, however busy the bridge is before it next reads
		// the PR. And in sync with the change from the start: made from
		// it, its text and draft state are the change's, so an edit on
		// GitHub before this run ends is an edit, not drift for Gerrit's
		// text to undo (in the rehearsal, a retitle while the run went on
		// was put back).
		return c.linkNew(ctx, s, a.Change, pr, at)
	case UpdatePR:
		if u := a.Update; u.State == nil && u.Base == nil {
			// Text only: wait if whoever changed it changed too many.
			ch, pr := s.Changes[a.Change], s.PRs[a.PR]
			linksOnly := u.Title == nil && u.Body != nil && pr != nil && userPart(*u.Body) == userPart(pr.Body)
			trustedOwner := false
			if ch != nil && c.Trusted != nil {
				t, known := c.Trusted(ctx, ch.OwnerID)
				trustedOwner = t && known
			}
			switch {
			case ch == nil:
			case linksOnly && !trustedOwner && !c.LinksBudget.Take(ctx, a.PR):
				return errTooMany
			case !linksOnly && ch.UploaderID != c.BridgeAccount && !c.TextBudget.Take(ctx, ch.UploaderID):
				// (The bridge's uploads are GitHub's pushes, each PR's
				// its own: not one budget for everyone without a Gerrit
				// account; fifth audit.)
				return errTooMany
			}
		}
		_, err := gh.UpdatePull(ctx, a.PR, *a.Update)
		return err
	case SetDraft:
		return gh.SetDraft(ctx, a.NodeID, a.Draft)
	case Unstack:
		return gh.Unstack(ctx, a.Stack)
	case CreateStack:
		st, err := gh.CreateStack(ctx, a.PRs)
		if err == nil {
			c.Logger.Info("created stack", "stack", st.Number, "prs", a.PRs)
		}
		return err
	case AddToStack:
		_, err := gh.AddToStack(ctx, a.Stack, a.PRs)
		return err
	case ClosePR:
		if s.Changes[a.Change].Status == "MERGED" {
			// GitHub may have just marked it merged (replication landed
			// its head on the target branch while this plan was made):
			// then there is nothing to close or explain.
			cur, err := gh.GetPull(ctx, a.PR)
			if err != nil {
				return err
			}
			if cur.Merged || cur.State != "open" {
				return c.updateState(ctx, a.Change, "PR merged on GitHub", func(st *state.Change) {
					st.State.ClosedNoticePosted = true
					st.State.Lifecycle = s.Changes[a.Change].Status
				})
			}
		}
		if a.Comment != "" {
			if _, err := gh.CreateIssueComment(ctx, a.PR, a.Comment+"\n\n"+noticeMarker); err != nil {
				return err
			}
		}
		if _, err := gh.UpdatePull(ctx, a.PR, github.PullUpdate{State: ptr("closed")}); err != nil {
			return err
		}
		return c.updateState(ctx, a.Change, "Close PR", func(st *state.Change) {
			st.State.ClosedNoticePosted = true
			st.State.Lifecycle = s.Changes[a.Change].Status
		})
	}
	return fmt.Errorf("unknown action %v", a.Kind)
}

// link records a new change <-> PR link and announces it on the change.
func (c *Code) link(ctx context.Context, s *Snapshot, n int, pr *github.PullRequest) error {
	origin := "gerrit"
	if s.githubBorn(n) {
		origin = "github"
	}
	return c.linkPR(ctx, n, origin, s.Branch, s.Changes[n].ChangeID, pr)
}

// linkNew is link for a PR the bridge just made from change n: it notes
// the PR's head as seen at at, and its text and draft state as in sync
// with the change's.
func (c *Code) linkNew(ctx context.Context, s *Snapshot, n int, pr *github.PullRequest, at time.Time) error {
	origin := "gerrit"
	if s.githubBorn(n) {
		origin = "github"
	}
	return c.linkPRAt(ctx, n, origin, s.Branch, s.Changes[n].ChangeID, pr, at)
}

func (c *Code) linkPR(ctx context.Context, n int, origin, branch, changeID string, pr *github.PullRequest) error {
	return c.linkPRAt(ctx, n, origin, branch, changeID, pr, time.Time{})
}

// linkPRAt links change n to pr, in one save. With at, pr is new: its
// head is noted as seen then, and its text and draft state as in sync.
func (c *Code) linkPRAt(ctx context.Context, n int, origin, branch, changeID string, pr *github.PullRequest, at time.Time) error {
	err := c.updateState(ctx, n, fmt.Sprintf("Link PR #%d", pr.Number), func(st *state.Change) {
		if !at.IsZero() {
			st.Heads = withHead(st.Heads, pr.Head.SHA, at)
			st.State.SyncedText = hashString(githubText(pr))
			st.State.SyncedWIP = wipState(pr.Draft)
		}
		st.State.Change = n
		st.State.ChangeID = changeID
		st.State.Branch = branch
		if st.State.Origin == "" {
			st.State.Origin = origin
		}
		st.State.PR = pr.Number
		st.State.PRNodeID = pr.NodeID
		st.State.HeadBranch = pr.HeadKey(c.GitHub.Owner + "/" + c.GitHub.Repo)
		st.State.Lifecycle = "NEW"
	})
	if err != nil {
		return err
	}
	return c.Gerrit.SetReview(ctx, n, "current", gerrit.ReviewInput{
		Message: fmt.Sprintf("GitHub: %s", pr.HTMLURL),
		Tag:     LinkTag,
		Notify:  "NONE",
	})
}

// appendCommit makes a commit with a patch set's tree on top of a GitHub
// head (design §5.2: a fast-forward, so `git pull` works), merging in the
// new base of a rebased patch set.
// pushGuard refuses to push commit to the repository's branch name if
// its files under withheldPaths are not the branch's (GitHub would use
// them; withhold), whatever a plan says. Only the files: what GitHub
// uses is a branch's tip, and the history a push brings is Gerrit's,
// which withhold checks, or GitHub's own (fourth audit: the bridge's
// merge of a branch that changed .github/ since, or a PR's commits that
// changed it and changed it back, would stop every push).
func (c *Code) pushGuard(ctx context.Context, branch, name, commit string) error {
	if _, _, fork := github.SplitHeadKey(name); fork || commit == "" {
		return nil // runs in the fork, with its own secrets; or a deletion
	}
	if w, err := c.changesConfig(ctx, branch, commit, false); err != nil || w {
		return cmp.Or(err, fmt.Errorf("refusing to push %s to %s: it changes %s", short(commit), name, withheldWhat))
	}
	return nil
}

// refusedPushes is the changes whose pushes in p pushGuard refuses,
// though withhold let them through: it checks a change's Gerrit commits,
// and a push can be of GitHub's (a frozen base at a parent's GitHub
// commit, say). Withheld instead, they do not stop the branch's other
// pushes (fourth audit). A refused push that is no one change's still
// fails in applyOne.
func (c *Code) refusedPushes(ctx context.Context, s *Snapshot, p *Plan) (map[int]bool, error) {
	owner := map[string]int{}
	for n, d := range p.Desired {
		owner[d.Head] = n
		if d.Frozen != "" {
			owner[d.Frozen] = n
		}
	}
	refused := map[int]bool{}
	for _, a := range p.Actions {
		if a.Kind != PushBranches {
			continue
		}
		for name, commit := range a.Refs {
			if n, ok := owner[name]; ok && c.pushGuard(ctx, s.Branch, name, commit) != nil {
				refused[n] = true
			}
		}
		for name, ap := range a.Appends {
			commit := ap.Revision
			if !ap.Force {
				var err error
				if commit, err = c.appendCommit(ctx, ap); err != nil {
					return nil, err
				}
			}
			if c.pushGuard(ctx, s.Branch, name, commit) != nil {
				refused[ap.Change] = true
			}
		}
	}
	return refused, nil
}

func (c *Code) appendCommit(ctx context.Context, a Append) (string, error) {
	out, err := c.Mirror.Git(ctx, nil, "log", "-1", "--format=%T%x00%an%x00%ae%x00%ad", "--date=raw", a.Revision)
	if err != nil {
		return "", err
	}
	f := strings.SplitN(strings.TrimSpace(string(out)), "\x00", 4)
	if len(f) != 4 {
		return "", fmt.Errorf("parsing %s", a.Revision)
	}
	env := []string{"GIT_AUTHOR_NAME=" + f[1], "GIT_AUTHOR_EMAIL=" + f[2], "GIT_AUTHOR_DATE=" + f[3]}
	if c.CommitterName != "" {
		env = append(env, "GIT_COMMITTER_NAME="+c.CommitterName)
	}
	if c.CommitterEmail != "" {
		env = append(env, "GIT_COMMITTER_EMAIL="+c.CommitterEmail)
	}
	link := fmt.Sprintf("%s/%d", c.changeURL(a.Change), a.PatchSet)
	msg := fmt.Sprintf("Patchset %d\n\n%s\n", a.PatchSet, link)
	parents := []string{"-p", a.Onto}
	if a.Merge != "" {
		msg = fmt.Sprintf("Patchset %d, rebased\n\n%s\n", a.PatchSet, link)
		parents = append(parents, "-p", a.Merge)
	}
	if a.KeepMessage {
		// Same message, author and dates: deterministic, so a retry
		// makes the same commit.
		raw, err := c.Mirror.Git(ctx, nil, "log", "-1", "--format=%B%x00%cn%x00%ce%x00%cd", "--date=raw", a.Revision)
		if err != nil {
			return "", err
		}
		g := strings.SplitN(string(raw), "\x00", 4)
		if len(g) != 4 {
			return "", fmt.Errorf("parsing %s", a.Revision)
		}
		msg = g[0]
		env = append(env, "GIT_COMMITTER_NAME="+g[1], "GIT_COMMITTER_EMAIL="+g[2], "GIT_COMMITTER_DATE="+strings.TrimSpace(g[3]))
	}
	commit, err := c.Mirror.GitEnv(ctx, env, []byte(msg), append(append([]string{"commit-tree", f[0]}, parents...), "-F", "-")...)
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(commit)), nil
}

// exported notes that change n's current patch set reached GitHub: for
// Reconcile to hand on (OnExported) once it lets go of the branch, or at
// once outside one.
func (c *Code) exported(ctx context.Context, n int) error {
	if list, ok := ctx.Value(exportedKey{}).(*[]int); ok {
		*list = append(*list, n)
		return nil
	}
	if c.OnExported == nil {
		return nil
	}
	return c.OnExported(ctx, n)
}

// record saves the converged state of every linked change.
func (c *Code) record(ctx context.Context, s *Snapshot, p *Plan, skip *skips) error {
	newRevision := map[int]bool{}
	defer func() {
		for _, n := range sortedKeys(newRevision) {
			if err := c.exported(ctx, n); err != nil {
				c.Logger.Warn("post-export sync failed", "change", n, "err", err)
			}
		}
	}()
	stackOf := map[int]int{}
	for _, st := range s.Stacks {
		for _, n := range st.Numbers() {
			stackOf[n] = st.Number
		}
	}
	var updates []stateUpdate
	for _, n := range sortedKeys(s.Changes) {
		ch := s.Changes[n]
		d := p.Desired[n]
		st := s.State[n]
		if skip.changes[n] {
			continue // not in sync: left out
		}
		if d == nil {
			// Not mirrored (closed or private): remember the status so we
			// stop fetching it.
			if st != nil && st.Version != "" && st.State.Lifecycle != ch.Status {
				updates = append(updates, stateUpdate{n, "Lifecycle " + ch.Status, func(st *state.Change) {
					st.State.Lifecycle = ch.Status
				}})
			}
			continue
		}
		if d.PR == 0 {
			continue
		}
		pr := s.PRs[d.PR]
		if st == nil || st.State.PR != d.PR {
			// Adopted without state, or state lost: relink.
			if err := c.link(ctx, s, n, pr); err != nil {
				return err
			}
		}
		tree, parentTree := c.trees(ctx, ch.Revision)
		updates = append(updates, stateUpdate{n, fmt.Sprintf("Sync patch set %d", ch.PatchSet), func(st *state.Change) {
			st.State.BaseBranch = d.Base
			st.State.Stack = stackOf[d.PR]
			st.State.Lifecycle = ch.Status
			st.State.Title = ch.Subject
			st.State.BodyHash = d.BodyHash
			st.State.ClosedNoticePosted = false
			// Where the PR and the change agree, neither side has news for
			// the other (mirrorPREdits).
			// So do they where the PR shows what the bridge wrote (a
			// description shortened for GitHub, say).
			if pr != nil && (githubText(pr) == gerritText(ch.Message) || (pr.Body == d.Body && strings.TrimSpace(pr.Title) == d.Title)) {
				st.State.SyncedText = hashString(githubText(pr))
			}
			if pr != nil && pr.Draft == ch.WIP {
				st.State.SyncedWIP = wipState(ch.WIP)
			}
			// Commits the bridge built (imports, appends, re-parented
			// exports) are recorded where they are made, with both SHAs.
			// A foreign patch set is not on GitHub even where its tree is
			// (a commit-message edit, say).
			if gh := s.bridgeHead(n, d.Head); gh != "" && !s.Foreign[n] &&
				!slices.ContainsFunc(st.Revisions, func(r state.Revision) bool { return r.GerritSHA == ch.Revision && r.GitHubSHA == gh }) {
				newRevision[n] = true
				st.Revisions = append(st.Revisions, state.Revision{
					PatchSet: ch.PatchSet, GerritSHA: ch.Revision, GitHubSHA: gh,
					Tree: tree, ParentTree: parentTree, At: time.Now(), Vetted: st.State.Origin == "github" || c.GitHubOwned,
					// Exported only as Gerrit's own commit: a head with its
					// tree may be the push an import was made of.
					Exported: gh == ch.Revision,
				})
			}
		}})
	}
	// One push for all: each is a push to Gerrit, which sends every ref
	// the project has first.
	return c.updateStates(ctx, updates)
}

// stateUpdate is a change to make to change n's state, saved with msg.
type stateUpdate struct {
	n   int
	msg string
	f   func(*state.Change)
}

// updateStates is updateState for several changes, saved together
// (Store.SaveAll); on a concurrent write, each again on its own.
func (c *Code) updateStates(ctx context.Context, us []stateUpdate) error {
	cs := map[int]*state.Change{}
	msgs := map[int]string{}
	for _, u := range us {
		if cs[u.n] == nil {
			st, err := c.Store.Load(ctx, u.n)
			if err != nil {
				return err
			}
			cs[u.n] = st
			msgs[u.n] = u.msg
		} else {
			msgs[u.n] += "; " + u.msg
		}
		u.f(cs[u.n])
	}
	err := c.Store.SaveAll(ctx, cs, func(n int) string { return msgs[n] })
	if !errors.Is(err, state.ErrConflict) {
		return err
	}
	for _, u := range us {
		if err := c.updateState(ctx, u.n, u.msg, u.f); err != nil {
			return err
		}
	}
	return nil
}

func (c *Code) trees(ctx context.Context, rev string) (tree, parent string) {
	if out, err := c.Mirror.Git(ctx, nil, "rev-parse", rev+"^{tree}", rev+"^^{tree}"); err == nil {
		f := strings.Fields(string(out))
		if len(f) == 2 {
			return f[0], f[1]
		}
	}
	return "", ""
}

// updateState loads, mutates and saves change n's state, retrying once on
// a concurrent write.
func (c *Code) updateState(ctx context.Context, n int, msg string, f func(*state.Change)) error {
	for try := 0; ; try++ {
		st, err := c.Store.Load(ctx, n)
		if err != nil {
			return err
		}
		f(st)
		err = c.Store.Save(ctx, n, st, msg)
		if errors.Is(err, state.ErrConflict) && try == 0 {
			continue
		}
		return err
	}
}

// BranchLister lists what a full resync must visit: every branch with open
// changes, and every branch the bridge has state for.
type BranchLister struct {
	Gerrit  *gerrit.Client
	Project string
	Store   *state.Store
}

// ResyncKeys implements Lister.
func (l BranchLister) ResyncKeys(ctx context.Context) ([]Key, error) {
	infos, err := l.Gerrit.QueryChanges(ctx, "project:"+gerrit.QueryString(l.Project)+" status:open")
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	var keys []Key
	add := func(b string) {
		if b != "" && !seen[b] {
			seen[b] = true
			keys = append(keys, Key{Branch: b})
		}
	}
	for _, ci := range infos {
		add(ci.Branch)
	}
	for _, b := range l.Store.Branches() {
		add(b)
		// Comments of every mirrored open change.
		for _, n := range l.Store.ChangesOnBranch(b) {
			st, err := l.Store.Load(ctx, n)
			if err != nil {
				return nil, err
			}
			if st.State.PR != 0 && st.State.Lifecycle == "NEW" {
				keys = append(keys, Key{Comments: n})
			}
		}
	}
	return keys, nil
}

func sortedStringKeys[V any](m map[string]V) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

// maySwap refuses what applyOne would not push to a change's PR branch:
// a branch Gerrit owns, or, for a GitHub-born change not merged yet, a
// patch set of someone who may not push to its author's branch
// (markForeign). A merged one lands on the target branch anyway.
func (c *Code) maySwap(ctx context.Context, ch *gerrit.ChangeInfo, rev gerrit.RevisionInfo, st *state.Change, landing map[string]bool) error {
	name := st.State.HeadBranch
	if name == "" || name == ch.Branch || name == c.DefaultBranch {
		return fmt.Errorf("refusing to push to %q, which Gerrit owns", name)
	}
	if _, _, fork := github.SplitHeadKey(name); !fork {
		if owned, err := c.Gerrit.BranchExists(ctx, c.Project, name); err != nil {
			return err
		} else if owned {
			return fmt.Errorf("refusing to push to %s, which Gerrit owns", name)
		}
	}
	if st.State.Origin == "github" && ch.Status != "MERGED" {
		// The one rule (mayReach), not a fifth way of asking it
		// (thirteenth review: this one read only the uploader). No
		// gitHubHas exception: what is pushed is Gerrit's own commit.
		full, err := c.Gerrit.GetChange(ctx, ch.Number, "ALL_REVISIONS", "ALL_COMMITS", "DETAILED_ACCOUNTS")
		if err != nil {
			return err
		}
		owner := ownerPass(c.GitHubOwned, ch.Owner.AccountID, st.State.HeadBranch)
		r := newMemoReader(landingReader{c.belowReader(), landing})
		ok, known, why, err := mayReach(ctx, r, c.pushTrust(), c.BridgeAccount, owner, revisionsByNumber(full), rev.Number, ch.Branch, st)
		if err != nil {
			return err
		}
		if !ok || !known {
			return fmt.Errorf("patch set %d is not the author's, nor a maintainer's (%s)", rev.Number, cmp.Or(why, "its code, or its parents"))
		}
	}
	return nil
}

// landingReader is r, with the commits a submit is about to merge (the
// changes submitted together) read as on the branch: whoever may submit
// has chosen them for it (sixteenth review, a Gerrit-owned regression: a
// PR on another owner's change submitted with it was neither swapped nor
// retargeted).
type landingReader struct {
	belowReader
	landing map[string]bool
}

func (l landingReader) inBranch(ctx context.Context, branch, sha string) (bool, error) {
	if l.landing[sha] {
		return true, nil
	}
	return l.belowReader.inBranch(ctx, branch, sha)
}

// PrepareSubmit readies the PRs of the changes a submit of change n will
// merge, before the bridge submits it (/submit): each PR whose head is
// (or, for a Gerrit-born change, is made) exactly its change's commit
// leaves its stack and is retargeted to the target branch. When
// replication then lands the commits, GitHub shows every PR merged, which
// it only does for PRs based on that branch (design §6.7). Doing it before
// the submit means the bridge never races replication. If the submit
// fails, the next reconcile restores the stack, and the next patch set
// goes on top of Gerrit's commit. The caller holds the branch lock.
func (c *Code) PrepareSubmit(ctx context.Context, n int) error {
	if c.GitHubOwned {
		// Nothing replicates Gerrit's merges to GitHub: GitHub merged it.
		return nil
	}
	together, err := c.Gerrit.SubmittedTogether(ctx, n)
	if err != nil {
		return err
	}
	if len(together) == 0 {
		ch, err := c.Gerrit.GetChange(ctx, n, "CURRENT_REVISION")
		if err != nil {
			return err
		}
		together = []gerrit.ChangeInfo{*ch}
	}
	landing := map[string]bool{}
	for _, ch := range together {
		if ch.CurrentRevision != "" {
			landing[ch.CurrentRevision] = true
		}
	}
	var prs []*github.PullRequest
	unstack := map[int]bool{}
	specs := map[string][]string{} // push URL -> heads to swap for Gerrit's commits
	var fetch []string             // where to fetch those commits from
	for _, ch := range together {
		st, err := c.Store.Load(ctx, ch.Number)
		if err != nil {
			return err
		}
		if st.State.PR == 0 {
			continue
		}
		pr, err := c.GitHub.GetPull(ctx, st.State.PR)
		if err != nil {
			return err
		}
		if pr.State != "open" {
			continue
		}
		rev, ok := ch.Current()
		var last state.Revision
		if len(st.Revisions) > 0 {
			last = st.Revisions[len(st.Revisions)-1]
		}
		switch {
		case pr.Head.SHA == ch.CurrentRevision || !ok:
		case last.GitHubSHA != pr.Head.SHA || (ch.Status != "MERGED" && last.GerritSHA != ch.CurrentRevision):
			// A push not imported yet, never overwritten; or, before the
			// merge, a patch set GitHub never had (someone else's in
			// Gerrit, say), which must not reach the author's branch this
			// way either (fourth audit).
			c.Logger.Warn("PR head is not the patch set being submitted; not swapping it", "change", ch.Number, "pr", pr.Number, "head", pr.Head.SHA)
		default:
			// GitHub's head is the patch sets' history (Gerrit-born) or the
			// commits Gerrit squashed (GitHub-born): swap in Gerrit's
			// commit, which has the same files.
			url, branch := c.GitHubURL, st.State.HeadBranch
			if err := c.maySwap(ctx, &ch, rev, st, landing); err != nil {
				c.Logger.Warn("not swapping it", "change", ch.Number, "pr", pr.Number, "err", err)
				continue
			}
			fork, b, isFork := github.SplitHeadKey(st.State.HeadBranch)
			if isFork {
				if !pr.MaintainerCanModify {
					continue // the author's fork: closed with a notice instead
				}
				url, branch = "https://github.com/"+fork+".git", b
			} else if ch.Status != "MERGED" {
				// Not yet on the branch: the push guard's rule applies.
				if _, err := c.Mirror.Git(ctx, nil, "fetch", "--quiet", "origin", rev.Ref); err != nil {
					return err
				}
				if err := c.pushGuard(ctx, ch.Branch, branch, ch.CurrentRevision); err != nil {
					c.Logger.Warn("not swapping in a commit that changes "+withheldWhat, "change", ch.Number, "pr", pr.Number, "err", err)
					continue
				}
			}
			ref := "refs/heads/" + branch
			specs[url] = append(specs[url], "--force-with-lease="+ref+":"+pr.Head.SHA, ch.CurrentRevision+":"+ref)
			fetch = append(fetch, rev.Ref)
		}
		if pr.Base.Ref == ch.Branch {
			continue
		}
		pr.Base.Ref = ch.Branch // the target, for below
		prs = append(prs, pr)
		if pr.Stack != nil {
			unstack[pr.Stack.Number] = true
		}
	}
	if c.DryRun {
		if len(prs) > 0 {
			c.Logger.Info("dry run: would retarget PRs before submit", "change", n, "prs", len(prs), "swapped_heads", len(fetch))
		}
		return nil
	}
	if len(specs) > 0 {
		if _, err := c.Mirror.Git(ctx, nil, append([]string{"fetch", "--quiet", "origin"}, fetch...)...); err != nil {
			return err
		}
		env, err := c.githubEnv(ctx)
		if err != nil {
			return err
		}
		for _, url := range sortedStringKeys(specs) {
			args := append([]string{"push", "--porcelain", "--atomic", url}, specs[url]...)
			if out, err := c.Mirror.GitEnv(ctx, env, nil, args...); err != nil {
				return fmt.Errorf("swapping in Gerrit's commits before submit: %w\n%s", err, out)
			}
		}
		c.Logger.Info("swapped PR heads for Gerrit's commits before submit", "change", n, "heads", len(fetch))
	}
	for _, sn := range sortedKeys(unstack) {
		if err := c.GitHub.Unstack(ctx, sn); err != nil && !github.IsNotFound(err) {
			return err
		}
	}
	for _, pr := range prs {
		if _, err := c.GitHub.UpdatePull(ctx, pr.Number, github.PullUpdate{Base: ptr(pr.Base.Ref)}); err != nil {
			return fmt.Errorf("retargeting #%d: %w", pr.Number, err)
		}
		c.Logger.Info("retargeted PR before submit", "change", n, "pr", pr.Number, "base", pr.Base.Ref)
	}
	return nil
}
